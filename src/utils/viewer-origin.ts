// ORIGIN, КОТОРЫЙ УЕДЕТ НА БУМАГУ И ОСТАНЕТСЯ ТАМ НАВСЕГДА.
//
// window.location.origin — это адрес вкладки, из которой нажали «save as pdf», а не адрес
// продукта. Напечатать документ из превью Vercel (штатный способ смотреть бету) значит зашить в
// каждый QR эфемерный алиас превью: он живёт за Deployment Protection, то есть встречает швею
// SSO-стеной, и умирает при переименовании ветки. Ни печать, ни QR, ни вьюер при этом не
// ломаются — бумага просто перестаёт работать через месяц, молча.
//
// Поэтому origin берётся из окружения деплоя (у бэкенда ровно это и есть PatternToken.
// PublicBaseURL), а window.location.origin остаётся ТОЛЬКО как локальный запасной вариант.
//
// ОДНА ПЕРЕМЕННАЯ НА ВСЕ ПУБЛИЧНЫЕ ВЬЮЕРЫ, и это решение, а не лень. Тех-пак печатает QR вьюера
// выкроек (/p/{token}), наряд на партию — QR вьюера наряда (/r/{token}); обе страницы живут на
// ОДНОМ И ТОМ ЖЕ хосте админки, потому что это одна SPA. Вторая переменная не добавила бы ни одной
// достижимой конфигурации, зато добавила бы вторую строку в спеку деплоя, которую забудут выставить
// — и тогда наряд печатался бы с эфемерным origin'ом ровно так, как описано выше, но уже молча и
// в отдельном контуре. Имя VITE_PATTERN_VIEWER_ORIGIN осталось историческим (оно старше наряда):
// переименование стоило бы синхронного апдейта .do/Vercel обоих контуров, а неверная переменная
// здесь не падает, а тихо печатает мёртвую бумагу.
export const viewerOrigin = (): string => {
  const configured = (import.meta.env.VITE_PATTERN_VIEWER_ORIGIN as string | undefined)?.trim();
  if (configured) return configured.replace(/\/$/, '');
  return window.location.origin;
};
