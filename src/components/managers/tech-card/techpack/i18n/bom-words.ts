const localeKey = (locale: PdfLocale): PdfLang => (locale === 'xx' ? 'en' : locale);

export function bomWord(value: string | undefined, translate: PdfT): string | undefined {
  const words = value ? BOM_WORDS[value] : undefined;
  return words?.[WORD_INDEX[localeKey(pdfLocaleOf(translate))]];
}

export const BOM_WORD_VALUES = Object.freeze(Object.keys(BOM_WORDS));
