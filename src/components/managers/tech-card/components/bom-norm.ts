import { common_TechCardColorwayUsage } from 'api/proto-http/admin';
import { wireInt } from './wire-int';

// НОРМА СЛОТА — КАКИЕ СТРОКИ РЕЦЕПТА ЕЙ ВООБЩЕ ПРИНАДЛЕЖАТ.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ХЕЛПЕР В ЭКРАНЕ. Этот вопрос задавали ДВЕ поверхности, каждая своей
// копией, и копии разошлись — не в слове, как все прочие расхождения этой волны, а В ЧИСЛЕ,
// ПО КОТОРОМУ ЗАКУПАЮТ. Панель редактора отбрасывала строки рецепта, привязанные к ДЕТАЛИ; печатный
// лист их считал. Поэтому «+15 %» появлялся на спецификации у слотов, у которых в редакторе никакой
// надбавки не стояло, и закупка по бумаге расходилась с закупкой по экрану, молча и в пользу
// бумаги — той самой копии, которую никто не сверяет.
//
// ПРАВ БЫЛ ЭКРАН, И ЭТО НЕ ВКУСОВОЕ РЕШЕНИЕ. Сервер держит правило одним именованным предикатом
// (`entity.IsPieceMaterialAssignment`), и строка, привязанная к детали, исключена из ВСЕХ
// норм-роллапов: стоимости колорвея, оценки себестоимости модели, ПЛАНА МАТЕРИАЛОВ ПРОГОНА,
// готовности прогона и замороженных релизных стоимостей. «A piece-bound row has no norm-money»
// (T8). Строка, привязанная к детали, — это НАЗНАЧЕНИЕ МАТЕРИАЛА («эта деталь из этой ткани»), а не
// норма: расхода у неё нет, и гросс-апу нечего умножать. Обоснование, стоявшее у листа, описывало
// сервер ДО T8 и снято как устаревшее, а не перенесено сюда.
//
// ДВА РАЗНЫХ МНОЖИТЕЛЯ, И ИХ НЕЛЬЗЯ ПУТАТЬ. Серверный `wastageApplies` — это про ИСТОЧНИК
// (`consumption_source != marker`) и про детали не говорит вовсе; про детали решает
// `IsPieceMaterialAssignment`. А процент раскроя и коэффициент раскроя артикула — вообще два разных
// множителя: коэффициент применяется независимо от источника, включая марочную строку. Кто прочтёт
// «процент не берётся» как «гросс-апа нет», выключит вместе с процентом и рулон.

/** Одна строка рецепта, ПОПАВШАЯ в норму слота (привязанные к детали сюда не доезжают). */
export type SlotNormRow = {
  /** Колорвей, чей это рецепт, — коротким именем, для строки «у кого именно». */
  sku: string;
  /**
   * Норма СНЯТА С РАСКЛАДКИ. Процент раскроя такой строке не начисляется: измеренная длина отходы
   * уже содержит, и надбавка поверх неё посчитала бы их дважды (серверный `wastageApplies`).
   */
  marker: boolean;
  /**
   * МЕРНАЯ строка — та, у которой есть РАСХОД, а не количество штук. Ровно по этому признаку сервер
   * решает, начислять ли гросс-ап вообще: счётную строку отсекает ранний возврат `LineTotal`
   * («4 пуговицы остаются 4 пуговицами»).
   */
  measured: boolean;
};

/**
 * Строки рецепта этого слота — по всем колорвеям карточки.
 *
 * ЧИТАЕТСЯ ЖИВОЙ РЕЦЕПТ (`colorways[].usages`), а не форма: рецепт колорвея живёт своим RPC и в
 * состоянии формы карточки не лежит вовсе.
 *
 * СОПОСТАВЛЕНИЕ ПО `bom_item_id`: чтение не эмитит `bom_line_key` на строке рецепта вовсе
 * (`ConvertRecipeUsagesToPb`), ключ оставлен запасным на случай, когда однажды начнёт.
 *
 * ТИПИЗИРОВАН СТРУКТУРНО — ровно по тем полям, которые читает, — чтобы его удовлетворяли обе формы
 * колорвея разом: и `common_AdminColorwayRef` живого чтения, и та, что доезжает до печатного листа.
 */
export function slotNormRows(
  colorways:
    | ReadonlyArray<{
        colorwayId?: number | undefined;
        baseSku?: string | undefined;
        colorCode?: string | undefined;
        usages?: common_TechCardColorwayUsage[] | undefined;
      }>
    | undefined,
  bomItemId: number,
  lineKey: string,
): SlotNormRow[] {
  const rows: SlotNormRow[] = [];
  const key = (lineKey ?? '').trim();
  for (const c of colorways ?? []) {
    for (const u of c.usages ?? []) {
      const mine =
        (bomItemId > 0 && wireInt(u.bomItemId) === bomItemId) ||
        (key !== '' && !!u.bomLineKey && u.bomLineKey.trim() === key);
      if (!mine) continue;
      // НАЗНАЧЕНИЕ МАТЕРИАЛА, А НЕ НОРМА (T8) — см. шапку модуля.
      if ((u.pieceLineKey ?? '').trim() || wireInt(u.pieceId) > 0) continue;
      rows.push({
        sku: c.baseSku?.trim() || c.colorCode?.trim() || `#${c.colorwayId ?? 0}`,
        marker: (u.consumptionSource ?? '').trim() === 'marker',
        measured: !!u.consumption?.value?.trim() || (u.sizeConsumptions?.length ?? 0) > 0,
      });
    }
  }
  return rows;
}

/**
 * БЕРЁТ ЛИ СЛОТ ПРОЦЕНТ РАСКРОЯ — есть ли у него ХОТЬ ОДНА мерная и не марочная строка нормы.
 *
 * Печатать процент там, где его никто не берёт, — это отправить на фабрику число, которое там
 * некому опровергнуть: «+15 %» рядом с пуговицами читается как указание к закупке.
 */
export const slotTakesWastage = (rows: readonly SlotNormRow[]): boolean =>
  rows.some((r) => r.measured && !r.marker);
