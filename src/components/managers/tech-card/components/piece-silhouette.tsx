// Жил приватно в рецепте колорвея, пока имя детали печаталось в одном месте. Теперь его печатает и
// сборка — тарелка деталей, чипы шага, строка рельса, — а глиф, скопированный во второй файл,
// разошёлся бы с оригиналом молча: тот же сорт «почти одинакового», от которого заведены
// piece-block-refs.ts и card-dxf-pack.ts. Контур сюда приходит уже НАЙДЕННЫМ (usePieceShapes), так
// что этот файл отвечает ровно за одно: как деталь выглядит рядом со своим именем.
import { cn } from 'lib/utility';
import { fmtCm, PieceShape, type FoundPiece } from './nesting/dxf-geometry';

/**
 * Силуэт детали при её имени: форма из ЧЕРТЕЖА, не пиктограмма — рисуется тем же контуром
 * (findPiece: срединный размер ряда, слой линии кроя с фолбэком), что и плитка этой детали на
 * вкладке деталей кроя. Подпись обязательна, иначе это декорация: title называет блок, размер, по
 * которому нарисовано (силуэт один на всю градацию), и габарит. Нет контура — нет и спана, даже
 * пустого: прочерк перед каждой несопоставленной деталью — шум, а диагностика («нет в файлах»,
 * «ткань потеряна») живёт на вкладке деталей кроя.
 *
 * `boxClassName` задаёт бокс поверх дефолтных 28×40 (и, через tailwind-merge, его отступ): строка
 * рецепта берёт дефолт, а чип и строка рельса просят меньше — вырасти в высоту им нельзя, иначе
 * полоса, которую оператор читает как ровный список, перестраивается ради картинки.
 */
export function PieceSilhouette({
  found,
  boxClassName,
}: {
  found: FoundPiece | null;
  boxClassName?: string;
}) {
  if (!found) return null;
  const size = found.size
    ? `размер ${found.size}${found.sizes.length > 1 ? ` из ${found.sizes.length}` : ''}`
    : '';
  const title = [found.block, size, `${fmtCm(found.piece.bboxW)}×${fmtCm(found.piece.bboxH)} см`]
    .filter(Boolean)
    .join(' · ');
  // Без рамки (глиф при имени, не контрол); grainLayer='' гасит красную долевую — на 28px она
  // читалась бы как цвет состояния, а красный в системе — только ошибка; outlineOnly гасит
  // внутреннюю геометрию, нечитаемую в этом размере. SVG letterbox-ится в бокс сам (meet).
  return (
    <span title={title} className={cn('mr-1.5 inline-flex h-7 w-10 shrink-0', boxClassName)}>
      <PieceShape piece={found.piece} grainLayer='' outlineOnly />
    </span>
  );
}
