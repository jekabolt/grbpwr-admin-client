// ── МОЖНО ЛИ ВООБЩЕ ПУБЛИКОВАТЬ ПЛОЩАДИ ПРЯМО СЕЙЧАС ───────────────────────────────────────────
//
// Правило живёт ЗДЕСЬ, рядом с самой публикацией, потому что точек входа у неё ДВЕ — замер площадей
// на вкладке выкроек и применение нормы «по выкройкам», — и обе обязаны спрашивать одно и то же.
// Одна проверка на два места: разойдись они, дыру закрыли бы наполовину, а комментарий у закрытой
// половины утверждал бы, что закрыта вся.
//
// ЧТО ИМЕННО ЛОМАЕТСЯ БЕЗ НЕЁ. Выкройки и связи блок→деталь правятся В ФОРМЕ (piece-match-modal
// пишет setValue), а полноту присланного комплекта сервер доказывает против СВОИХ, сохранённых
// связей. Отсюда два живых сценария, и второй хуже первого:
//   1. связи созданы и не сохранены — сервер отвечает «у скоупа нет связей блок→деталь» про набор,
//      который оператор видит связанным, и читает это как поломку;
//   2. деталь ПЕРЕПРИВЯЗАНА в форме к другому блоку, а состав деталей не изменился — тогда
//      серверная сверка «в обе стороны» проходит против СТАРЫХ связей, и площади, снятые с
//      геометрии, которой сохранённая карточка не заявляет, записываются МОЛЧА. Отказаться от
//      правок формы после этого — значит остаться с неверными площадями без единого следа.
//
// Поэтому ответ один: пока источник правлен и не сохранён, публиковать нельзя ничем.
//
// ТРЕТИЙ ИСТОЧНИК — ГАЛКА «НЕ ГРАДУИРУЕТСЯ». Она решает, СКОЛЬКО строк площадей у детали бывает:
// у помеченной — одна общая на весь ряд, и пер-размерные строки сервер отвергает (0302). Значит её
// правка меняет форму самого замера, а не только число, — и опубликовать замер, снятый до ответа,
// значит записать набор строк, которого сохранённая карточка не заявляет.
//
// Следят РОВНО ЗА НЕЙ, а не за `dirtyFields.pieces` целиком: имя, заметка и количество на изделие
// к геометрии отношения не имеют, и «правил имя детали» замораживало бы публикацию площадей на
// ровном месте — то есть отказывало бы там, где отказывать не за что.
export function useUnsavedAreaSource(control: Control<TechCardFormData>): boolean {
  const { dirtyFields } = useFormState({
    control,
    name: ['patterns', 'pieceDxfAliases', 'pieces'],
  });
  // Спрашивается ЗНАЧЕНИЕ, а не наличие ключа: у массивов RHF заводит запись сразу и кладёт в неё
  // пустой массив или объект из `false`, так что `!!dirtyFields.patterns` был бы вечной «правкой».
  const anyDirty = (v: unknown): boolean =>
    Array.isArray(v)
      ? v.some(anyDirty)
      : v !== null && typeof v === 'object'
        ? Object.values(v as Record<string, unknown>).some(anyDirty)
        : v === true;
  return (
    anyDirty(dirtyFields.patterns) ||
    anyDirty(dirtyFields.pieceDxfAliases) ||
    (dirtyFields.pieces ?? []).some((p) => p?.ungraded === true)
  );
}

// ПУБЛИКАЦИЯ ПЛОЩАДЕЙ ДЕТАЛЕЙ (Ф0, 0297) — то, из чего сервер выводит норму расхода сам.
//
// ЗАЧЕМ ЭТО ВООБЩЕ ЕДЕТ НА СЕРВЕР. Карточка может быть заполнена целиком — спецификация с ценами,
// разобранные выкройки, назначение каждой детали на ткань в рецепте — и всё равно стоить НОЛЬ:
// деньги считает только строка рецепта с явно вписанной нормой, а строка, привязанная к детали,
// нормы не несёт (T8). Не хватало ровно площади, и существовала она только здесь, в памяти
// вкладки, потому что DXF разбирает браузер и только браузер.
//
// ЧТО ЕДЕТ: площадь ОДНОГО ЭКЗЕМПЛЯРА контура. Количество на изделие живёт на детали, меняется
// отдельной правкой карточки и к геометрии файла отношения не имеет — умножает читатель. Отправить
// уже умноженное значило бы записать кратность внутрь геометрии и получить число, которое молча
// врёт после первой же правки «этой детали идёт две».
//
// ЧТО НЕ ЕДЕТ: отпечаток набора листов. Его считает СЕРВЕР по своим строкам, и именно поэтому
// заявить покрытие по файлам, которых нет, отсюда нельзя, а перезаливка любого листа делает площади
// устаревшими сама, без чьего-либо участия.

export type PublishPieceAreasResult = { ok: true; stored: number } | { ok: false; reason: string };

/** Лист выкройки в терминах публикации: сырая привязка и стабильный ключ строки. */
export type PieceAreaSheet = { lineKey?: string; fabricPurpose?: string; bomLineKey?: string };

/**
 * ЛИСТЫ, ПО КОТОРЫМ МЕРИЛИ, И СКОУП, ПОД КОТОРЫМ ПИШЕМ, ДОЛЖНЫ БЫТЬ ОДНИМ И ТЕМ ЖЕ. Причина отказа
 * либо `null`.
 *
 * Здесь встречаются ДВА разных ответа на вопрос «чья это ткань», и их несовпадение — не мелочь:
 *
 *   • РАЗРЕШЁННЫЙ скоуп (то, по чему сгруппированы файлы и по чему считалась геометрия): лист,
 *     привязанный к строке L, принадлежит назначению P, если L разложена в P;
 *   • СЫРОЙ скоуп сервера (`entity.FabricScopeKey`): тот же лист лежит в скоупе L, потому что
 *     сервер смотрит на само поле, а не на сегодняшний BOM.
 *
 * Пока карточка разложена целиком, оба ответа совпадают. На ПОЛУразобранной — нет, и тогда прежний
 * код просто отфильтровывал «чужие» листы и публиковал остаток: геометрия бралась с обоих, а
 * отпечаток отвечал за один. Перезалив «невидимый» лист, оператор менял площади и НЕ делал замер
 * устаревшим — то есть получал молча неверную себестоимость, ровно ту, ради предотвращения которой
 * отпечаток и считает сервер.
 *
 * Второе следствие того же: слот, разложенный в назначение, ищет площади под ключом назначения.
 * Замер, записанный под ключом строки, он не найдёт НИКОГДА — запись «удалась» и не значит ничего.
 *
 * Поэтому правило одно на оба входа в замер: все листы этой ткани обязаны сырьём указывать на тот
 * же скоуп, под которым мы пишем; иначе отказ с адресом починки.
 */
export function pieceAreaSheetsRefusal(
  sheets: readonly PieceAreaSheet[],
  scopeKey: string,
): string | null {
  const key = scopeKey.trim();
  if (!key) return 'не определён скоуп ткани';
  if (sheets.length === 0) return 'у этой ткани нет листов выкроек';
  const keys = new Set(sheets.map(serverScopeKeyOfSheet));
  if (keys.size > 1) {
    return 'листы этой ткани привязаны по-разному: часть — к назначению, часть — к строке BOM. Сервер хранит их в РАЗНЫХ скоупах, и замер отвечал бы за файлы, которых в его скоупе нет. Допривяжите листы к назначению (кнопка «⇄» в строке листа)';
  }
  const only = [...keys][0] ?? '';
  if (!only) {
    return 'листы этой ткани не несут привязки к материалу — площадям не на чем висеть. Выберите материал в строке листа («⇄»)';
  }
  if (only !== key) {
    return `листы этой ткани привязаны к строке BOM, а сама ткань разложена в назначение: сервер сложит замер в скоуп «${only}», а слот будет искать его в «${key}» — и не найдёт. Допривяжите листы к назначению (кнопка «⇄» в строке листа)`;
  }
  if (sheets.some((sh) => !(sh.lineKey ?? '').trim())) {
    return 'у части листов ещё нет идентификатора — сохраните карточку и повторите замер';
  }
  return null;
}

/**
 * РЯД РАЗМЕРОВ, ПО КОТОРОМУ МЕРИЛИ, И РЯД, КОТОРЫЙ КАРТОЧКА ЗАЯВЛЯЕТ НА СЕРВЕРЕ, ДОЛЖНЫ БЫТЬ ОДНИМ
 * И ТЕМ ЖЕ. Причина отказа либо `null`.
 *
 * Замер идёт ПО РЯДУ ФОРМЫ (строка на каждый размер каждой градуируемой детали), а принимает его
 * сервер против СВОЕГО ряда — строк tech_card_size. Разойтись они могут без единой осознанной
 * правки: «↔ детали кроя» заводит найденные в чертеже размеры в ряд карточки САМА, молча и через
 * setValue, — то есть ряд в форме растёт от простого открытия модалки сопоставления, а на сервер
 * уезжает только вместе с сохранением карточки.
 *
 * Что происходит без этой проверки — ровно то, что и произошло: замер уходит с размером, которого
 * сервер не знает, и весь скоуп отвергается полем `size_not_in_range`. Отказ приходит на английском,
 * называет ULID детали (а виноват размер) и ни словом не говорит про несохранённую карточку —
 * прочесть его как «сохрани карточку» невозможно, и вкладка выглядит сломанной.
 *
 * ОТКАЗ, А НЕ ТИХОЕ СУЖЕНИЕ ДО СОХРАНЁННОГО РЯДА. Померить «только те размеры, что сервер знает»
 * значило бы записать комплект, который сервер примет как полный, — а после сохранения карточки ряд
 * вырастет, и у нового размера площадей не окажется. Заниженная площадь занижает норму, и
 * обнаруживается это на складе, а не на экране: та же арифметика, из-за которой сервер и сверяет
 * комплект в обе стороны.
 *
 * ПРОВЕРКА СИММЕТРИЧНА. Ряд формы, который УЖЕ сервера (размер убрали и не сохранили; форма
 * устарела, потому что ряд правили в другой вкладке), тоже отвергается: у ГРАДУИРУЕМОЙ детали
 * сервер требует строку на каждый размер СВОЕГО ряда и ответил бы `size_set_incomplete`, столь же
 * нечитаемым.
 *
 * …НО ТОЛЬКО ЕСЛИ ЗАМЕР ВООБЩЕ ГОВОРИТ О РАЗМЕРАХ, и это не оговорка, а условие честности проверки.
 * Скоуп, где НИ ОДНА деталь не градуируется, отдаёт строки с размером 0 — «деталь входит в каждый
 * размер целиком», — и ряд карточки для такого замера не предмет разговора вовсе: сервер примет его
 * при любом ряде. Отказать там значило бы придумать препятствие: расхождение есть, а сломать оно
 * ничего не может. (Такой скоуп проходит `dxfNormAreas` только при ряде из ОДНОГО размера — на
 * большем она сама отказывает, — так что случай узкий, но живой: ряд сузили в форме и не сохранили.)
 *
 * `savedSizeIds === undefined` — серверного ряда нет на руках (карточки нет в кэше, ответ без неё);
 * сравнивать не с чем, проверка молчит, остаётся серверная. Пустой массив — это ЗНАНИЕ («ряд не
 * заведён»), а не незнание.
 *
 * ЧЕГО ПРОВЕРКА НЕ ЛОВИТ И НЕ МОЖЕТ. Серверный ряд здесь — СНИМОК чтения карточки. Если ряд правил
 * кто-то другой уже после него, оба списка совпадут и замер всё равно упрётся в сервер; а сразу
 * после сохранения, если дочитывание карточки сорвалось, они на несколько секунд разойдутся в
 * обратную сторону и отказ будет лишним. Оба состояния лечит перечитывание карточки, и текст отказа
 * называет его вторым действием именно поэтому.
 *
 * ЗОВЁТ ЕЁ ОДИН ВХОД ИЗ ДВУХ, и это не забытая половина. Второй вход — применение нормы «по
 * выкройкам» — живёт в рецепте колорвея, а рецепт берёт ряд размеров с СЕРВЕРА
 * (`techCard.techCard.sizeIds`, colorway-recipe.tsx), а не из формы: расходиться там нечему. Гейт
 * на листы общий именно потому, что там оба входа отвечают за один набор файлов; здесь — не так.
 */
export function pieceAreaSizeRangeRefusal(
  formSizeIds: readonly number[],
  savedSizeIds: readonly number[] | undefined,
  nameOfSize: (sizeId: number) => string,
  /**
   * Строки замера — те самые, что уедут на сервер. Ряд карточки проверяется только когда среди них
   * есть хоть одна С РАЗМЕРОМ: набор из одних безразмерных строк сервер принимает при любом ряде.
   */
  rows: readonly { sizeId: number }[],
): string | null {
  if (savedSizeIds == null) return null;
  if (!rows.some((r) => r.sizeId > 0)) return null;
  const saved = new Set(savedSizeIds);
  const form = new Set(formSizeIds);
  const added = [...form].filter((id) => !saved.has(id));
  const dropped = [...saved].filter((id) => !form.has(id));
  if (added.length === 0 && dropped.length === 0) return null;
  const parts: string[] = [];
  if (added.length > 0) {
    parts.push(`в форме есть, на сервере нет: ${added.map(nameOfSize).join(', ')}`);
  }
  if (dropped.length > 0) {
    parts.push(`на сервере есть, в форме убраны: ${dropped.map(nameOfSize).join(', ')}`);
  }
  return `размерный ряд формы разошёлся с сохранённым (${parts.join('; ')}). Замер идёт по ряду формы, а принимает его сервер по своему — и отвергнет весь скоуп. Сохраните карточку (ряд из чертежа модалка «↔ детали кроя» добавляет в форму сама) либо перечитайте её, если ряд правили не вы, — и повторите замер`;
}

// НИЖНЯЯ ГРАНИЦА ПЛОЩАДИ НА ПРОВОДЕ. На провод число уходит с двумя знаками, а колонка держит
// CHECK area_cm2 > 0: 0.004 см² превращается в «0.00» и роняет ВЕСЬ замер одной строкой, причём
// сообщением про ограничение БД, в котором нет ни детали, ни размера. Проверяем сами и называем
// виновника — это единственное место, где ещё известно, кто он.
const MIN_WIRE_AREA_CM2 = 0.005;

/**
 * Публикует площади ОДНОГО скоупа ткани.
 *
 * Возвращает результат, а не бросает: замер — это то, что вкладка уже посчитала и показала. Сорванная
 * публикация не имеет права выглядеть как провал самого разбора.
 *
 * КОМПЛЕКТ ОБЯЗАН БЫТЬ ПОЛНЫМ, и проверяет это сервер: он сверяет присланные детали с привязками
 * блоков своего скоупа в обе стороны. Недостающая деталь занижает площадь изделия, заниженная
 * площадь занижает норму, и обнаруживается это на складе, а не на экране. Поэтому здесь нет и не
 * должно быть «отправим что нашлось» — и по той же причине отсюда ушла ТИХАЯ ФИЛЬТРАЦИЯ строк с
 * непригодной площадью: выбросить такую строку значило бы объявить неполный набор полным.
 */
export async function publishPieceAreas(args: {
  techCardId: number;
  scopeKey: string;
  /**
   * ВСЕ листы этой ткани (любого формата, включая наследие в PDF): именно из них сервер считает
   * отпечаток скоупа, и прислать подмножество значит подписаться под чужим набором.
   */
  sheets: PieceAreaSheet[];
  /**
   * Строки замера, как их посчитал `dxfNormAreas` — вместе с признаками «оболочка» и
   * «неоднозначный выбор» НА САМОЙ СТРОКЕ. Раньше признаки приходили сюда двумя отдельными
   * множествами имён, а искались в них по line_key детали, — то есть не находились никогда, и
   * сервер получал два нуля вместо провенанса замера.
   */
  areas: DxfPieceAreaRow[];
  contourLayer: string;
  seamAllowanceMm: number;
  /** Имя детали по её line_key — чтобы отказ называл деталь, а не ULID. */
  nameOfPiece?: (pieceLineKey: string) => string;
}): Promise<PublishPieceAreasResult> {
  const scopeKey = args.scopeKey.trim();
  const sheetsRefusal = pieceAreaSheetsRefusal(args.sheets, scopeKey);
  if (sheetsRefusal) return { ok: false, reason: sheetsRefusal };
  const rows = args.areas;
  if (rows.length === 0) {
    return {
      ok: false,
      reason:
        'разбор не дал ни одной площади — проверьте слой контура и связи блоков с деталями',
    };
  }
  const named = (key: string) => args.nameOfPiece?.(key) || key;
  const unaddressed = rows.filter((a) => !(a.pieceLineKey ?? '').trim());
  if (unaddressed.length > 0) {
    return {
      ok: false,
      reason: `${unaddressed.length} деталей ещё не сохранены на сервере — площадь ложится на деталь по её ключу, а его пока нет. Сохраните карточку и повторите замер`,
    };
  }
  const tooSmall = rows.filter((a) => !(a.areaCm2 >= MIN_WIRE_AREA_CM2));
  if (tooSmall.length > 0) {
    return {
      ok: false,
      reason: `площадь этих деталей нулевая или меньше сотой доли см²: ${[
        ...new Set(tooSmall.map((a) => named(a.pieceLineKey))),
      ].join(', ')} — на проводе она станет нулём, которого не примет ни сервер, ни здравый смысл. Похоже, выбран не тот слой контура`,
    };
  }
  const sheetLineKeys = args.sheets.map((sh) => (sh.lineKey ?? '').trim()).filter(Boolean);
  try {
    const res = await adminService.SaveTechCardPieceAreas({
      techCardId: args.techCardId,
      scopeKey,
      sheetLineKeys,
      contourLayer: args.contourLayer,
      seamAllowanceMm: { value: String(args.seamAllowanceMm) },
      areas: rows.map((a) => ({
        pieceLineKey: a.pieceLineKey,
        sizeId: a.sizeId,
        areaCm2: { value: a.areaCm2.toFixed(2) },
        // Периметр (0305) — вторая мера того же контура, тем же масштабом, что и площадь: сервер
        // округляет до сотых при сравнении «тот же ли это замер», и присланное с большей точностью
        // вечно читалось бы как изменение, переписывая провенанс на каждом повторе.
        perimeterCm: { value: a.perimeterCm.toFixed(2) },
        hulled: a.hulled,
        ambiguousPick: a.ambiguousPick,
      })),
    });
    return { ok: true, stored: Number(res?.stored ?? rows.length) };
  } catch (e) {
    const violations = extractFieldViolations(e);
    const first = violations.length > 0 ? violations[0].description : "";
    return { ok: false, reason: first || 'сервер не принял замер площадей' };
  }
}
