// ЕДИНСТВЕННЫЙ ВХОД КАРТОЧКИ В МАНИФЕСТ КОНВЕРТАЦИИ (F6b, 08-CONTRACT §3.1).
//
// Каждое поведение, которое меняется от манифеста, спрашивает его ЗДЕСЬ и только здесь: размер и
// идентичность блока (split-pieces, use-block-sizes, size-areas-from-dxf), слой кроя и припуск в нём
// (contour-layer), долевая (grain), пара и развёрнутый сгиб (piece-match-modal). Деталь без манифеста
// получает null — и каждый из этих путей идёт ровно той веткой, которой шёл до F6b.
//
// Одна точка — не ради красоты. Через неё проверяется, что манифест ничего не меняет у файлов, которые
// его не несут: зонд F6b (scripts/pattern-import/f6b.mjs) подменяет ЭТУ функцию на «доверять всем» и
// требует, чтобы регрессия по старым файлам покраснела. Ворота, размазанные по десятку `p.manifest`,
// так не проверишь — и однажды одни из них откроются молча.
import type { PieceDTO, PieceManifestFacts } from 'lib/nesting/types';

export function manifestFactsOf(p: PieceDTO): PieceManifestFacts | null {
  return p.manifest ?? null;
}
