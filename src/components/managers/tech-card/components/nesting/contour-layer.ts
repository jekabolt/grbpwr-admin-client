// Какой слой DXF несёт саму деталь.
//
// Блок обычно содержит контур ДВАЖДЫ: линию шва и линию кроя на разных слоях. Внутри одного
// блока их не различить — оба замкнуты, оба похожи на деталь. Различает их градация: настоящая
// деталь МЕНЯЕТСЯ от размера к размеру, а справочный контур — нет.
//
// Замерено на реальном файле лекальщика (summer men.dxf):
//   слой 1:  BP 52.1×18.5 во ВСЕХ пяти размерах; FP_R 32.2×74.4 во всех; SL_R 47.8×34.2 во всех
//   слой 14: BP XS 47.9×15.2 → XL 51.9×17.2; FP_R 28.4×70.5 → 32.0×73.7 (ровный шаг градации)
// Слой 1 там оказался линией кроя БАЗОВОГО размера, выгруженной без градации, а прежний парсер
// предпочитал именно его — отчего BP_S и BP_M выходили с одинаковым габаритом.
//
// Отсюда правило: слой тем правдоподобнее, чем на большем числе деталей его габарит меняется
// между размерами. Ни одного размера сравнить не с чем — правило молчит и решает запасной
// порядок, а не выдумка.
//
// ГРАДАЦИЯ ОТВЕЧАЕТ НЕ НА ТОТ ВОПРОС, КОТОРЫЙ ЗАДАЁТ ОПЕРАТОР (Ф3.4). Она ранжирует
// правдоподобие («который из слоёв — настоящая деталь»), но не говорит, ЧТО именно на выбранном
// слое лежит: линия шва, которую раскладка обязана раздуть припуском, или линия кроя, в которую
// припуск уже вложен лекальщиком. Второе спрашивается замером (`contour-allowance.ts`) и
// приезжает сюда ОТДЕЛЬНЫМ полем — ранжирование от этого не меняется НИ НА СТРОКУ. Так и надо:
// правило «по градации» уже ставит линию шва первой, а замер добавляется как подпись к выбору, а
// не как второй судья над ним.
import type { PieceDTO } from 'lib/nesting/types';

import { clampSeamAllowanceMm, engineCmToMm, MAX_SEAM_ALLOWANCE_MM } from './allowance-units';
import {
  measureContourAllowance,
  type AllowanceIndex,
  type ContourAllowance,
} from './contour-allowance';

export type LayerOption = {
  layer: string;
  // Сколько деталей этот слой даёт вообще.
  pieces: number;
  // На скольких идентичностях (деталь без размерного хвоста) слой ГРАДУИРУЕТСЯ, и на скольких
  // его можно было проверить. graded === 0 при checked > 0 — это справочный контур.
  graded: number;
  checked: number;
  // ЗАМЕР ПРИПУСКА, УЖЕ ЛЕЖАЩЕГО В КОНТУРЕ ЭТОГО СЛОЯ (Ф3.3, спека §5.2). Весь разбор — вердикт,
  // число, история выборки и статистика отказов — лежит здесь целиком, чтобы подпись в списке и
  // отказ «двойной припуск» читали ОДНО И ТО ЖЕ, а не два похожих числа из разных мест.
  //
  // `null` значит «НЕ МЕРИЛИ» — вызывающий не передал индекс. Это НЕ то же самое, что
  // `verdict: 'unknown'` («мерили, улик не нашлось»), и путать их нельзя ровно там же, где
  // нельзя путать ноль с отсутствием: одному лечение «передайте индекс», другому — «файл такой».
  allowance: ContourAllowance | null;
  // То же число плоско: сколько припуска в контуре, см. `null` в ОБОИХ случаях «числа нет» — и
  // когда не мерили, и когда не смогли. НОЛЬ ЗДЕСЬ ИЗМЕРЕН и значит «на слое линия шва».
  allowanceCm: number | null;
  // Замер ДАЛ ВЕРДИКТ (крой или шов). false — либо не мерили вовсе, либо улик не нашлось; обе
  // ветки обязаны звучать как «не измерено», а не как «ноль».
  sampled: boolean;
};

// Габарит с точностью до 0.5 мм: градация мельче этого не бывает, а дребезг тесселяции бывает.
const dim = (p: PieceDTO) => `${Math.round(p.bboxW * 20)}x${Math.round(p.bboxH * 20)}`;

export function layerOptions(
  pieces: readonly PieceDTO[],
  // Идентичность детали (имя блока без размера) и размер — по id детали.
  codeById: ReadonlyMap<number, { identity: string; size: string }>,
  // ЗАМЕР ПРИПУСКА — по желанию вызывающего и ГОТОВЫМ ИНДЕКСОМ, а не флагом.
  //
  // Индекс строится по ПОЛНОМУ разбору (`buildAllowanceIndex`) и держит кеш уже посчитанных пар:
  // пара «слой 1 ↔ слой 14» внутри блока ОДНА, и оба слоя читают её с разных сторон. Замер всех
  // слоёв реального файла стоит 3–13 мс — не бесплатно, но и не по разу на слой, если индекс
  // общий. Не передан ⇒ слои не мерятся вовсе (`allowance: null`), и это законный режим:
  // просмотрщику листа и диалогу сопоставления деталей припуск не нужен, а платить за него они
  // не обязаны.
  //
  // ⚠ Индекс обязан быть построен по НЕОТФИЛЬТРОВАННОМУ набору деталей. На наборе, уже суженном
  // до одного слоя, второго контура блока нет по построению — мерить нечем, и замер молча
  // выродится в 'unknown' на каждом слое.
  index?: AllowanceIndex,
): LayerOption[] {
  // слой → идентичность → размер → габарит
  const byLayer = new Map<string, Map<string, Map<string, string>>>();
  const count = new Map<string, number>();
  for (const p of pieces) {
    const layer = p.layer ?? '';
    count.set(layer, (count.get(layer) ?? 0) + 1);
    const code = codeById.get(p.id);
    if (!code || !code.identity) continue;
    const ident = byLayer.get(layer) ?? new Map<string, Map<string, string>>();
    const sizes = ident.get(code.identity.toLowerCase()) ?? new Map<string, string>();
    // Первый выигрывает: две ревизии одного размера в одном разборе не должны читаться как
    // градация.
    if (!sizes.has(code.size)) sizes.set(code.size, dim(p));
    ident.set(code.identity.toLowerCase(), sizes);
    byLayer.set(layer, ident);
  }

  const out: LayerOption[] = [];
  for (const [layer, pieceCount] of count) {
    let graded = 0;
    let checked = 0;
    for (const sizes of byLayer.get(layer)?.values() ?? []) {
      // Одна деталь в одном размере ничего не доказывает ни в одну сторону.
      if (sizes.size < 2) continue;
      checked++;
      if (new Set(sizes.values()).size > 1) graded++;
    }
    // Замер пристёгивается ЗДЕСЬ, а не в сортировке ниже: он подпись к выбору, а не участник
    // ранжирования. Слой, на котором лежит линия кроя, остаётся ровно там же в списке, где стоял
    // до Ф3, — просто теперь про него сказано, что он линия кроя.
    const allowance = index ? measureContourAllowance(pieces, layer, index) : null;
    out.push({
      layer,
      pieces: pieceCount,
      graded,
      checked,
      allowance,
      allowanceCm: allowance?.allowanceCm ?? null,
      sampled: allowance != null && allowance.verdict !== 'unknown',
    });
  }

  // Сортировка = порядок правдоподобия. Сперва доля градуирующихся деталей, затем охват
  // (слой, дающий деталей больше, вероятнее несёт весь комплект), затем сам номер слоя — чтобы
  // порядок был устойчивым, а не зависел от порядка обхода Map.
  //
  // ЗАМЕР В СОРТИРОВКУ НЕ ВХОДИТ, и это решение, а не забывчивость. «Слой с линией шва вперёд»
  // выглядит соблазнительно — раскладывать надо шов, — но замер отвечает 'unknown' законно и
  // часто (файл-россыпь, мелкая карточка, неградуирующийся слой), и слой, про который улик нет,
  // тогда молча уезжал бы вниз или вверх по причине, которой в списке не видно. Градация же
  // работает ровно там, где замер молчит, — на градуированном файле; менять судью на того, кто
  // чаще отказывается судить, значит терять текущий выбор без выигрыша.
  const rate = (o: LayerOption) => (o.checked > 0 ? o.graded / o.checked : -1);
  return out.sort(
    (a, b) => rate(b) - rate(a) || b.pieces - a.pieces || a.layer.localeCompare(b.layer),
  );
}

// Короткая подпись к слою в списке выбора: «линия кроя, +1.00 см» / «линия шва» / «не измерено».
// Пустая строка — «замер не проводился вовсе», и её вызывающий не печатает: сказать «не измерено»
// там, где никто и не собирался мерить, значит сообщить о проблеме, которой нет.
//
// Живёт здесь, а не в модалке, по той же причине, по которой текст отказа пересборки живёт в
// `marker-rebuild.ts`: подпись в списке слоёв и подпись под полем припуска говорят об ОДНОМ
// факте, и два места, где он формулируется, однажды скажут разное.
export function layerAllowanceLabel(o: LayerOption): string {
  const m = o.allowance;
  if (!m) return '';
  // ЗАМЕР ЖИВЁТ В САНТИМЕТРАХ (это геометрия файла), ПОКАЗЫВАЕТСЯ В МИЛЛИМЕТРАХ (это припуск).
  // Конверсия здесь и в предзаполнении ниже — по одной и той же функции, других в файле нет.
  if (m.verdict === 'cut') return `cut line, +${(engineCmToMm(m.allowanceCm) ?? 0).toFixed(1)} mm`;
  if (m.verdict === 'seam') return 'seam line';
  return 'not measured';
}

// Слой, на котором ЗАМЕРЕНА линия шва, — то есть тот, который надо предложить оператору взамен,
// когда выбран слой с линией кроя (спека §5.3: «либо поставьте припуск 0, либо выберите
// контурный слой с линией шва»). Совет обязан называть слой, а не жанр: «выберите слой с линией
// шва» на файле с четырьмя слоями — это предложение перебрать их вручную.
//
// `null`, когда такого слоя не намерено: тогда остаётся ровно один выход, и назвать надо его.
export function seamLineLayer(options: readonly LayerOption[]): string | null {
  const seam = options.filter((o) => o.allowance?.verdict === 'seam');
  if (seam.length === 0) return null;
  // Порядок списка — это порядок правдоподобия (см. сортировку выше), и первый совпадающий с ним
  // ответ лучше «самого измеренного»: оператору предлагается слой, который система и так считает
  // деталью.
  return seam[0].layer;
}

// ── СКОЛЬКО ПРИПУСКА ПОДСТАВИТЬ В ПОЛЕ (Ф3.2, спека §5.5) ─────────────────────────────────────
//
// Живёт РЯДОМ С ЗАМЕРОМ, а не в модалке, по той же причине, по которой рядом с составом живёт
// `legacyPairOf`: это РЕШЕНИЕ, а не выражение, и решение, которое обязано проверяться зондом.
// Пока порядок источников был цепочкой тернарников внутри компонента, единственным способом
// узнать, что он не переставлен, было прочитать компонент.
//
// Первый источник — не эталон, а ФАКТ, и поэтому он выше эталона: файл с линией кроя уже несёт
// припуск, и добавлять к нему нечего (уточнение §10.5 к плану — «файл с линией кроя ⇒ требуемый
// припуск 0» относится к слагаемому, а не к эталону).
//
// Последний источник — признание, а не ответ. `NEST_DEFAULTS.seamAllowanceCm` перестал быть
// источником истины и остался фолбэком, у которого в подписи так и сказано, что его никто не
// задавал. Подставлять сюда ноль было бы хуже всего: ноль — ЗАКОННАЯ настройка («наши выкройки
// несут линию кроя»), и выдав её за «не настроено», экран объявил бы каждую раскладку с
// припуском 10 мм нарушающей эталон, которого никто не задавал.

// Потолок припуска, мм — тот же, что валидирует сервер (entity.MaxSeamAllowanceMm). Не физика, а
// проверка единиц: самый широкий реальный припуск — подгиб низа 40–50 мм, поэтому «110» вместо «11»
// это промах по точке, дающий совершенно правдоподобный маркер вчетверо длиннее. Ноль ЗАКОНЕН.
// Потолок переехал в allowance-units.ts вместе с единицей: он обязан двигаться вместе с CHECK'ом
// миграции 0290 и entity.MaxSeamAllowanceMm, и держать его в трёх файлах вместо двух значило бы
// добавить третье место для расхождения. Реэкспорт — чтобы модалка импортировала его оттуда же,
// откуда берёт конверсию.
export { MAX_SEAM_ALLOWANCE_MM, clampSeamAllowanceMm } from './allowance-units';

export type SeamAllowancePrefill = {
  /** МИЛЛИМЕТРЫ — то, что попадёт в поле оператора и уедет на провод. */
  value: number;
  // Откуда взялось число — печатается под полем. Подставленное молча неотличимо от введённого, и
  // оператор не может ни проверить его, ни возразить ему.
  why: string;
  // Ярлык источника для зонда и для отладки. Порядок значений — это и есть порядок §5.5.
  source: 'contour_is_cut' | 'card' | 'workshop' | 'measured_gap' | 'fallback';
};

export function seamAllowancePrefill(args: {
  // Замер ВЫБРАННОГО контурного слоя. null = не мерили. В САНТИМЕТРАХ — это геометрия файла.
  measured: ContourAllowance | null;
  // «Требуемый припуск» карточки, ММ. null/undefined = не задан. НОЛЬ — ЗАДАН.
  cardRequiredMm?: number | null;
  // Припуск цеха по умолчанию, ММ. Тот же договор.
  workshopDefaultMm?: number | null;
  // Последний фолбэк — `NEST_DEFAULTS.seamAllowanceCm`, переведённый в ММ вызывающим. Приходит
  // параметром, чтобы этот модуль не тянул конфиг движка ради одного числа.
  fallbackMm: number;
}): SeamAllowancePrefill {
  const m = args.measured;
  if (m && m.verdict === 'cut' && (m.allowanceCm ?? 0) > 0) {
    return {
      value: 0,
      source: 'contour_is_cut',
      why: `layer ${m.layer} carries the CUT line — the ${(engineCmToMm(m.allowanceCm) ?? 0).toFixed(1)} mm allowance is already in the contour, no offset needed`,
    };
  }
  if (args.cardRequiredMm != null && Number.isFinite(args.cardRequiredMm)) {
    return {
      value: clampSeamAllowanceMm(args.cardRequiredMm),
      source: 'card',
      why: 'the allowance the card requires',
    };
  }
  if (args.workshopDefaultMm != null && Number.isFinite(args.workshopDefaultMm)) {
    return {
      value: clampSeamAllowanceMm(args.workshopDefaultMm),
      source: 'workshop',
      why: "the workshop's default allowance",
    };
  }
  // Замеренная дистанция между двумя контурами — последнее, что ИЗМЕРЕНО, и потому последнее, что
  // имеет право подставиться. Ниже только умолчание, которого никто не мерил.
  if (m && m.verdict === 'seam' && m.gapCm != null && m.gapCm > 0) {
    return {
      value: clampSeamAllowanceMm(engineCmToMm(m.gapCm)),
      source: 'measured_gap',
      why: `measured from the file: the cut line is drawn ${(engineCmToMm(m.gapCm) ?? 0).toFixed(1)} mm outside the seam line`,
    };
  }
  return {
    value: clampSeamAllowanceMm(args.fallbackMm),
    source: 'fallback',
    why: "the marker's default — neither the card, nor the workshop, nor the file named an allowance",
  };
}

// Слой по умолчанию. Возвращает '' когда выбирать не из чего — вызывающий тогда ничего не
// фильтрует, вместо того чтобы показать пустой лист.
export function defaultContourLayer(options: readonly LayerOption[]): string {
  return options[0]?.layer ?? '';
}

// Блоки, у которых на выбранном слое контура НЕТ вовсе. Такие детали фильтр выкидывает молча —
// а молча потерянная деталь кроя обнаруживается уже на раскроенной ткани. Считаем по имени
// блока, а не по идентичности: пропасть может и отдельный размер.
export function blocksMissingOnLayer(
  pieces: readonly PieceDTO[],
  layer: string,
): string[] {
  const all = new Set<string>();
  const present = new Set<string>();
  for (const p of pieces) {
    const b = (p.blockName ?? '').trim();
    if (!b) continue; // безымянный контур привязать всё равно не к чему
    all.add(b);
    if ((p.layer ?? '') === layer) present.add(b);
  }
  return [...all].filter((b) => !present.has(b)).sort();
}
