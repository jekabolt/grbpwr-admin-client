// ЕСТЬ ЛИ У КАРТОЧКИ ЧЕРТЁЖ — один ответ на всех, кто спрашивает «можно ли ещё заводить детали руками».
//
// Деталь кроя приходит из DXF: её заводит модалка сопоставления «↔ детали кроя», она же считает
// число экземпляров и она же предлагает удалить исчезнувшие из чертежа. Ручное заведение осталось
// ровно одной лазейкой — карточка, к которой чертежа ЕЩЁ НЕТ: на детали вешают операции и строки
// рецепта, пока конструктор рисует. Как только первый DXF привязан, единственным автором деталей
// становится модалка, а ручная кнопка исчезает — иначе карточка расходится с чертежом молча.
//
// Предикат намеренно смотрит на ФОРМУ, а не на сохранённую карточку: лист, добавленный в этой
// сессии, уже закрывает ручное заведение — до сохранения деталь всё равно не уедет.
//
// Модуль лёгкий по той же причине, что и dxf-by-scope: его импортируют главный бандл (вкладки
// деталей и операций) и ленивый чанк раскладки, поэтому из тяжёлого графа (dxf-parser, clipper,
// воркер) он не тянет ничего.
import { isDxfUrl } from 'utils/pattern';

/** Строка листа выкройки, как она лежит в форме (`patterns`). */
export type PatternSheetRow = { url?: string; filename?: string };

/**
 * true — к карточке привязан хотя бы один DXF-лист.
 *
 * Тип листа решает РАСШИРЕНИЕ URL и только оно — ровно как у всех остальных потребителей
 * (`patterns-field`, `dxf-by-scope`, разбор чертежа). Имя файла спрашивать НЕЛЬЗЯ, хотя соблазн
 * есть: расширение объекту даёт СЕРВЕР по результату сниффа байтов, поэтому файл, залитый как
 * `.dxf`, но опознанный как PDF, живёт с `.pdf`-адресом и `.dxf`-именем. Предикат, верящий имени,
 * запер бы такую карточку намертво: ручное заведение он закрывает, а сопоставлять нечего —
 * панель выкроек этот лист считает PDF и кнопки «↔ детали кроя» не показывает.
 */
export function cardHasDxf(patterns: readonly PatternSheetRow[] | undefined): boolean {
  if (!patterns?.length) return false;
  return patterns.some((p) => isDxfUrl(p?.url));
}
