// ГРАНИЦА МИЛЛИМЕТРОВ И САНТИМЕТРОВ. Ровно две функции, и ими исчерпывается вся конверсия в
// приложении.
//
// ЧТО ПО КАКУЮ СТОРОНУ. Контракт (0290) говорит о припуске в МИЛЛИМЕТРАХ: цеховой дефолт, эталон
// карточки, припуск шага, оба припуска раскладки. Движок раскладки говорит в САНТИМЕТРАХ и будет
// говорить в них дальше — это не поле с единицей, а система координат: контуры (`poly`), габариты,
// начала координат, координаты размещений, сагитта, эпсилон RDP, пороги замера припуска, и парсер
// DXF, который нормализует к сантиметрам файл в любых единицах. Переводить её значит трогать NFP,
// clipper, все сохранённые раскладки и все допуски разом — ради чисел, которых человек не видит.
//
// ПОЧЕМУ ИМЕННО ДВЕ ФУНКЦИИ И ПОЧЕМУ В ОТДЕЛЬНОМ ФАЙЛЕ. Умножение на десять, размноженное по двум
// местам, даёт десятикратную ошибку в норме ткани по всему периметру каждой детали — и она
// выглядит правдоподобно. Один модуль, два имени, и `grep mmToEngineCm` отвечает на вопрос «где мы
// конвертируем» полным списком.
//
// НОЛЬ И ОТСУТСТВИЕ РАЗЛИЧАЮТСЯ ВЕЗДЕ. Ноль — законное значение («кроим по линии как нарисована»),
// null — «не задано»/«не мерялось». Поэтому обе функции пропускают null и undefined НАСКВОЗЬ, а не
// сводят их к нулю: ровно там, где 0 * 10 = 0 безобидно, null → 0 объявил бы каждую раскладку с
// припуском нарушающей эталон, которого никто не задавал.

export const MM_PER_CM = 10;

/** Контрактные миллиметры → сантиметры движка. */
export function mmToEngineCm(mm: number): number;
export function mmToEngineCm(mm: number | null | undefined): number | null;
export function mmToEngineCm(mm: number | null | undefined): number | null {
  if (mm == null || !Number.isFinite(mm)) return null;
  return mm / MM_PER_CM;
}

/** Сантиметры движка → контрактные миллиметры. */
export function engineCmToMm(cm: number): number;
export function engineCmToMm(cm: number | null | undefined): number | null;
export function engineCmToMm(cm: number | null | undefined): number | null {
  if (cm == null || !Number.isFinite(cm)) return null;
  return cm * MM_PER_CM;
}

// Потолок припуска, МИЛЛИМЕТРЫ — та же тройка чисел, что CHECK'и миграции 0290 и
// entity.MaxSeamAllowanceMm на сервере. Они обязаны двигаться вместе.
//
// Проверка единиц теперь ловит ОБРАТНУЮ ошибку по сравнению с прежней сантиметровой: самый широкий
// реальный припуск — подгиб низа 40–50 мм, поэтому больше 100 это лишний ноль, а МЕНЬШЕ 1 —
// сантиметры, набранные в миллиметровое поле. Ноль исключён из второй проверки: он настройка, а не
// опечатка.
export const MAX_SEAM_ALLOWANCE_MM = 100;
export const SUSPICIOUSLY_SMALL_SEAM_ALLOWANCE_MM = 1;

export const clampSeamAllowanceMm = (v: number): number =>
  Math.min(MAX_SEAM_ALLOWANCE_MM, Math.max(0, v));
