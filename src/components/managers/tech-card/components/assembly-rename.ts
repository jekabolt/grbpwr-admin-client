import type { PosOverrides } from './assembly-positions';
import type { PosEdit } from './last-mutation';

// ПЕРЕИМЕНОВАНИЕ УЗЛА — ВЕСЬ РАСЧЁТ ЖЕСТА, БЕЗ REACT И БЕЗ ФОРМЫ.
//
// Идентичность узла — это его код: колонка `output_unit_key VARCHAR(64) COLLATE utf8mb4_bin`
// (0307), и никакой durable-идентичности у узла нет. Шапка той же миграции обещает взамен
// «переименование кода — атомарная перезапись потребителей в том же сохранении», то есть
// клиентский переписыватель ссылок. Здесь считается ровно он: где стоит ключ, чем ответить на
// занятый или слишком длинный код и куда переезжает ручная позиция ноды.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ЧИСТЫЙ МОДУЛЬ. Тест-раннера у клиента нет, а раньше этот расчёт жил внутри
// `operations-field.tsx` — и удостоверяла его ТОЛЬКО КОПИЯ, написанная в пробе истории. Копия
// успела разойтись с оригиналом (в ней не было ни ветки растворения, ни коллизии с деталью), и
// проба зеленела на модели, а не на коде. Две правды об одном расчёте хуже одной непроверенной:
// расхождение видно только тому, кто читает обе. Поэтому расчёт живёт здесь, а проба
// (`scripts/assembly-rename-probe.mjs`) импортирует НАСТОЯЩИЙ модуль — и проба истории тоже.
//
// ЧЕГО ЗДЕСЬ НЕТ: ни одной записи. Модуль отвечает «что сделать», а делает — мутатор
// `renameUnit`, единственный на обе поверхности (R3). Гейт заморозки тоже не здесь: он общий у
// всех мутаторов и стоит у них первой строкой.

/** Ровно то, что переписывателю ссылок нужно от строки формы: два места, где живёт ключ узла. */
export type UnitKeyRow = { outputUnitKey?: string; inputKeys?: string[] };

/** Деталь глазами переименования: ключ занимает то же пространство имён, имя — для слов отказа. */
export type UnitRenamePiece = { lineKey: string; name?: string };

/** План перезаписи: где стоит ключ и сколько ШАГОВ жест затронет. */
export type UnitRenamePlan = {
  /** Индексы шагов, у которых ключ стоит ВЫХОДОМ: производитель и каждый поглощающий. */
  outputs: number[];
  /** Потребители: адрес шага и позиции ключа внутри его `inputKeys`. */
  inputs: { index: number; at: number[] }[];
  /** Сколько РАЗНЫХ шагов затронуто — это число и произносится в успехе. */
  steps: number;
};

/**
 * ТРИ ВИДА МЕСТ, ГДЕ СТОИТ КЛЮЧ УЗЛА, а не два.
 *
 *  1. `outputUnitKey` производителя — сама правка;
 *  2. `outputUnitKey` каждого ПОГЛОЩАЮЩЕГО шага: поглощение выражено тем же ключом в ВЫХОДЕ
 *     (`GARMENT + HEM → GARMENT`). Пропустить это значит превратить поглотителей во ВТОРЫХ
 *     ПРОИЗВОДИТЕЛЕЙ старого кода, то есть в новые узлы, — самая тихая из трёх ошибок: на глаз
 *     переименование выглядит удавшимся, а движок начинает отвергать половину карточки;
 *  3. элементы `inputKeys` каждого потребителя.
 *
 * Всё остальное (блоки, фронтир, печать, серверная запись полной заменой) — деривативы, они
 * пересчитаются сами.
 *
 * СКАН ЛЕКСИЧЕСКИЙ, А НЕ ПО РЕЗУЛЬТАТУ СВИПА, и это осознанно: свип знает только ЗАКОННЫЕ узлы, а
 * переписывать надо ВСЕ места, где ключ стоит буквально. На сломанной карточке (второй
 * производитель, отвергнутый джойн) свип половины этих мест не видит вовсе — и переименование
 * оставило бы их со старым кодом, то есть починка ломала бы.
 *
 * СРАВНЕНИЕ ПОБАЙТНОЕ: никаких `trim` и `toLowerCase`. «SHELL» и «Shell» — два разных узла, ровно
 * как в колонке `utf8mb4_bin`. Подрезка живёт ВЫШЕ, в `unitRenameAct`, и ровно одна: сюда ключ
 * приходит уже нормализованным, а искать надо и по НЕнормализованному старому — на карточке, где
 * такой ключ успели завести, места с ним обязаны найтись и починиться.
 */
export function planUnitRename(ops: UnitKeyRow[], from: string): UnitRenamePlan {
  const outputs: number[] = [];
  const inputs: { index: number; at: number[] }[] = [];
  ops.forEach((o, i) => {
    if (((o?.outputUnitKey ?? '') as string) === from) outputs.push(i);
    const at: number[] = [];
    (o?.inputKeys ?? []).forEach((k, j) => {
      if (k === from) at.push(j);
    });
    if (at.length > 0) inputs.push({ index: i, at });
  });
  const touched = new Set<number>(outputs);
  for (const s of inputs) touched.add(s.index);
  return { outputs, inputs, steps: touched.size };
}

/**
 * ПОТОЛОК КОДА УЗЛА — В БАЙТАХ, А НЕ В СИМВОЛАХ.
 *
 * Сервер меряет `len(key)` по UTF-8 (`assemblyUnitKeyMaxLen`, `internal/dto/techcard_assembly.go`),
 * а `maxLength` у поля ввода — единицы UTF-16. Для латиницы это одно и то же, для кириллицы —
 * вдвое разное: 64 набранных символа это 128 байт, и сервер отвечает `too_long` уже ПОСЛЕ того,
 * как интерфейс разрешил их набрать. Отказ, прилетевший с провода на давно набранное поле,
 * читается как поломка, а не как правило.
 *
 * МЕРЯЕТСЯ КЛЮЧ, КАКИМ ОН УЕДЕТ, то есть уже подрезанный: сервер считает то, что получил, а
 * получает он `(o.outputUnitKey ?? '').trim()`. Мерить набранное с пробелами значило бы отказывать
 * там, где сервер бы принял, — тот же разлад, только в другую сторону.
 */
export const UNIT_KEY_MAX_BYTES = 64;

const utf8 = new TextEncoder();

/** Длина ключа так, как её посчитает сервер. */
export function unitKeyBytes(key: string): number {
  return utf8.encode(key).length;
}

/**
 * Отказ по длине — СЛОВАМИ И С ЧИСЛОМ, а не молчаливой обрезкой посреди набора. Без числа
 * «слишком длинный» на латинице и на кириллице читается одинаково, а рубеж у них разный, и
 * человек не понимает, сколько ещё стирать.
 *
 * ТОТ ЖЕ РАЗЛАД ЖИВЁТ У СОСЕДЕЙ, и он сюда НЕ затянут намеренно: `maxLength={255}` у имени узла
 * (и в редакторе шага, и в диалоге создания) и `maxLength={64}` у кода в диалоге создания считают
 * ровно так же, а сервер меряет байтами и их. Чинится это тем же вызовом, но чинить надо жестом, у
 * которого есть свой стенд, — иначе правка расползается на четыре поля без единого замера.
 */
export function unitKeyLengthRefusal(key: string): string | null {
  const bytes = unitKeyBytes(key);
  if (bytes <= UNIT_KEY_MAX_BYTES) return null;
  return `the unit code is ${bytes} bytes and the limit is ${UNIT_KEY_MAX_BYTES} — non-latin letters count as two bytes each, so the server would refuse it`;
}

/**
 * ЧТО ЖЕСТ СОБИРАЕТСЯ СДЕЛАТЬ — один ответ на все ветки, чтобы у мутатора не было своей второй
 * лестницы условий.
 *
 * `noop` — набрали побайтно то же самое: жеста не было, и говорить не о чем.
 * `dissolve` — пустой ключ это НЕ переименование, а растворение, и ведёт оно в существующий
 * мутатор: второй растворитель рядом с первым разошёлся бы с ним молча.
 * `refuse` — слова движка; ни одной записи.
 */
export type UnitRenameAct =
  | { kind: 'noop' }
  | { kind: 'dissolve' }
  | { kind: 'refuse'; why: string }
  /**
   * `to` — ключ, каким он ЛЯЖЕТ В ФОРМУ, а не каким его набрали: подрезанный. Вызывающий обязан
   * писать именно его, иначе клиент и сервер разойдутся тождеством ключа (см. `unitRenameAct`).
   */
  | { kind: 'rewrite'; from: string; to: string; plan: UnitRenamePlan };

/**
 * ВСЕ ОТКАЗЫ ПЕРЕИМЕНОВАНИЯ В ОДНОМ МЕСТЕ И ДО ЕДИНОЙ ЗАПИСИ.
 *
 * ТРИ КОЛЛИЗИИ, А НЕ ОДНА:
 *  • ключ занят ДЕТАЛЬЮ — пространство имён у деталей и узлов одно (правило 6);
 *  • ключ уже производится другим шагом — второй производитель отвергается правилом 2;
 *  • ДУБЛЬ ВО ВХОДАХ ОДНОГО ШАГА (правило 7) — самая неочевидная. Новый ключ может нигде не
 *    производиться и не быть деталью, и всё равно СТОЯТЬ ВХОДОМ там же, где стоит старый: так
 *    выглядит висячая ссылка на растворённый узел, состояние живое и частое. Перезапись поставила
 *    бы один и тот же вход дважды, движок отверг бы шаг правилом 7 и показал слова не о
 *    переименовании — и причину искали бы не там.
 *
 * Номер шага в словах ЭКРАННЫЙ, `(i + 1) * 10`: движок считает шаги порядковыми, а рельс и боксы
 * подписаны десятками, и назвать человеку порядковый значит отправить его искать не тот шаг.
 */
export function unitRenameAct(
  ops: UnitKeyRow[],
  stepIndex: number,
  next: string,
  pieces: UnitRenamePiece[],
): UnitRenameAct {
  const from = ((ops[stepIndex]?.outputUnitKey ?? '') as string) ?? '';
  // Переименовывать нечего: шаг ничего не собирает. Сюда попадают только через поле кода, которое
  // на таком шаге не рендерится вовсе, — но расчёт про разметку не знает.
  if (!from) {
    return { kind: 'refuse', why: 'this step assembles nothing — there is no code to rename' };
  }
  // ПОДРЕЗКА ОДИН РАЗ И ЗДЕСЬ — потому что подрезает КЛИЕНТ ЖЕ, только позже: на провод ключ уезжает
  // через `(o.outputUnitKey ?? '').trim()` (`schema.ts`). Пока набранное не нормализовано прямо тут,
  // у ключа ДВА ТОЖДЕСТВА — побайтное на экране и подрезанное на проводе, — и расходятся они молча.
  // Замерено стендом: «BODY⎵» на карточке, где BODY уже производится, проходит проверку занятости
  // (побайтно это другой ключ), подсказка печатает «▣ SHELL → BODY», то есть ровно тот код, который
  // только что был бы отвергнут, свип клиента считает карточку целой — а на сервер уезжают ДВА
  // производителя одного узла и вход, ссылающийся на собственный выход. Правило 2 отвергает
  // сохранение, и причину человек ищет где угодно, только не в невидимом пробеле.
  //
  // Сравнения НИЖЕ остаются побайтными: нормализация — это не «мягкое сравнение». «SHELL» и «Shell»
  // по-прежнему два разных узла, ровно как в колонке `utf8mb4_bin`.
  const to = next.trim();
  if (to === from) return { kind: 'noop' };
  // Ключ из одних пробелов — это ОТСУТСТВИЕ ключа, то есть растворение, а не узел с пустым именем.
  if (to === '') return { kind: 'dissolve' };

  // ГИГИЕНА ДО ГРАФА — тем же порядком, каким проверяет сервер: «код длиннее 64 байт» полезнее,
  // чем «этот код уже занят», полученное из того же набора.
  const tooLong = unitKeyLengthRefusal(to);
  if (tooLong) return { kind: 'refuse', why: tooLong };

  const piece = pieces.find((p) => p.lineKey === to);
  if (piece) {
    return {
      kind: 'refuse',
      why: `the unit key “${to}” is taken by piece “${piece.name || to}”: pieces and units share one namespace`,
    };
  }
  const taken = ops.findIndex((o) => ((o?.outputUnitKey ?? '') as string) === to);
  if (taken >= 0) {
    return {
      kind: 'refuse',
      why: `unit “${to}” is already produced by step ${(taken + 1) * 10} — pick another code, or dissolve that unit first`,
    };
  }

  const plan = planUnitRename(ops, from);
  const clash = plan.inputs.find((s) => ((ops[s.index]?.inputKeys ?? []) as string[]).includes(to));
  if (clash) {
    return {
      kind: 'refuse',
      why: `step ${(clash.index + 1) * 10} already takes “${to}” as an input: renaming “${from}” would put the same input there twice — drop one of them first`,
    };
  }
  return { kind: 'rewrite', from, to, plan };
}

/**
 * РУЧНАЯ ПОЗИЦИЯ НОДЫ ПЕРЕЕЗЖАЕТ НА НОВЫЙ КОД. Хранилище раскладки ключуется кодом узла
 * (`PosOverrides`), поэтому без переезда переименованная нода прыгала бы в авто-раскладку, а
 * оверрайд оставался бы под мёртвым ключом до чистки по потолку. Ровно эта потеря и есть жалоба,
 * с которой затевался переписыватель: конструктор расставил схему руками, переименовал узел — и
 * расстановка рассыпалась. Переименование обязано быть переименованием, а не переездом.
 *
 * ТРИ СЛУЧАЯ, И ВО ВСЕХ ТРЁХ НОДА ОБЯЗАНА ОСТАТЬСЯ НА МЕСТЕ:
 *  • у старого ключа оверрайд есть — снять его и поставить ту же точку под новым ключом;
 *  • у старого нет, а под НОВЫМ лежит чужой (узел с таким кодом когда-то жил, его растворили,
 *    оверрайд остался) — снять чужой: иначе нода, которую человек не двигал ни разу, телепортнётся
 *    в место, оставшееся от покойника. Отмена вернёт его: обратную пачку считает `inverseEdits` по
 *    снимку ДО жеста, и снятый оверрайд там ещё есть;
 *  • оверрайда нет ни под одним ключом — ПУСТАЯ ПАЧКА, и это законный ответ. Выдумывать позицию
 *    ноде, которую не двигали, значит приколотить её там, куда её однажды поставила авто-раскладка.
 *
 * Новый ключ к этому моменту гарантированно не принадлежит живой ноде: `unitRenameAct` отказывает
 * и на занятый узел, и на деталь, а пустой ключ уводит в растворение.
 *
 * ПОРЯДОК ПРАВОК В ПАЧКЕ НИЧЕГО НЕ РЕШАЕТ, и говорить обратное — вредно: правки адресуют РАЗНЫЕ
 * ключи (`to !== from` гарантирован вердиктом — равные дают `noop`), а `applyEdits` пишет и снимает
 * по ключу. Снятие стоит первым только затем, чтобы пачка читалась как рассказ «отсюда — сюда».
 * Единственный порядок, который тут действительно несущий, — снаружи: обратную пачку обязан
 * посчитать `restore` по снимку ДО применения, иначе отмена вернёт уже переехавшее состояние.
 */
export function renamePosEdits(pos: PosOverrides, from: string, to: string): PosEdit[] {
  const at = pos[from];
  if (at) {
    return [
      { key: from, at: null },
      { key: to, at: { x: at.x, y: at.y } },
    ];
  }
  return pos[to] ? [{ key: to, at: null }] : [];
}

/**
 * СОСТОЯВШЕЕСЯ ПЕРЕИМЕНОВАНИЕ — весть тем, кто держит ключи узлов у себя. Держит их выделение, и
 * оно живёт в ДВУХ местах: у инлайновой схемы и у фулскрина (полотно берёт их пропом).
 *
 * Почему вестью, а не общим состоянием: выделение — состояние ЖЕСТА, а не данных, и поднимать его
 * в поле операций значило бы связать два экрана, которые о выборе друг друга ничего знать не
 * должны. Весть же несёт ровно факт: этот ключ теперь называется так.
 */
export type UnitRenameNotice = { from: string; to: string };

/**
 * ПЕРЕНЕСТИ ВЫДЕЛЕНИЕ НА НОВЫЙ КЛЮЧ.
 *
 * Оба вида чистят выделение от ключей, которых больше нет в раскладке, — и это верно для
 * растворения, но неверно для переименования: нода никуда не делась, у неё другое имя. Молча
 * слетевшее выделение читается как «жест сбил мне работу», а не как «узел переименован».
 *
 * ТОТ ЖЕ МАССИВ, ЕСЛИ СТАРОГО КЛЮЧА В НЁМ НЕ БЫЛО: новая ссылка на прежний набор перерисовала бы
 * полотно на каждое чужое переименование.
 */
export function renamePicked(picked: string[], from: string, to: string): string[] {
  return picked.includes(from) ? picked.map((k) => (k === from ? to : k)) : picked;
}
