import { cn } from 'lib/utility';
import { useEffect, useMemo, useState, type JSX } from 'react';
import { Placeholder } from 'ui/components/placeholder';
import Text from 'ui/components/text';

/**
 * ═══ ДВА ВОПРОСА О ПЛИТКЕ, И НИ НА ОДИН ИЗ НИХ НЕ ОТВЕЧАЕТ САМА ПЛИТКА ════════════════════════
 *
 *   1. «ОНО ВООБЩЕ ТАЙЛИТСЯ» — на это отвечает `TileGrid`, предпросмотр 3×3.
 *   2. «КАКОГО ОНО РАЗМЕРА» — на это отвечает `ScaleStrip`, линейка.
 *
 * ПОЧЕМУ 3×3 ОБЯЗАТЕЛЕН, А НЕ ЖЕЛАТЕЛЕН. Сервер ловит два порока: плитку, которая НЕ
 * заворачивается, и рамку по краю (`pattern_not_seamless`). Он НЕ ловит третий — плитку, которая
 * заворачивается идеально и всё равно заметно повторяется: пятно, которое глаз находит через
 * каждые 12 см и больше не может развидеть. Это судит только глаз, и судить ему нечем, пока плитка
 * показана одна: одиночный квадрат ткани выглядит хорошо ВСЕГДА. Девять копий рядом — минимальная
 * сцена, на которой видны оба стыка (вертикальный и горизонтальный) и повтор мотива.
 *
 * ЗАСЕЧКИ СТОЯТ СНАРУЖИ КАДРА, А НЕ ПОВЕРХ НЕГО, и это не мелочь. Линия, проведённая по стыку,
 * ЗАКРЫВАЕТ ровно тот пиксель, ради которого сцену и открыли: плохой шов прячется под собственной
 * разметкой, и предпросмотр начинает подтверждать то, что должен опровергать. Поэтому засечки —
 * две снизу и две справа, ЗА границей кадра; они говорят, ГДЕ искать, и ничего не перекрывают.
 * Наложение линий существует отдельным переключателем и по умолчанию выключено.
 *
 * ФОН, А НЕ ДЕВЯТЬ `<img>`. Девять картинок, отмасштабированных браузером по отдельности,
 * расходятся на дробной ширине и рисуют между собой волосяной зазор — то есть СОБСТВЕННЫЙ шов,
 * которого в плитке нет. Один повторяющийся фон с `background-size: calc(100% / 3)` укладывается
 * одной раскладкой, и всё, что видно на стыке, принадлежит картинке.
 */

/** Доли третей — вынесены, чтобы засечки и наложение стояли на одних и тех же числах. */
const THIRDS = ['33.3333%', '66.6667%'] as const;

export function TileGrid({
  url,
  alt,
  /** Наложить волосяные линии ПО стыкам. По умолчанию нет — см. довод в шапке. */
  edges,
  className,
}: {
  url: string;
  alt: string;
  edges?: boolean;
  className?: string;
}): JSX.Element {
  if (!url) {
    return (
      <Placeholder
        dashed
        label='no tile yet'
        className={cn('aspect-square w-full', className)}
      />
    );
  }
  return (
    <div className={cn('flex w-full flex-col', className)} data-probe='tile-preview'>
      <div className='flex w-full items-stretch'>
        <div className='relative min-w-0 flex-1'>
          <div
            role='img'
            aria-label={`${alt} — repeated three by three`}
            data-probe='tile-3x3'
            /* ЧИСЛО КОПИЙ — ЗНАЧЕНИЕ НА АТРИБУТЕ, А НЕ ВЫВОД ИЗ CSS. Пробе нужно утверждение
               «здесь девять плиток», а `background-size` она прочитает как строку `calc(...)`,
               из которой это не следует. */
            data-tiles='9'
            data-tile-url={url}
            className='aspect-square w-full border border-textColor bg-bgColor'
            style={{
              backgroundImage: `url("${url}")`,
              backgroundRepeat: 'repeat',
              // Ровно три по горизонтали и три по вертикали. `calc` считается раскладкой, а не
              // округлённым процентом, поэтому у правого и нижнего края не остаётся полосы.
              backgroundSize: 'calc(100% / 3) calc(100% / 3)',
              backgroundPosition: '0 0',
            }}
          />
          {edges && (
            <div aria-hidden='true' className='pointer-events-none absolute inset-0'>
              {THIRDS.map((at) => (
                <span
                  key={`v${at}`}
                  data-probe='edge-line'
                  style={{ left: at }}
                  className='absolute top-0 h-full w-px bg-textColor/40'
                />
              ))}
              {THIRDS.map((at) => (
                <span
                  key={`h${at}`}
                  data-probe='edge-line'
                  style={{ top: at }}
                  className='absolute left-0 h-px w-full bg-textColor/40'
                />
              ))}
            </div>
          )}
        </div>
        {/* Правые засечки — где проходят ГОРИЗОНТАЛЬНЫЕ стыки. */}
        <div aria-hidden='true' className='relative w-1.5 shrink-0'>
          {THIRDS.map((at) => (
            <span
              key={at}
              data-probe='tick-h'
              style={{ top: at }}
              className='absolute left-0 h-px w-full bg-textColor'
            />
          ))}
        </div>
      </div>
      <div className='flex'>
        {/* Нижние засечки — где проходят ВЕРТИКАЛЬНЫЕ стыки. */}
        <div aria-hidden='true' className='relative h-1.5 min-w-0 flex-1'>
          {THIRDS.map((at) => (
            <span
              key={at}
              data-probe='tick-v'
              style={{ left: at }}
              className='absolute top-0 h-full w-px bg-textColor'
            />
          ))}
        </div>
        <div className='w-1.5 shrink-0' />
      </div>
    </div>
  );
}

/* ─────────────────────────── линейка ─────────────────────────── */

/**
 * ═══ ЧИСЛО БЕЗ МАСШТАБА НЕ ЗНАЧИТ НИЧЕГО (K-13: «прикинуть размер … руками») ══════════════════
 *
 * `repeat_mm` уезжает на сервер числом и приходит в промпт указанием масштаба («одна плитка
 * покрывает 120 мм ткани»). Поле ввода с надписью «120» не отвечает на единственный вопрос, ради
 * которого его крутят: КРУПНО это или мелко. Поэтому рядом с полем стоит полоса, на которой плитка
 * уложена в НАЗВАННЫЙ отрезок ткани, и под полосой — линейка в сантиметрах.
 *
 * ЧТО ЗДЕСЬ ЧЕСТНО, А ЧТО БЫЛО БЫ ЛОЖЬЮ. Полоса НЕ обещает физического 1:1 на мониторе — размер
 * пикселя в миллиметрах браузер не знает и знать не может, и линейка, объявившая себя настоящей,
 * врала бы на каждом втором экране. Она обещает ОТНОШЕНИЕ: плитка и линейка нарисованы одним и тем
 * же масштабом, поэтому «сколько раз мотив уложится в полметра» читается верно на любом экране.
 * Это и есть тот вопрос, который человек задаёт числу раппорта.
 *
 * И ОНА НЕ РИСУЕТ ПЛИТКУ НА ФЛЭТЕ. Владелец просил прикинуть размер «на флете» (K-13), но там же,
 * пунктом K-14, увёл разметку в раздел RENDERS. Соблюсти оба можно было бы, только зная РОСТ
 * изделия в миллиметрах, — а карточка его не называет: технический чертёж не несёт масштаба вовсе.
 * Полоса поверх флэта означала бы, что мы этот рост ВЫДУМАЛИ, и человек мерил бы по нашей выдумке.
 * Названный отрезок ткани («500 мм — половина обхвата груди») — то же сравнение, но с честно
 * объявленным допущением.
 */

/** Отрезки ткани, к которым прикладывают плитку. Три, а не поле: это единица сравнения, не число. */
export const SPANS: { mm: number; label: string; what: string }[] = [
  { mm: 200, label: '200 mm', what: 'a cuff, a pocket' },
  { mm: 500, label: '500 mm', what: 'half a chest' },
  { mm: 1000, label: '1000 mm', what: 'a front, top to hem' },
];

/** Шаг делений: не больше сорока штук на полосу, иначе линейка становится заливкой. */
function tickStep(spanMm: number): { minor: number; major: number } {
  if (spanMm <= 250) return { minor: 10, major: 50 };
  if (spanMm <= 600) return { minor: 25, major: 100 };
  return { minor: 50, major: 250 };
}

/**
 * ═══ ЛОСКУТ ТКАНИ — ОДНА КАРТИНКА, ЗАМОЩЁННАЯ НА НАЗВАННОМ ОТРЕЗКЕ ═════════════════════════════
 *
 * Выделен из `ScaleStrip`, потому что его нужны ДВА разных вопроса, а линейка — только одному:
 *   · акт 2 (`ScaleStrip`) — «того ли размера ВЫШЛА плитка»: лоскут ПЛЮС линейка с делениями;
 *   · акт 1 (полоса плотности, H-7) — «что значит 60 против 120 НА МОЕЙ картинке»: лоскут БЕЗ
 *     линейки, до денег, на фиксированном отрезке.
 * Скопировать расчёт во второе место означало бы два масштаба под одним именем, расходящихся
 * первой же правкой пропорции.
 *
 * ИМЯ ЯКОРЯ ЗАДАЁТ ВЫЗЫВАЮЩИЙ (`probe`), и это не украшение: два лоскута на одном экране под одним
 * `data-probe` сделали бы любой селектор пробы неоднозначным, а «первый в документе» — не то, что
 * измеряют.
 */
/**
 * ЗА ПРЕДЕЛОМ ЭТОГО ЧИСЛА ПЛИТОК НА ОТРЕЗКЕ МЕНЬШЕ ОДНОЙ, И ШВА НА ЭКРАНЕ НЕТ ВОВСЕ.
 *
 * Экспортируется, потому что на этот вопрос отвечают ДВОЕ: сам кадр (замощать или показать
 * картинку целиком) и подпись под ним («шов чинит прогон» — либо правда, либо нет). Два ответа на
 * один вопрос расходятся ровно тем, чем расходятся их правки: подпись обещала бы шов там, где
 * кадр его уже не рисует.
 */
export function swatchTiles(repeatMm: number, spanMm: number): boolean {
  return repeatMm > 0 && spanMm / repeatMm >= 1.05;
}

/** Максимальная высота лоскута акта 1, px. Ширина подрезается под неё, ПРОПОРЦИЯ сохраняется. */
const PICTURE_MAX_H = 240;
/** Нижняя граница высоты акта 1 в долях ширины: мелкий раппорт иначе даёт полоску в пять пикселей. */
const PICTURE_MIN_RATIO = 0.14;

export function ClothSwatchStrip({
  url,
  repeatMm,
  spanMm,
  probe,
  subject = 'tile',
  caption,
  className,
}: {
  url: string;
  /** 0 = раппорт не назван. Лоскут тогда говорит это словами и ничего не масштабирует. */
  repeatMm: number;
  spanMm: number;
  probe: string;
  /**
   * ЧТО ИМЕННО ЗАМОЩЕНО — и это не косметический проп, а ДВА РАЗНЫХ ФАКТА О КАРТИНКЕ.
   *
   * `tile` (акт 2) — картинка ЕСТЬ сгенерированная плитка, квадратная по построению. Вертикальный
   *   период можно брать из её пропорции (`auto`), потому что пропорция — единица.
   * `picture` (акт 1) — картинка ПРОИЗВОЛЬНОЕ ФОТО человека, и ровно в этом смысл полосы
   *   плотности. `auto` там берёт вертикальный период из пропорции фотографии: замерено на стенде
   *   `h7swatch-stand` при 120 мм на 500 — у широкого исходника 3:1 период по вертикали выходил
   *   73px против 220px по горизонтали, то есть подпись «only the density is true» стояла под
   *   картинкой, у которой плотность по вертикали втрое выше заявленной; у высокого 1:3 мотив
   *   уезжал за кадр целиком, и это читается как «мой файл сломан».
   *
   * Поэтому у `picture` вертикальный период задан ЯВНО и равен горизонтальному в миллиметрах, а
   * высота кадра не меньше одного периода — иначе мотив обрезан под той же подписью.
   */
  subject?: 'tile' | 'picture';
  /**
   * ЧТО СКАЗАНО ПОД ЛОСКУТОМ — И ГОВОРИТСЯ ЭТО ТОЛЬКО ТОГДА, КОГДА ЛОСКУТ ЕСТЬ.
   *
   * ⚠ ПРОП ЗАВЕДЁН ИЗ-ЗА ПРОТИВОРЕЧИЯ, А НЕ ДЛЯ УДОБСТВА. Подпись жила у вызывающего и выбиралась
   * по масштабу, а «загрузилась ли картинка» знает ТОЛЬКО этот компонент — сторож `onError` внутри
   * него. Поэтому на битом файле плейсхолдер говорил «the picture did not load», а строка под ним
   * в ту же секунду утверждала «your own picture laid out raw at this scale — only the density is
   * true»: два взаимоисключающих заявления об одной картинке, в шести пикселях друг от друга.
   *
   * Перенос подписи СЮДА делает это состояние невыразимым: один флаг решает и кадр, и слова. Это
   * дешевле сторожа — пробе нечего ловить там, где противоречие нельзя написать.
   */
  caption?: React.ReactNode;
  className?: string;
}): JSX.Element {
  /**
   * АДРЕС, КОТОРЫЙ НЕ ЗАГРУЗИЛСЯ, — ЭТО НЕ ПУСТОЙ АДРЕС. `background-image` о своём отказе не
   * сообщает никак: 404 или просроченная ссылка дают БЕЛЫЙ кадр в рамке, неотличимый от «ткань
   * белая». Здесь это стоит в двух шагах от денег, поэтому рядом висит невидимый `img` — ровно
   * затем, чтобы у браузера было место сказать `onError`.
   */
  const [broken, setBroken] = useState(false);
  useEffect(() => setBroken(false), [url]);
  /** Доля ширины полосы, которую занимает ОДНА плитка. Никогда не 0: нулевой фон не рисуется. */
  const tilePct = repeatMm > 0 ? Math.max(0.2, (repeatMm / spanMm) * 100) : 0;
  const across = repeatMm > 0 ? spanMm / repeatMm : 0;
  const picture = subject === 'picture';
  /** Замощать или показать картинку целиком — один ответ на двоих, кадр и подпись (см. выше). */
  const tiles = swatchTiles(repeatMm, spanMm);
  /**
   * ВЫСОТА ПОЛОСЫ ИДЁТ ЗА РАЗМЕРОМ ПЛИТКИ, А НЕ ЗАДАНА ЧИСЛОМ, и это не косметика.
   *
   * При фиксированной высоте крупная плитка не помещается по вертикали и ОБРЕЗАЕТСЯ пополам —
   * замерено на снимке: раппорт 120 мм на отрезке 500 мм рисовал ряд полукругов, и это читается
   * как «плитка испорчена», хотя обрезан кадр, а не мотив. Полоса — это ЛОСКУТ ткани, и её высота
   * обязана быть её собственной: ровно один ряд плиток, когда плитка крупная.
   *
   * Пределы с двух сторон. Мелкая плитка (5 мм на метре) дала бы полоску в четыре пикселя —
   * нижняя граница держит её читаемой, и тогда в кадре честно оказывается несколько рядов.
   * Верхняя не даёт полосе съесть экран, когда раппорт близок к отрезку.
   */
  const heightRatio = Math.min(0.34, Math.max(0.13, repeatMm > 0 ? repeatMm / spanMm : 0.18));

  /**
   * ГЕОМЕТРИЯ АКТА 1 — ОДНА ФОРМУЛА, ТРИ СЛЕДСТВИЯ.
   *
   * Высота задана долей ширины (`pictureRatio`) и НЕ ограничена сверху `max-height`: потолок по
   * высоте ломает пропорцию, а вместе с ней и проценты `background-size`, которые от неё считаются.
   * Размер вместо этого держит `max-width` — он подрезает ШИРИНУ, сохраняя пропорцию, поэтому
   * арифметика остаётся точной на любом экране.
   *
   *   pictureRatio ≥ repeat/span  → в кадр помещается ПОЛНЫЙ вертикальный период (мотив не срезан);
   *   verticalPct = tilePct / pictureRatio → вертикальный период РАВЕН горизонтальному в мм;
   *   maxWidth = 240 / pictureRatio → абсолютная высота не больше 240px при любом раппорте.
   */
  const pictureRatio = Math.max(repeatMm / spanMm, PICTURE_MIN_RATIO);
  const pictureStyle: React.CSSProperties = tiles
    ? {
        aspectRatio: `1 / ${pictureRatio}`,
        maxWidth: `${Math.round(PICTURE_MAX_H / pictureRatio)}px`,
        backgroundRepeat: 'repeat',
        backgroundSize: `${tilePct}% ${tilePct / pictureRatio}%`,
      }
    : {
        /* ЗА ПРЕДЕЛОМ ШВА КАДР ПЕРЕСТАЁТ ПРИТВОРЯТЬСЯ ЗАМОЩЕНИЕМ. Одна плитка шире отрезка —
           значит на экране был бы УГОЛ картинки, выданный за раппорт: замерено, при 1000 мм на
           500 в кадр попадает 0.5 плитки и шва нет ни одного. Честный ответ — показать картинку
           целиком и сказать это подписью. */
        aspectRatio: '1 / 0.34',
        maxWidth: '420px',
        backgroundRepeat: 'no-repeat',
        backgroundSize: 'contain',
      };

  return (
    <>
      {url && repeatMm > 0 && !broken ? (
        <>
          {/* Невидимый сторож загрузки. `display:none` не отменяет запрос — картинка грузится, и
              её отказ доезжает до `onError`, которого у фона не бывает. */}
          <img src={url} alt='' aria-hidden='true' className='hidden' onError={() => setBroken(true)} />
        <div
          role='img'
          aria-label={
            picture
              ? tiles
                ? `your picture repeated across ${spanMm} mm of cloth`
                : `your picture whole: one tile is wider than ${spanMm} mm of cloth`
              : `the tile laid out across ${spanMm} mm of cloth`
          }
          data-probe={probe}
          data-span={spanMm}
          data-across={across.toFixed(2)}
          data-whole={picture && !tiles ? 'true' : undefined}
          className={cn('w-full border border-textColor bg-bgColor', className)}
          style={{
            /* ПРОПОРЦИЯ ЗАДАЁТ ВЫСОТУ, ПОТОЛОК ЕЁ ОГРАНИЧИВАЕТ. Без потолка крупный раппорт на
               широком блоке вырастал в кадр высотой в треть экрана (замерено: 120 мм на 500 мм при
               ширине 1500px давали 360px) — и полоса-СПРАВКА о масштабе становилась главным
               предметом меню, хотя предмет здесь один, число раппорта. Выше потолка лоскут просто
               подрезан по высоте, что для полосы ткани и есть правда: она про ШИРИНУ. */
            backgroundImage: `url("${url}")`,
            backgroundPosition: '0 0',
            // ШИРИНА В ПРОЦЕНТАХ ОТ ПОЛОСЫ, то есть от названного отрезка ткани, — это и есть
            // масштаб. Вертикаль у акта 2 — `auto` (плитка квадратна по построению, и её
            // пропорция единична), у акта 1 — явный процент: см. довод у пропа `subject`.
            ...(picture
              ? pictureStyle
              : {
                  aspectRatio: `1 / ${heightRatio}`,
                  maxHeight: 200,
                  backgroundRepeat: 'repeat',
                  backgroundSize: `${tilePct}% auto`,
                }),
          }}
        />
        {/* Подпись — часть «лоскут нарисован», а не соседняя строка меню: у плейсхолдера ниже своё
            слово, и второго заявления о той же картинке рядом с ним не будет. */}
        {caption ? (
          <Text size='micro' variant='label' component='span' className='min-w-0 normal-case'>
            {caption}
          </Text>
        ) : null}
        </>
      ) : (
        <Placeholder
          dashed
          label={
            broken
              ? 'the picture did not load'
              : repeatMm > 0
                ? 'no picture yet'
                : 'no repeat stated'
          }
          className={cn('w-full', className)}
          /* ПУСТОЙ КАДР НЕ СЛЕДУЕТ ЗА РАППОРТОМ И НЕ МЕРЯЕТСЯ ПРОПОРЦИЕЙ. Ему нечего показывать в
             масштабе, а рост «как у плитки» превращал «пока ничего» в двести пикселей полосатой
             пустоты посреди меню (замерено при 900px и при 1280px). Одна низкая высота, одно
             слово. */
          style={{ height: 88 }}
        />
      )}
    </>
  );
}

export function ScaleStrip({
  url,
  repeatMm,
  spanMm,
  className,
}: {
  url: string;
  /** 0 = раппорт не назван. Полоса тогда говорит это словами и ничего не масштабирует. */
  repeatMm: number;
  spanMm: number;
  className?: string;
}): JSX.Element {
  const { minor, major } = tickStep(spanMm);
  const ticks = useMemo(() => {
    const out: { at: number; major: boolean }[] = [];
    for (let mm = 0; mm <= spanMm + 0.01; mm += minor) {
      out.push({ at: (mm / spanMm) * 100, major: Math.abs(mm % major) < 0.01 });
    }
    return out;
  }, [spanMm, minor, major]);

  return (
    <div className={cn('w-full', className)} data-probe='scale-strip' data-repeat={repeatMm}>
      <ClothSwatchStrip url={url} repeatMm={repeatMm} spanMm={spanMm} probe='scale-cloth' />

      {/* ЛИНЕЙКА. Деления снизу, подписи под крупными; ноль и правый край подписаны всегда. */}
      <div aria-hidden='true' className='relative h-2 w-full'>
        {ticks.map((t, i) => (
          <span
            key={i}
            style={{ left: `${t.at}%` }}
            className={cn(
              'absolute top-0 w-px bg-textColor',
              t.major ? 'h-2' : 'h-1 bg-borderColor',
            )}
          />
        ))}
      </div>
      <div className='flex items-baseline justify-between'>
        <Text size='nano' variant='label' component='span'>
          0
        </Text>
        <Text size='nano' variant='label' component='span'>
          {spanMm} mm · one tick {minor} mm
        </Text>
      </div>
    </div>
  );
}
