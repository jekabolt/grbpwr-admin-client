/**
 * ОБВЕСТИ РАСТР. Единственная дверь движка.
 *
 * Возвращает либо чтение с числами, либо ОТКАЗ СЛОВАМИ, и причина та же: половина результата,
 * поданная как успех, обнаруживается недели спустя, на бумаге, на фабрике.
 */
export function traceRaster(src: ImageData, opts: TraceOptions = {}): TraceResult {
  const w = src.width;
  const h = src.height;
  if (w < 1 || h < 1) return refuse('there is nothing to trace: the picture has no pixels.');

  const tol = clamp(
    opts.tolerance ?? DEFAULT_TRACE_TOLERANCE,
    MIN_TRACE_TOLERANCE,
    MAX_TRACE_TOLERANCE,
  );
  const minArea = Math.max(0, Math.round(opts.minArea ?? DEFAULT_TRACE_MIN_AREA));
  const cornerAngle = clamp(opts.cornerAngle ?? DEFAULT_TRACE_CORNER, 1, 179);
  const budget = Math.max(0, Math.round(opts.budgetBytes ?? MAX_STROKES_BYTES));
  const ratio = opts.ratio && opts.ratio > 0 ? opts.ratio : w / h;

  const ink = traceInk(src, opts);

  // Краска — восьмисвязная, фон — четырёхсвязный. Пара, а не вкус: см. `labelRegions`.
  const fg = labelRegions(ink, w, h, 1, true);
  const bg = labelRegions(ink, w, h, 0, false);

  // ДЫРКА — ЭТО ФОН, НЕ КАСАЮЩИЙСЯ КРАЯ ХОЛСТА. У буквы «о» внутренняя область фона окружена
  // краской со всех сторон, а наружное поле выходит на край. Родитель дырки берётся ОДНИМ
  // ЧТЕНИЕМ: пиксель НАД её верхней-левой точкой обязан быть краской (будь он фоном, он лежал бы
  // в той же четырёхсвязной области, а она тогда не была бы верхней).
  const keepFg = new Uint8Array(fg.count + 1);
  let regions = 0;
  let specks = 0;
  for (let id = 1; id <= fg.count; id++) {
    if (fg.area[id] >= minArea) {
      keepFg[id] = 1;
      regions++;
    } else specks++;
  }
  const holeParent = new Int32Array(bg.count + 1);
  let holes = 0;
  for (let id = 1; id <= bg.count; id++) {
    if (bg.edge[id]) continue;
    const hx = bg.seedX[id];
    const hy = bg.seedY[id];
    const parent = hy > 0 ? fg.lab[(hy - 1) * w + hx] : 0;
    if (!parent || !keepFg[parent]) continue;
    if (bg.area[id] < minArea) {
      specks++;
      continue;
    }
    holeParent[id] = parent;
    holes++;
  }

  if (regions + holes > MAX_TRACE_REGIONS) {
    return refuse(
      `this picture breaks into ${regions + holes} separate shapes at threshold ${
        opts.threshold ?? DEFAULT_TRACE_THRESHOLD
      }. That is a photograph, not a line drawing: tracing it would produce more nodes than the layer can hold and more than anybody could edit. Raise the speck size, or flatten the picture to line art first.`,
    );
  }
  if (regions === 0) {
    return {
      ok: true,
      strokes: [],
      regions: 0,
      holes: 0,
      specks,
      nodes: 0,
      curves: 0,
      deviation: 0,
      meanDeviation: 0,
      bytes: 0,
      notes: [
        specks > 0
          ? `nothing was traced: every one of the ${specks} shapes found was smaller than ${minArea} px².`
          : 'nothing was traced: at this threshold the picture holds no ink at all.',
      ],
    };
  }

  const stroke = opts.stroke ?? {};
  const brush: StitchKey = stroke.brush ?? 'plain';
  const weight: StrokeWeight = stroke.weight ?? 'hairline';
  const dashed = stroke.dashed ?? false;

  const strokes: VectorStroke[] = [];
  let nodes = 0;
  let curves = 0;
  let deviation = 0;
  let devSum = 0;
  let devCount = 0;
  let capped = false;

  const emit = (c: Contour | null) => {
    // ПУСТОЙ ШТРИХ НЕ РОЖДАЕТСЯ, И ЭТО ДЕРЖИТ ОДИН СТОРОЖ, А НЕ ДВА. `traceOne` отдаёт `null`,
    // когда кусков не вышло ни одного, поэтому у всякого пришедшего сюда контура точек не меньше
    // двух — узел начала плюс узел на каждый кусок. Второй сторож («а вдруг точек меньше двух»)
    // здесь стоял и был СНЯТ: он недостижим, ни одна проба его не краснит, и мёртвая проверка
    // рядом с живой читается как признак того, что живой не доверяют.
    if (!c) return;
    const pts = c.pts.map(([x, y]) => [x / w, y / h] as [number, number]);
    const s: VectorStroke = { tool: 'curve', brush, weight, dashed, pts, segs: c.segs.map((g) => (g ? [g[0] / w, g[1] / h, g[2] / w, g[3] / h] : null)) };
    if (stroke.ink) s.ink = stroke.ink;
    strokes.push(s);
    nodes += c.segs.length;
    for (const g of c.segs) if (g) curves++;
    if (c.error > deviation) deviation = c.error;
    devSum += c.sum;
    devCount += c.count;
  };

  for (let id = 1; id <= fg.count && !capped; id++) {
    if (!keepFg[id]) continue;
    const crack = traceCrack(fg.lab, id, w, h, fg.seedX[id], fg.seedY[id], true);
    emit(traceOne(crack, tol, cornerAngle, TRACE_NODE_CAP));
    if (nodes > TRACE_NODE_CAP) capped = true;
  }
  for (let id = 1; id <= bg.count && !capped; id++) {
    if (!holeParent[id]) continue;
    const crack = traceCrack(bg.lab, id, w, h, bg.seedX[id], bg.seedY[id], false);
    emit(traceOne(crack, tol, cornerAngle, TRACE_NODE_CAP));
    if (nodes > TRACE_NODE_CAP) capped = true;
  }

  if (capped) {
    return refuse(
      `this picture needs more than ${TRACE_NODE_CAP.toLocaleString('en-US')} nodes at a tolerance of ${tol} px — far more than the layer can hold and more than anybody could edit by hand. Nothing was traced. Raise the tolerance, or trace a part of the picture at a time with the lasso.`,
      Math.min(MAX_TRACE_TOLERANCE, Math.round(tol * 4 * 10) / 10),
    );
  }

  // ПОТОЛОК ДОКУМЕНТА МЕРЯЕТСЯ НАСТОЯЩИМ ПИСАТЕЛЕМ, А НЕ ОЦЕНКОЙ ПО ЧИСЛУ УЗЛОВ. Оценка — это
  // вторая копия правила сериализации, и она разойдётся с `writeLayer` на первой же правке
  // формата; тогда движок обещал бы «влезет», а сервер отвечал бы `strokes_too_large`.
  const bytes = new TextEncoder().encode(writeLayer(strokes, ratio)).length;
  if (bytes > budget) {
    // Число узлов гладкой кривой падает примерно как 1/√tol (хорда ≈ √(8·R·tol)), поэтому чтобы
    // ужать результат в k раз, допуск надо поднять примерно в k². Это ОЦЕНКА, и она названа
    // оценкой: автоматически пересчитывать движок не станет — «немного сдвинуть линии, чтобы
    // влезло» это ровно та молчаливая потеря, ради которой здесь стоит отказ.
    const shrink = bytes / Math.max(1, budget);
    const suggest = clamp(
      Math.round(tol * shrink * shrink * 10) / 10,
      MIN_TRACE_TOLERANCE,
      MAX_TRACE_TOLERANCE,
    );
    return refuse(
      `this trace is ${size(bytes)} of strokes against ${size(
        budget,
      )} left in the layer — ${nodes.toLocaleString('en-US')} nodes at a tolerance of ${tol} px. Nothing was added: thinning it here would move lines that are exactly where the picture put them. Trace it coarser, or lasso part of the picture and trace that.`,
      suggest,
    );
  }

  const notes: string[] = [];
  notes.push(
    'every shape came back as its OUTLINE, not as a filled area — a drawn line has two sides, so it returns as a loop around itself. This layer holds threads, not fills.',
  );
  if (holes > 0) {
    notes.push(
      `${holes} hole${holes === 1 ? '' : 's'} came back as ${
        holes === 1 ? 'a contour' : 'contours'
      } of its own — a ring is two outlines, not one.`,
    );
  }
  if (specks > 0) {
    notes.push(
      `${specks} shape${specks === 1 ? '' : 's'} smaller than ${minArea} px² ${
        specks === 1 ? 'was' : 'were'
      } dropped as scanner dirt. Set the speck size to 0 to keep them.`,
    );
  }
  // ОКРУГЛЕНИЕ ФОРМАТА НАЗЫВАЕТСЯ ВСЛУХ И В ТЕХ ЖЕ ПИКСЕЛЯХ. `writeLayer` пишет доли кадра
  // четырьмя знаками; на растре шириной 1600 это сетка в 0.16 px, ниже которой контур не выразим
  // ВООБЩЕ, каким бы мелким ни был допуск. Человек, тянущий допуск к полу и не видящий улучшения,
  // иначе решил бы, что ручка сломана.
  notes.push(
    `the curve sits within ${deviation.toFixed(2)} px of the picture's own edge (${(
      devSum / Math.max(1, devCount)
    ).toFixed(2)} px on average). The stored file rounds every point to 1/10000 of the frame — ${(
      0.0001 * w
    ).toFixed(2)} px here — so a tolerance below that buys nodes, not accuracy.`,
  );

  return {
    ok: true,
    strokes,
    regions,
    holes,
    specks,
    nodes,
    curves,
    deviation,
    meanDeviation: devSum / Math.max(1, devCount),
    bytes,
    notes,
  };
}

// ─────────────────────────────────────────────────────────────────────────────────────────────
// ВТОРАЯ ДВЕРЬ: ОТКРЫТАЯ ЛОМАНАЯ → КУБИКИ
// ─────────────────────────────────────────────────────────────────────────────────────────────

/**
 * ЧТО ЭТА ДВЕРЬ ДЕЛАЕТ И ЗАЧЕМ ОНА ЗДЕСЬ, А НЕ У ВЫЗЫВАЮЩЕГО.
 *
 * `traceRaster` выше кончает ЗАМКНУТЫМ контуром: обвод границы по определению замкнут, и весь
 * путь от трещинной границы до кубиков написан под замкнутость (`thinClosed` режет кольцо на две
 * дуги, `traceOne` разворачивает его начиная с первого угла и повторяет стартовую точку в конце).
 *
 * ОСЕВАЯ И ПУНКТИР ДАЮТ ОТКРЫТУЮ ЛОМАНУЮ — ось штриха, цепочку центроидов стежков, — и им нужны
 * РОВНО ТЕ ЖЕ три шага упрощения в РОВНО ТОМ ЖЕ порядке (отчёт владельца, раздел 5): прореживание
 * RDP → разрез по углам → фит Шнайдера. Вторая копия этих трёх шагов разошлась бы с первой первой
 * же правкой допуска, и разошлась бы МОЛЧА — обе стороны продолжали бы работать, просто рисуя
 * разные кривые из одних и тех же точек. Поэтому здесь ровно сборка, а не арифметика: `simplifyPath`,
 * `turnAt`, `sideTangent`, `fitRun` и `deviateRaw` — те же самые, что у обвода.
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО — СГЛАЖИВАНИЯ (`smoothRun`). Оно существует затем, чтобы снять полпикселя
 * ЛЕСТНИЦЫ у трещинной границы, которая идёт по решётке целых чисел. Вход этой двери по решётке не
 * идёт: осевая приходит с утоньшения, цепочка стежков — с центроидов, и у обеих сглаживание уже
 * своё, по своему правилу. Второе сглаживание поверх чужого — это уже не подпиксельная оценка
 * края, а размывание данных.
 */
export type OpenFit = {
  /** Узлы кривой, в тех же координатах, в которых пришли точки. */
  pts: [number, number][];
  /** По одному на интервал: две ручки кубики или `null` для прямого пролёта. */
  segs: (CubicSeg | null)[];
  /** Наибольшее отклонение готовой кривой от ВХОДНЫХ точек. */
  error: number;
  /** Среднее отклонение по тем же точкам. */
  meanError: number;
};

/** Допуск фита по умолчанию: отчёт называет 0.3–0.5 px для флэтов. */
export const DEFAULT_OPEN_TOLERANCE = 0.4;
/**
 * Порог разреза по углу для ОСЕВОЙ и ПУНКТИРА — 20°, а не 60°, как у обвода.
 * Отчёт: «Разрез по повороту > 20° поднял IoU 0.4518 → 0.6178 при том же числе узлов».
 */
export const DEFAULT_OPEN_CORNER = 20;
/** Потолок точности прореживания. Отчёт: ниже 0.8 платите узлами впустую, выше 1.0 теряете форму. */
export const DEFAULT_OPEN_RDP = 1;

export function fitOpenPath(
  points: readonly (readonly [number, number])[],
  opts: {
    tolerance?: number;
    corner?: number;
    rdp?: number;
    nodeCap?: number;
    /**
     * РАДИУС ПОДПИКСЕЛЬНОЙ ОЦЕНКИ ОСИ, В ТОЧКАХ ЛОМАНОЙ. Ноль — выключено, и это УМОЛЧАНИЕ.
     *
     * Довод в шапке двери («сглаживания здесь нет нарочно») верен для входа, который по решётке
     * целых чисел НЕ ИДЁТ — для цепочки центроидов стежков, у каждого из которых своя субпиксельная
     * позиция. Но у ОСЕВОЙ вход идёт ровно по решётке: утоньшение отдаёт целые координаты пикселей,
     * и на косом участке ось лежит то на полпикселя выше идеальной, то на полпикселя ниже — пилой.
     * Никакая гладкая кривая не пройдёт ближе 0.5 px от ВСЕХ таких точек, а допуск для флэтов равен
     * 0.4 — значит без оценки КАЖДЫЙ прогон делился бы до тех пор, пока куски не станут так коротки,
     * что пройдут как прямые, и осевая вернулась бы МНОГОУГОЛЬНИКОМ из тысяч узлов. Ровно этой
     * ценой тот же вопрос уже был оплачен у обвода границ — см. `SMOOTH_RADIUS`.
     *
     * ЧИСЛО СЧИТАЕТ ВЫЗЫВАЮЩИЙ, потому что только он знает, по какой решётке пришёл его вход.
     * ОТЧЁТНОЕ ОТКЛОНЕНИЕ ПРИ ЭТОМ ОСТАЁТСЯ ПРОТИВ СЫРЫХ ТОЧЕК: сверять кривую с оценкой, из
     * которой её вывели, значило бы удостоверять себя собой.
     */
    smooth?: number;
  } = {},
): OpenFit | null {
  const tol = clamp(
    opts.tolerance ?? DEFAULT_OPEN_TOLERANCE,
    MIN_TRACE_TOLERANCE,
    MAX_TRACE_TOLERANCE,
  );
  const cornerAngle = clamp(opts.corner ?? DEFAULT_OPEN_CORNER, 1, 179);
  const rdpEps = clamp(opts.rdp ?? DEFAULT_OPEN_RDP, 0.01, 100);
  const nodeCap = Math.max(1, Math.round(opts.nodeCap ?? TRACE_NODE_CAP));

  // ПОВТОРЫ СНИМАЮТСЯ ПЕРВЫМИ. Нулевой пролёт даёт вырожденную кубику, наименьшие квадраты по ней
  // возвращают мусор, и мусор этот тихий: кривая просто уезжает в сторону.
  const uniq: [number, number][] = [];
  for (const p of points) {
    const x = Number(p[0]);
    const y = Number(p[1]);
    if (!Number.isFinite(x) || !Number.isFinite(y)) continue;
    const last = uniq[uniq.length - 1];
    if (last && Math.abs(last[0] - x) < 1e-9 && Math.abs(last[1] - y) < 1e-9) continue;
    uniq.push([x, y]);
  }
  const n = uniq.length - 1;
  if (n < 1) return null;

  const px = new Float64Array(n + 1);
  const py = new Float64Array(n + 1);
  for (let i = 0; i <= n; i++) {
    px[i] = uniq[i][0];
    py[i] = uniq[i][1];
  }

  // УГЛЫ ИЩУТСЯ НА ПРОРЕЖЕННОЙ ЛОМАНОЙ, И ТОЛЬКО НА НЕЙ — тот же довод, что у `traceOne`: на сырых
  // точках «угол» значил бы шаг выборки, а не форму.
  const marked = uniq.map(([x, y], i) => ({ x, y, i }));
  const thin = simplifyPath(marked, rdpEps) as { x: number; y: number; i: number }[];
  const marks: number[] = [0];
  for (let k = 1; k + 1 < thin.length; k++) {
    if (turnAt(thin[k - 1], thin[k], thin[k + 1]) >= cornerAngle) {
      const at = thin[k].i;
      if (at > marks[marks.length - 1] && at < n) marks.push(at);
    }
  }
  marks.push(n);

  const window = Math.max(2, Math.round(3 * tol));

  // ПОДПИКСЕЛЬНАЯ ОЦЕНКА ОСИ — ТОЛЬКО ЕСЛИ ВЫЗЫВАЮЩИЙ ЕЁ ПОПРОСИЛ, и окно НЕ ПЕРЕХОДИТ ЧЕРЕЗ УГЛЫ:
  // усреднить прямой угол значило бы срезать его до подгонки, и никакая односторонняя касательная
  // его потом не вернула бы. При выключенной оценке `qx`/`qy` — это те же самые массивы, то есть
  // ни одного лишнего байта и ни одного различия в поведении по умолчанию.
  const rad = Math.max(0, Math.round(opts.smooth ?? 0));
  let qx = px;
  let qy = py;
  if (rad > 0) {
    qx = new Float64Array(n + 1);
    qy = new Float64Array(n + 1);
    for (let s = 0; s + 1 < marks.length; s++) smoothRun(px, py, marks[s], marks[s + 1], rad, qx, qy);
  }

  const pieces: Piece[] = [];
  for (let s = 0; s + 1 < marks.length; s++) {
    const a = marks[s];
    const b = marks[s + 1];
    if (b <= a) continue;
    const [t1x, t1y] = sideTangent(qx, qy, a, +1, window, a, b);
    const [t2x, t2y] = sideTangent(qx, qy, b, -1, window, a, b);
    pieces.push(...fitRun(qx, qy, a, b, t1x, t1y, t2x, t2y, tol, window, nodeCap));
  }
  if (!pieces.length) return null;

  const outPts: [number, number][] = [[qx[0], qy[0]]];
  const segs: (CubicSeg | null)[] = [];
  let error = 0;
  let sum = 0;
  let count = 0;
  let from = 0;
  for (const p of pieces) {
    outPts.push([qx[p.end], qy[p.end]]);
    segs.push(p.seg);
    // ГЕОМЕТРИЯ — ИЗ ОЦЕНКИ ЦЕЛИКОМ, и узлы, и ручки: взять узел из сырого, а ручку из оценки
    // значило бы разорвать кривую в каждом внутреннем разрезе ровно на те полпикселя, ради которых
    // оценка и заведена. ОТКЛОНЕНИЕ — ПРОТИВ СЫРЫХ ТОЧЕК.
    const raw = deviateRaw(px, py, from, p.end, qx[from], qy[from], p.seg, qx[p.end], qy[p.end]);
    if (raw.error > error) error = raw.error;
    sum += raw.sum;
    count += p.end - from + 1;
    from = p.end;
  }
  return { pts: outPts, segs, error, meanError: sum / Math.max(1, count) };
}
