/**
 * КРАСКА ИЛИ ФОН, ПО ПИКСЕЛЮ. Вынесено отдельным экспортом не ради стройности: панели нужен ЖИВОЙ
 * ПРЕДПРОСМОТР порога — человек тянет регулятор и обязан видеть, что именно станет контуром,
 * ДО того как контур посчитан. Второй копии этого правила в модалке быть не должно: она разошлась
 * бы с настоящей бинаризацией первой же правкой, и предпросмотр врал бы.
 *
 * Возвращает 1 или 0 на пиксель, длиной `width * height`.
 */
export function traceInk(src: ImageData, opts: TraceOptions = {}): Uint8Array {
  const w = src.width;
  const h = src.height;
  const n = w * h;
  const px = src.data;
  const out = new Uint8Array(n);

  const threshold = clamp(opts.threshold ?? DEFAULT_TRACE_THRESHOLD, 0, 255);
  const floor = clamp(opts.alphaFloor ?? DEFAULT_TRACE_ALPHA_FLOOR, 0, 255);
  const light = opts.polarity === 'light';
  const byAlpha = opts.channel === 'alpha';
  const sel = opts.selection ?? null;
  if (sel && sel.length !== n) {
    throw new Error('the selection mask does not match the raster it is asked to hold');
  }

  for (let i = 0; i < n; i++) {
    const p = i * 4;
    // ПЕРВАЯ СТУПЕНЬ — АЛЬФА, И ОНА ГЛАВНЕЕ ЦВЕТА. Прозрачный пиксель это фон, а не чёрный: его
    // RGB обнулены самим `getImageData`, и наивное сравнение по яркости обвело бы пустой слой
    // целиком.
    if (px[p + 3] < floor) continue;
    if (byAlpha) {
      out[i] = 1;
      continue;
    }
    // Яркость по BT.601 — та же формула, которой живёт весь редактор.
    const luma = 0.299 * px[p] + 0.587 * px[p + 1] + 0.114 * px[p + 2];
    out[i] = (light ? luma >= threshold : luma <= threshold) ? 1 : 0;
  }

  // ВЫДЕЛЕНИЕ ПЕРЕСЕКАЕТСЯ ПОСЛЕ ПОРОГА, А НЕ ДО. Порог обязан читать настоящие пиксели всюду:
  // иначе одна и та же картинка бинаризовалась бы по-разному от того, что обвели лассо.
  if (sel) for (let i = 0; i < n; i++) if (sel[i] < TRACE_SELECTION_FLOOR) out[i] = 0;
  return out;
}

