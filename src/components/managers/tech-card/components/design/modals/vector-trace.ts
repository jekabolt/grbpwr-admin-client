/**
 * ПОРОГ ЯРКОСТИ. Середина шкалы, и это не «просто середина»: чертёж — это тёмная краска на светлом
 * поле, и на сглаженном крае половина покрытия приходится ровно на половину яркости. Значит
 * граница ложится туда, где край и есть, с точностью лучше пикселя.
 */
export const DEFAULT_TRACE_THRESHOLD = 128;

/**
 * ПОРОГ АЛЬФЫ — первая ступень решения, и она главнее яркости. Половина: у сглаженного края
 * покрытие проходит через 50 % ровно на геометрической границе.
 */
export const DEFAULT_TRACE_ALPHA_FLOOR = 128;

/**
 * ДОПУСК СГЛАЖИВАНИЯ В ПИКСЕЛЯХ РАСТРА — насколько кривой позволено отойти от границы краски.
 *
 * ЕДИНИЦА ВЫБРАНА НЕ НА ГЛАЗ. Цифровой отрезок (то, во что превращается прямая на пиксельной
 * сетке) отходит от своей идеальной прямой МЕНЬШЕ ЧЕМ НА ПИКСЕЛЬ — это его определяющее свойство
 * («chord property»). Поэтому допуск 1.0 съедает лестницу любого наклона целиком и возвращает
 * прямую сторону прямой, а не «почти прямой с дрожью». Допуск мельче начинает ОБВОДИТЬ САМУ
 * ЛЕСТНИЦУ: узлов становится втрое больше, а точнее контур не становится — он становится точнее
 * ПИКСЕЛЕЙ, которых человек не рисовал.
 */
export const DEFAULT_TRACE_TOLERANCE = 1;

/** Концы регулятора допуска. Ниже пола обводится сетка, выше потолка — уже не тот рисунок. */
export const MIN_TRACE_TOLERANCE = 0.2;
export const MAX_TRACE_TOLERANCE = 8;

/**
 * МИНИМАЛЬНАЯ ПЛОЩАДЬ ОБЛАСТИ В ПИКСЕЛЯХ. Восемь — это «мельче, чем 3×3»: у такого пятна нет
 * формы вовсе, его контур это квадратик из четырёх узлов, и скан приносит их сотнями. Ноль
 * выключает отсев: тогда крапина в один пиксель — законная область и вернётся квадратом.
 *
 * Порог одинаково стоит и на краске, и на ДЫРКАХ: белая точка в залитом пятне — это тот же сор.
 */
export const DEFAULT_TRACE_MIN_AREA = 8;

/**
 * УГОЛ, ОТ КОТОРОГО ПОВОРОТ СЧИТАЕТСЯ УГЛОМ, А НЕ КРИВИЗНОЙ, в градусах.
 *
 * Шестьдесят — не круглое число, а граница между двумя замеренными случаями. Прямой угол чертежа
 * это 90°, и он обязан остаться острым. А прорежённая ОКРУЖНОСТЬ поворачивает на своих вершинах
 * примерно на √(8·tol/R) радиан: при допуске 1 это 15° для R = 120, 36° для R = 20 и 57° для
 * R = 8. То есть всё, что человек назовёт кругом, ложится ПОД шестьдесят, а прямой угол — над.
 *
 * Поворот мягче порога не теряется совсем: подгонка всё равно разобьёт кривую в этом месте, если
 * одной кубикой её не описать, — просто стык выйдет гладким, а не острым. Цена названа вслух:
 * настоящий надрез в 45° вернётся скруглённым в пределах допуска.
 */
export const DEFAULT_TRACE_CORNER = 60;

/**
 * ПОТОЛОК ЧИСЛА ОБЛАСТЕЙ. Фотография, прогнанная через порог, рассыпается на десятки тысяч пятен,
 * и обводить их все — это минуты работы ради результата, который всё равно не влезет в документ.
 * Отказ ДО обхода границ, словами, дешевле для всех.
 */
export const MAX_TRACE_REGIONS = 4000;

/**
 * ЖЁСТКИЙ ПОТОЛОК УЗЛОВ. Страховка от патологического разбиения (допуск ниже сетки на шумном
 * скане): считать дальше незачем, документ такого всё равно не примет. Число заведомо выше того,
 * что влезает в 512 КБ, — то есть сюда упирается только явная патология, а нормальный перебор
 * ловится честным замером байтов.
 */
export const TRACE_NODE_CAP = 200000;

/**
 * ПОЛ ПОКРЫТИЯ ВЫДЕЛЕНИЯ. Растушёвка у бинарного решения смысла не имеет: пиксель либо краска,
 * либо нет. Мягкий край лассо режется по своей половине — то есть ровно по той линии, которую
 * человек считает границей области.
 */
export const TRACE_SELECTION_FLOOR = 128;

export type TraceOptions = {
  /** Яркость 0..255, ниже которой (при `polarity: 'dark'`) непрозрачный пиксель — краска. */
  threshold?: number;
  /** Что считать краской: тёмное (чертёж на белом) или светлое (выворотка, белое по чёрному). */
  polarity?: 'dark' | 'light';
  /**
   * По чему судить. `luma` — по яркости, с альфой как первой ступенью (умолчание, чертёж).
   * `alpha` — по одной непрозрачности, чем бы ни был цвет: это для слоя, у которого фон
   * НАСТОЯЩАЯ дырка, а краска может быть и белой.
   *
   * АВТОВЫБОРА ЗДЕСЬ НЕТ НАРОЧНО. Догадка «похоже, тут прозрачный фон» ошибается молча и возвращает
   * контур всей плиты вместо рисунка; названный режим ошибается вслух и чинится одним щелчком.
   */
  channel?: 'luma' | 'alpha';
  /** Альфа 0..255, ниже которой пиксель — фон, чем бы ни были его RGB. */
  alphaFloor?: number;
  /** Допуск в пикселях растра: насколько кривой позволено отойти от границы краски. */
  tolerance?: number;
  /** Область мельче этого числа пикселей отбрасывается как сор. Ноль — не отбрасывать ничего. */
  minArea?: number;
  /** Поворот от этого числа градусов — угол, а не кривизна. */
  cornerAngle?: number;
  /**
   * Выделение как покрытие 0..255 на пиксель, длиной ровно `width * height`.
   *
   * ЧИТАТЬ ЗА НЕГО МОЖНО И НУЖНО — порог считается по НАСТОЯЩИМ пикселям всюду, а не по
   * вырезанному куску, иначе одна и та же картинка бинаризовалась бы по-разному в зависимости от
   * того, что обвели лассо. А МЕНЯТЬ (то есть выпускать геометрию) — только внутри: маска
   * пересекается с краской, поэтому фигура, пересекающая границу лассо, возвращается ОБРЕЗАННОЙ,
   * и край лассо становится частью её контура. Ни одна точка результата не лежит снаружи.
   */
  selection?: Uint8Array | null;
  /**
   * Сколько байт документа осталось под эти штрихи. Умолчание — весь потолок `MAX_STROKES_BYTES`;
   * модалка, у которой в слое уже что-то лежит, обязана вычесть своё и передать остаток.
   *
   * Замер идёт настоящим `writeLayer` по ОДНИМ ТОЛЬКО обводкам, поэтому в него дважды попадает
   * обёртка документа (`{"v":2,"ratio":…,"strokes":[…]}`) — три десятка байт. Ошибка эта в
   * СТОРОНУ ОТКАЗА, то есть движок скорее откажет чуть раньше, чем пообещает то, что сервер
   * отвергнет; обратная ошибка стоила бы человеку сохранения.
   */
  budgetBytes?: number;
  /** Пропорция кадра — нужна только для честного замера байтов. Умолчание — пропорция растра. */
  ratio?: number;
  /** Чем рисовать обводку. Умолчание — простая линия волосяной толщины без своего цвета. */
  stroke?: { brush?: StitchKey; weight?: StrokeWeight; dashed?: boolean; ink?: string };
};

export type TraceRefusal = {
  ok: false;
  /** Одно предложение теми словами, которые покажет панель. Никаких кодов и стеков. */
  reason: string;
  /** Допуск, при котором результат, скорее всего, влез бы. Оценка, и названа оценкой. */
  suggestTolerance?: number;
};

export type TraceReading = {
  ok: true;
  strokes: VectorStroke[];
  /** Обведённых областей краски и отдельно — дырок в них. */
  regions: number;
  holes: number;
  /** Отброшено как сор: областей краски и дырок. */
  specks: number;
  /** Узлов всего (это интервалы кривой — то, что человек будет двигать руками) и из них кривых. */
  nodes: number;
  curves: number;
  /**
   * ЗАМЕРЕННОЕ отклонение кривой от границы краски, в пикселях растра: максимум и среднее.
   * Считается по тем же точкам, по которым шла подгонка, то есть по самой границе, — ДО
   * округления формата в четыре знака (о нём сказано в шапке и в `notes`).
   */
  deviation: number;
  meanDeviation: number;
  /** Что эти штрихи весят на проводе, против потолка в 512 КБ. */
  bytes: number;
  /** Честные замечания о том, чего обводка не умеет. */
  notes: string[];
};

export type TraceResult = TraceReading | TraceRefusal;

const refuse = (reason: string, suggestTolerance?: number): TraceRefusal => ({
  ok: false,
  reason,
  ...(suggestTolerance === undefined ? {} : { suggestTolerance }),
});

const clamp = (n: number, lo: number, hi: number) => (n < lo ? lo : n > hi ? hi : n);

/**
 * Размер словами. Килобайты, ОКРУГЛЁННЫЕ ВНИЗ ДО НУЛЯ, превращали отказ в «0 KB против 0 KB» —
 * предложение, из которого человек не может узнать ровно ничего.
 *
 * ЭКСПОРТИРОВАН РАДИ ПАНЕЛИ, А НЕ РАДИ СТРОЙНОСТИ. Дверь печатает вес удавшейся обводки тем же
 * правилом, каким движок печатает вес отказавшей; вторая копия этого правила снаружи вернула бы
 * ровно тот «0 KB», ради которого оно и написано (замерено: обводка прямоугольника весит 150 байт,
 * и наивные килобайты показывали её как «0 KB»).
 */
export const traceSize = (bytes: number) =>
  bytes < 1024 ? `${bytes} bytes` : `${(bytes / 1024).toFixed(bytes < 10240 ? 1 : 0)} KB`;

/** Прежнее имя внутри файла — чтобы отказы читались как раньше. */
const size = traceSize;

