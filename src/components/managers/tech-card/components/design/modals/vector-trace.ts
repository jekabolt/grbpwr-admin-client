/**
 * ЛОКАЛЬНАЯ ТРАССИРОВКА РАСТРА В КРИВЫЕ — вторая, принципиально иная половина «растр → вектор».
 *
 * ── ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ ──────────────────────────────────────────────────────────────────────
 *
 * Рядом ЖИЛ второй инструмент — платная машинная ПЕРЕРИСОВКА (`StartDesignRun(kind='vector')`):
 * модель рисовала одежду ЗАНОВО, держа утверждённый растр лишь композиционной ссылкой, и манжета
 * могла вернуться другой манжетой. Владелец снял её с пути целиком (H-1, круг 14), и с круга 14
 * трассировка — ЕДИНСТВЕННАЯ дорога «растр → вектор» в этом редакторе.
 *
 * Здесь: ни одного запроса, ни цента, и контур ТОТ ЖЕ, что на растре, с названным числом в
 * пикселях, насколько он от него отходит. Ни одна линия не появляется и не исчезает: то, что
 * нарисовано, обводится; то, чего нет, не выдумывается. Растр СЫРОЙ (фотография, грязный скан)
 * этим движком честно даст вектор всей грязи — но выбор «чистый чертёж вместо этого» теперь
 * делает человек кистью, а не машина за деньги.
 *
 * ── ВЫБРАННЫЙ АЛГОРИТМ: РАЗБОР ГРАНИЦ ПО ШКОЛЕ POTRACE + ПОДГОНКА ПО ШНАЙДЕРУ ────────────────
 *
 * Четыре шага, и каждый отвечает ровно за одно:
 *
 *   1. БИНАРИЗАЦИЯ. Пиксель — краска или фон. Прозрачность решается ОТДЕЛЬНЫМ порогом, см. ниже.
 *
 *   2. РАЗБОР ГРАНИЦ ПО ТРЕЩИНАМ (crack boundary), ровно как у potrace. Обход идёт НЕ по центрам
 *      пикселей, а по СТЫКАМ между «внутри» и «снаружи» — по решётке углов пикселей. Это не вкус:
 *      цепной код по центрам вырождается на линии толщиной в один пиксель (у неё нет «внутри»), а
 *      обход по трещинам даёт замкнутый прямоугольный многоугольник при любой толщине. Он же
 *      снимает вопрос «где именно проходит граница»: она проходит по стыку, и это ТОЧНЫЙ ответ, а
 *      не приближение.
 *
 *   3. ПРОРЕЖИВАНИЕ ДУГЛАСА–ПОЙКЕРА с допуском в ПИКСЕЛЯХ. Даёт скелет многоугольника, по которому
 *      находятся УГЛЫ, — и только для этого. Сама кривая гонится не по нему, см. шаг 4.
 *
 *   4. ПОДГОНКА КУБИК ПО ШНАЙДЕРУ (Graphics Gems, «An Algorithm for Automatically Fitting
 *      Digitized Curves»): метод наименьших квадратов по длине хорды, уточнение параметризации
 *      Ньютоном, и РАЗБИЕНИЕ В ХУДШЕЙ ТОЧКЕ, пока ошибка не уложится в допуск.
 *
 * ПОЧЕМУ ШНАЙДЕР, А НЕ СОБСТВЕННОЕ СГЛАЖИВАНИЕ POTRACE. У potrace последний шаг — эвристика с
 * параметром alpha: она даёт красивый результат, но НЕ ОГРАНИЧИВАЕТ ОШИБКУ. А единственное
 * преимущество этого инструмента перед перерисовкой — верность контура, и его надо не обещать, а
 * ДЕРЖАТЬ ЧИСЛОМ. У Шнайдера критерий разбиения — это и есть максимальное отклонение от исходных
 * точек, то есть ровно та величина, которую мы обязаны назвать. Он же сам подбирает число узлов
 * под кривизну: окружность выходит четырьмя кубиками, прямая сторона — одним отрезком.
 *
 * ПОЧЕМУ ПОДГОНКА ИДЁТ ПО ПОЛНОМУ КОНТУРУ, А НЕ ПО ПРОРЕЖЕННОМУ. Ошибка меряется в точках выборки;
 * если выборкой сделать прорежённый многоугольник, кривая сможет выпучиться МЕЖДУ его далеко
 * стоящими вершинами, и замер этого не увидит. Точки трещинного контура стоят через один пиксель —
 * между ними кубике негде спрятаться. Прорежённый многоугольник участвует ТОЛЬКО как искатель
 * углов; геометрию считает подгонка по всем точкам.
 *
 * ── ЧЕМ ПЛАТИМ, ВСЛУХ ────────────────────────────────────────────────────────────────────────
 *
 *   • ДВОЙНОЙ КОНТУР. Обход границ обводит ОБЛАСТЬ, а не линию. Штрих чертежа толщиной 3 px — это
 *     область, у которой две стороны, и она вернётся ЗАМКНУТОЙ ПЕТЛЁЙ вокруг штриха, а не одной
 *     линией по его середине. Это верно (контур ровно там, где кончается краска) и это неудобно:
 *     чтобы подвинуть линию, придётся двигать обе её стороны. Настоящее лекарство — второй режим,
 *     осевой (centerline, по скелету), и его здесь НЕТ; см. хвост файла и отчёт.
 *     Отказаться от обхода границ в его пользу нельзя: у буквы «о» ДВЕ границы, у осевой линии —
 *     одна, а требование «кольцо даёт две границы» — прямое.
 *
 *   • ДОКУМЕНТ СЛОЯ НЕ ЗНАЕТ ЗАЛИВОК. `VectorStroke` — это нить: кисть, толщина, пунктир. Поля
 *     «залить» в нём нет вовсе. Поэтому чёрное пятно возвращается СВОИМ ОЧЕРТАНИЕМ, а не чёрным
 *     пятном. Заливка живёт в пиксельном канале (`vector-fill.ts`), и это разные материалы.
 *
 *   • УГОЛ МЯГЧЕ `TRACE_CORNER` СГЛАЖИВАЕТСЯ. Порог назван числом и вынесен в ручку, но всякий
 *     порог кого-то режет: надрез в 45° вернётся скруглённым в пределах допуска.
 *
 *   • ОКРУГЛЕНИЕ ФОРМАТА. `writeLayer` пишет доли кадра с четырьмя знаками — на растре шириной
 *     1600 это сетка в 0.16 px. Ниже неё контур не выразим В ПРИНЦИПЕ, каким бы точным ни был
 *     допуск, и допуск мельче этого числа покупает только узлы. Замер это подтверждает.
 *
 * ── ПРОЗРАЧНОСТЬ: АЛЬФА 0 — ЗАКОННЫЙ ФОН, А НЕ БЕЛЫЙ И НЕ ЧЁРНЫЙ ─────────────────────────────
 *
 * Тот же довод, что у ведра и у лечилки, и та же цена ошибки. `getImageData` отдаёт RGB полностью
 * прозрачного пикселя ОБНУЛЁННЫМ, поэтому «прозрачно» при наивном сравнении по яркости
 * неотличимо от «черно» — и трассировка пустого слоя вернула бы контур ВСЕЙ ПЛИТЫ, залитой
 * краской. Поэтому решение двухступенчатое и первая ступень — альфа: пиксель ниже `alphaFloor`
 * это фон, чем бы ни были его RGB. И только у достаточно непрозрачного смотрят яркость.
 *
 * Отсюда же берётся правильное поведение на сглаженном крае чёрного штриха по прозрачному: там
 * RGB (0,0,0), а альфа плывёт от 0 до 255, и граница ложится ровно на её половину — то есть туда,
 * где край и находится.
 *
 * ── БЕЗ РЕКУРСИИ ПО ПИКСЕЛЯМ ─────────────────────────────────────────────────────────────────
 *
 * Разметка связных областей идёт ПОСТРОЧНО, со своим стеком `Int32Array`, в который кладутся
 * зародыши прогонов, — как в `bucketFill`. Рекурсия по соседям на плите 1600×2000 сняла бы поток,
 * и человек увидел бы не «трассировка не смогла», а «редактор упал». Разбиение подгонки — тоже
 * явный стек диапазонов, а не рекурсивный вызов: контур в четверть миллиона точек даёт дерево
 * разбиений, чью глубину никто не обещал.
 *
 * ── ПОЧЕМУ НЕ ЧЕРЕЗ СТРОКУ `d` ───────────────────────────────────────────────────────────────
 *
 * Соблазн был понятный: печатать кубики строкой `d` и пропускать её через разборщик чужого SVG.
 * Приёмник кубических сегментов — это НЕ разборщик пути, а `VectorStroke.segs`: разборщик отдаёт
 * координаты ФАЙЛА, и перевод в доли кадра всё равно делался бы здесь. Повторное использование не
 * покупало ни одного правила — только печать десятичных чисел, их обратный разбор и потерю
 * точности на этом круге. Кубики строятся сразу в той форме, которую документ и хранит. (Сам
 * разборщик удалён вместе с платным прогоном, H-1, — соблазна больше нет и физически.)
 */

