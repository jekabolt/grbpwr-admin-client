/** Точка многоугольника, помнящая свой номер в исходном контуре. */
type Marked = ShapePoint & { i: number };

/**
 * СХЛОПНУТЬ КОЛЛИНЕАРНЫЕ ПРОГОНЫ ЗАМКНУТОГО ЛОМАНОГО КОНТУРА. Шаги здесь единичные и осевые,
 * поэтому «вершина» — это ровно смена направления, и проверка стоит один разряд, а не косое
 * произведение. Обход циклический: иначе стартовая точка осталась бы в середине прямой стороны и
 * прямоугольник приехал бы пятиугольником.
 *
 * Это ЧИСТО ДЕШЁВЫЙ ШАГ и он ничего не приближает: выброшенные точки лежат ТОЧНО на отрезке между
 * оставшимися. Он существует, чтобы прореживанию досталось в десять раз меньше работы.
 */
function collapseRuns(b: { x: Int32Array; y: Int32Array; n: number }): Marked[] {
  const { x, y, n } = b;
  const out: Marked[] = [];
  if (n < 3) {
    for (let i = 0; i < n; i++) out.push({ x: x[i], y: y[i], i });
    return out;
  }
  for (let i = 0; i < n; i++) {
    const p = (i + n - 1) % n;
    const q = (i + 1) % n;
    const inDx = x[i] - x[p];
    const inDy = y[i] - y[p];
    const outDx = x[q] - x[i];
    const outDy = y[q] - y[i];
    if (inDx !== outDx || inDy !== outDy) out.push({ x: x[i], y: y[i], i });
  }
  return out;
}

/**
 * ПРОРЕЖИВАНИЕ ЗАМКНУТОГО КОНТУРА. Дуглас–Пойкер держит ДВА конца неподвижными, поэтому замкнутый
 * контур разрезается на две дуги по паре опорных точек — самой далёкой от центра тяжести и самой
 * далёкой от неё. Обе почти всегда оказываются настоящими углами (у прямоугольника — ровно
 * противоположными углами), то есть разрез проходит там, где вершина и так обязана остаться.
 *
 * САМО ПРАВИЛО НЕ ПОВТОРЯЕТСЯ: зовётся `simplifyPath` из `ui/components/annotation/geometry` —
 * тот же Дуглас–Пойкер со своим явным стеком, которым уже живут выноски и след пера. Вторая копия
 * разошлась бы с ним первой же правкой, и «прорежено» значило бы в двух местах разное.
 *
 * Номера точек переживают прореживание: `simplifyPath` возвращает ТЕ ЖЕ объекты (`pts.filter`), а
 * они помнят свой индекс. Искать их обратно по координатам было бы неверно — самокасающийся
 * контур содержит одну и ту же точку дважды.
 */
function thinClosed(pts: Marked[], tol: number): Marked[] {
  const m = pts.length;
  if (m <= 4) return pts.slice();
  let cx = 0;
  let cy = 0;
  for (const p of pts) {
    cx += p.x;
    cy += p.y;
  }
  cx /= m;
  cy /= m;
  let a = 0;
  let best = -1;
  for (let i = 0; i < m; i++) {
    const d = (pts[i].x - cx) ** 2 + (pts[i].y - cy) ** 2;
    if (d > best) {
      best = d;
      a = i;
    }
  }
  let b = a;
  best = -1;
  for (let i = 0; i < m; i++) {
    const d = (pts[i].x - pts[a].x) ** 2 + (pts[i].y - pts[a].y) ** 2;
    if (d > best) {
      best = d;
      b = i;
    }
  }
  if (b === a) return pts.slice();
  const first: Marked[] = [];
  for (let i = a; ; i = (i + 1) % m) {
    first.push(pts[i]);
    if (i === b) break;
  }
  const second: Marked[] = [];
  for (let i = b; ; i = (i + 1) % m) {
    second.push(pts[i]);
    if (i === a) break;
  }
  const one = simplifyPath(first, tol) as Marked[];
  const two = simplifyPath(second, tol) as Marked[];
  // Стыки принадлежат обеим дугам — концы склеиваются, а не дублируются.
  return one.concat(two.slice(1, two.length - 1));
}

/** Поворот в вершине `b` ломаной `a → b → c`, в градусах, 0..180. */
function turnAt(a: ShapePoint, b: ShapePoint, c: ShapePoint): number {
  const ux = b.x - a.x;
  const uy = b.y - a.y;
  const vx = c.x - b.x;
  const vy = c.y - b.y;
  const lu = Math.hypot(ux, uy);
  const lv = Math.hypot(vx, vy);
  if (lu === 0 || lv === 0) return 0;
  const cosine = clamp((ux * vx + uy * vy) / (lu * lv), -1, 1);
  return (Math.acos(cosine) * 180) / Math.PI;
}

