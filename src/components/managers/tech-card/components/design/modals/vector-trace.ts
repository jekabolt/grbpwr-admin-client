type Labels = {
  lab: Int32Array;
  count: number;
  /** Площадь области с номером `id`, по индексу `id`. Нулевой элемент не используется. */
  area: Int32Array;
  /** Верхняя-левая точка области — с неё начинается обход границы, и только с неё. */
  seedX: Int32Array;
  seedY: Int32Array;
  /** Область касается края холста. Для фона это и значит «это не дырка, это наружное поле». */
  edge: Uint8Array;
};

/**
 * РАЗМЕТКА СВЯЗНЫХ ОБЛАСТЕЙ, ПОСТРОЧНАЯ, СО СВОИМ СТЕКОМ.
 *
 * Стек — `Int32Array` с удвоением, и в него кладутся ЗАРОДЫШИ ПРОГОНОВ, а не пиксели: у заливки
 * (`bucketFill`) это уже сделано ровно так и по той же причине — рекурсия по соседям на плите
 * 1600×2000 снимает поток, и это выглядит как «редактор упал», а не как «не смогли».
 *
 * СВЯЗНОСТЬ — ПАРА, А НЕ ВКУС. Краска берётся восьмисвязной (диагональная волосяная линия обязана
 * остаться ОДНОЙ линией), и тогда фон обязан быть четырёхсвязным — иначе граница между ними
 * определена противоречиво и дырка может «протечь» наружу через диагональ.
 */
function labelRegions(
  mask: Uint8Array,
  w: number,
  h: number,
  want: number,
  eight: boolean,
): Labels {
  const n = w * h;
  const lab = new Int32Array(n);
  const area: number[] = [0];
  const seedX: number[] = [0];
  const seedY: number[] = [0];
  const edge: number[] = [0];
  let stack = new Int32Array(1024);
  let top = 0;
  const push = (x: number, y: number) => {
    if (top + 2 > stack.length) {
      const bigger = new Int32Array(stack.length * 2);
      bigger.set(stack);
      stack = bigger;
    }
    stack[top++] = x;
    stack[top++] = y;
  };

  let id = 0;
  for (let sy = 0; sy < h; sy++) {
    for (let sx = 0; sx < w; sx++) {
      if (mask[sy * w + sx] !== want || lab[sy * w + sx] !== 0) continue;
      id++;
      let acc = 0;
      let minY = sy;
      let minX = sx;
      let touches = 0;
      top = 0;
      push(sx, sy);
      while (top > 0) {
        const y = stack[--top];
        const x = stack[--top];
        const row = y * w;
        if (mask[row + x] !== want || lab[row + x] !== 0) continue;
        let xl = x;
        while (xl - 1 >= 0 && mask[row + xl - 1] === want && lab[row + xl - 1] === 0) xl--;
        let xr = x;
        while (xr + 1 < w && mask[row + xr + 1] === want && lab[row + xr + 1] === 0) xr++;
        for (let k = xl; k <= xr; k++) lab[row + k] = id;
        acc += xr - xl + 1;
        if (y < minY || (y === minY && xl < minX)) {
          minY = y;
          minX = xl;
        }
        if (y === 0 || y === h - 1 || xl === 0 || xr === w - 1) touches = 1;
        // Соседние строки: восьмисвязность расширяет полосу поиска на пиксель в каждую сторону.
        const pad = eight ? 1 : 0;
        const from = Math.max(0, xl - pad);
        const to = Math.min(w - 1, xr + pad);
        for (let dy = -1; dy <= 1; dy += 2) {
          const ny = y + dy;
          if (ny < 0 || ny >= h) continue;
          const nrow = ny * w;
          let k = from;
          while (k <= to) {
            if (mask[nrow + k] === want && lab[nrow + k] === 0) {
              push(k, ny);
              while (k <= to && mask[nrow + k] === want) k++;
            }
            k++;
          }
        }
      }
      area.push(acc);
      seedX.push(minX);
      seedY.push(minY);
      edge.push(touches);
    }
  }

  return {
    lab,
    count: id,
    area: Int32Array.from(area),
    seedX: Int32Array.from(seedX),
    seedY: Int32Array.from(seedY),
    edge: Uint8Array.from(edge),
  };
}

/** Направления обхода: 0 вправо, 1 вниз, 2 влево, 3 вверх. Поворот направо — `(d + 1) & 3`. */
const DX = [1, 0, -1, 0];
const DY = [0, 1, 0, -1];

/**
 * ОБХОД ГРАНИЦЫ ПО ТРЕЩИНАМ. Идём по решётке УГЛОВ пикселей, держа область СПРАВА от движения.
 *
 * На каждом углу смотрят ровно две клетки — переднюю левую и переднюю правую относительно хода:
 *
 *   справа пусто                  → поворот НАПРАВО  (стена ушла из-под руки, доворачиваем к ней)
 *   справа своё, слева пусто      → ПРЯМО            (стена продолжается)
 *   справа своё, слева своё       → поворот НАЛЕВО   (стена встала поперёк)
 *   справа пусто, слева своё      → ДИАГОНАЛЬ, и здесь решает связность:
 *                                   восьмисвязная краска обходит обе клетки (налево),
 *                                   четырёхсвязный фон разделяет их (направо).
 *
 * Старт — верхний-левый угол верхнего-левого пикселя области, ходом ВПРАВО: над этим пикселем по
 * построению нет своих, значит первое решение всегда «прямо», и стартовое направление известно
 * без проверки. Остановка — возврат в стартовый угол С ТЕМ ЖЕ исходящим направлением: одной лишь
 * точки мало, самокасающийся контур проходит через свой перешеек дважды и закончился бы там рано.
 *
 * Возвращает УГЛЫ, каждый по разу, шагами по единице. Первая точка не повторяется в конце.
 */
function traceCrack(
  lab: Int32Array,
  id: number,
  w: number,
  h: number,
  sx: number,
  sy: number,
  eight: boolean,
): { x: Int32Array; y: Int32Array; n: number } {
  const inside = (px: number, py: number) =>
    px >= 0 && py >= 0 && px < w && py < h && lab[py * w + px] === id;

  const nextDir = (x: number, y: number, d: number): number => {
    let lx: number;
    let ly: number;
    let rx: number;
    let ry: number;
    if (d === 0) {
      lx = x;
      ly = y - 1;
      rx = x;
      ry = y;
    } else if (d === 1) {
      lx = x;
      ly = y;
      rx = x - 1;
      ry = y;
    } else if (d === 2) {
      lx = x - 1;
      ly = y;
      rx = x - 1;
      ry = y - 1;
    } else {
      lx = x - 1;
      ly = y - 1;
      rx = x;
      ry = y - 1;
    }
    const R = inside(rx, ry);
    const L = inside(lx, ly);
    if (R) return L ? (d + 3) & 3 : d;
    if (L) return eight ? (d + 3) & 3 : (d + 1) & 3;
    return (d + 1) & 3;
  };

  let cap = 256;
  let bx = new Int32Array(cap);
  let by = new Int32Array(cap);
  let n = 0;
  const put = (x: number, y: number) => {
    if (n === cap) {
      cap *= 2;
      const nx = new Int32Array(cap);
      const ny = new Int32Array(cap);
      nx.set(bx);
      ny.set(by);
      bx = nx;
      by = ny;
    }
    bx[n] = x;
    by[n] = y;
    n++;
  };

  const d0 = nextDir(sx, sy, 0);
  let x = sx;
  let y = sy;
  let d = d0;
  // Периметр трещинной границы не превышает 2·(w+1)·(h+1); потолок стоит сторожем от порчи
  // разметки, а не как настоящая граница — при исправных данных цикл до него не доходит.
  const guard = 2 * (w + 1) * (h + 1) + 8;
  for (let steps = 0; steps <= guard; steps++) {
    put(x, y);
    x += DX[d];
    y += DY[d];
    const nd = nextDir(x, y, d);
    if (x === sx && y === sy && nd === d0) break;
    d = nd;
  }
  return { x: bx, y: by, n };
}

