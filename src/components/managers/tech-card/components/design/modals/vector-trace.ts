type Piece = { end: number; seg: CubicSeg | null; error: number; sum: number; count: number };

/**
 * ПОДОГНАТЬ ОДИН ПРОГОН `a..b` КУБИКАМИ, разбивая в худшей точке, пока ошибка не уложится в допуск.
 *
 * РАЗБИЕНИЕ ИДЁТ ЧЕРЕЗ ЯВНЫЙ СТЕК ДИАПАЗОНОВ. Рекурсия здесь не по пикселям, но глубину дерева
 * разбиений на контуре в четверть миллиона точек никто не обещал, а «редактор упал» выглядит
 * одинаково независимо от того, что именно переполнило стек.
 *
 * КАСАТЕЛЬНАЯ НА ВНУТРЕННЕМ РАЗРЕЗЕ — ДВУСТОРОННЯЯ. Прогон уже нарезан по УГЛАМ (см. `traceOne`),
 * значит внутри него углов нет по построению, и односторонние касательные посадили бы на гладкое
 * место излом. А на концах прогона — наоборот, они односторонние, и именно поэтому прямой угол
 * остаётся острым, а не скругляется.
 */
function fitRun(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  t1x: number,
  t1y: number,
  t2x: number,
  t2y: number,
  tol: number,
  window: number,
  cap: number,
): Piece[] {
  const out: Piece[] = [];
  const u = new Float64Array(b - a + 1);
  // Стек диапазонов кладётся так, чтобы разбор шёл СЛЕВА НАПРАВО: куски обязаны выйти в порядке
  // контура, иначе штрих соберётся из тех же кусков в чужой последовательности.
  const stack: { a: number; b: number; t1x: number; t1y: number; t2x: number; t2y: number }[] = [
    { a, b, t1x, t1y, t2x, t2y },
  ];
  while (stack.length) {
    const job = stack.pop() as (typeof stack)[number];
    if (out.length > cap) break;
    const len = job.b - job.a;
    if (len <= 0) continue;

    // Прямая — первой: она и дешевле, и это ОТДЕЛЬНОЕ утверждение о форме, а не кривая с нулевой
    // кривизной.
    const line = straightError(px, py, job.a, job.b);
    if (line.error <= tol) {
      out.push({ end: job.b, seg: null, error: line.error, sum: line.sum, count: len + 1 });
      continue;
    }
    if (len === 1) {
      out.push({ end: job.b, seg: null, error: line.error, sum: line.sum, count: 2 });
      continue;
    }

    const view = u.subarray(0, len + 1);
    chordParam(px, py, job.a, job.b, view);
    let seg = fitOne(px, py, job.a, job.b, job.t1x, job.t1y, job.t2x, job.t2y, view);
    let w = worstOf(px, py, job.a, job.b, seg, view);
    for (let pass = 0; pass < NEWTON_PASSES && w.error > tol; pass++) {
      reparam(px, py, job.a, job.b, seg, view);
      const next = fitOne(px, py, job.a, job.b, job.t1x, job.t1y, job.t2x, job.t2y, view);
      const nw = worstOf(px, py, job.a, job.b, next, view);
      if (nw.error >= w.error) break;
      seg = next;
      w = nw;
    }
    if (w.error <= tol) {
      out.push({ end: job.b, seg, error: w.error, sum: w.sum, count: len + 1 });
      continue;
    }

    let cut = w.at;
    if (cut <= job.a || cut >= job.b) cut = job.a + (len >> 1);
    // Двусторонняя касательная в разрезе: окно берётся симметрично и упирается в концы куска.
    const q = Math.max(1, Math.min(window, cut - job.a, job.b - cut));
    let mx = px[cut + q] - px[cut - q];
    let my = py[cut + q] - py[cut - q];
    let ml = Math.hypot(mx, my);
    if (ml < EPS) {
      mx = px[job.b] - px[job.a];
      my = py[job.b] - py[job.a];
      ml = Math.hypot(mx, my) || 1;
    }
    mx /= ml;
    my /= ml;
    stack.push({ a: cut, b: job.b, t1x: mx, t1y: my, t2x: job.t2x, t2y: job.t2y });
    stack.push({ a: job.a, b: cut, t1x: job.t1x, t1y: job.t1y, t2x: -mx, t2y: -my });
  }
  return out;
}

/** Односторонняя касательная из точки `k` в сторону `dir` (+1 вперёд, −1 назад), окном `q`. */
function sideTangent(
  px: Float64Array,
  py: Float64Array,
  k: number,
  dir: number,
  q: number,
  lo: number,
  hi: number,
): [number, number] {
  let sx = 0;
  let sy = 0;
  let used = 0;
  for (let j = 1; j <= q; j++) {
    const i = k + dir * j;
    if (i < lo || i > hi) break;
    sx += px[i] - px[k];
    sy += py[i] - py[k];
    used++;
  }
  if (!used) return [dir >= 0 ? 1 : -1, 0];
  const l = Math.hypot(sx, sy);
  if (l < EPS) return [dir >= 0 ? 1 : -1, 0];
  return [sx / l, sy / l];
}

type Contour = { pts: [number, number][]; segs: (CubicSeg | null)[]; error: number; sum: number; count: number };

/**
 * ОДИН ЗАМКНУТЫЙ КОНТУР ЦЕЛИКОМ: трещинная граница → углы → кубики.
 *
 * ЗАМКНУТОСТЬ ХРАНИТСЯ ПОВТОРОМ ПЕРВОЙ ТОЧКИ В КОНЦЕ, а не флагом: у `VectorStroke` признака
 * «замкнут» нет. Второго написания замкнутости в формате заводить нельзя.
 *
 * КОНТУР БЕЗ ЕДИНОГО УГЛА (окружность) — ОСОБЫЙ СЛУЧАЙ, и не из вежливости. Кубика от точки к ней
 * же вырождена, наименьшие квадраты по ней дают мусор, поэтому такой контур РЕЖЕТСЯ ПОПОЛАМ
 * безусловно, а касательная на шве берётся ЧЕРЕЗ шов (по точкам с обеих его сторон) — иначе на
 * стыке остался бы излом ровно там, где у круга ничего не происходит.
 */
function traceOne(
  crack: { x: Int32Array; y: Int32Array; n: number },
  tol: number,
  cornerAngle: number,
  nodeCap: number,
): Contour | null {
  const collapsed = collapseRuns(crack);
  if (collapsed.length < 3) return null;
  const thin = thinClosed(collapsed, tol);
  if (thin.length < 3) return null;

  // УГЛЫ ИЩУТСЯ НА ПРОРЕЖЕННОМ КОНТУРЕ, И ТОЛЬКО НА НЁМ. На самой трещинной границе каждый шаг
  // лестницы поворачивает на 90°, то есть «угол» там значил бы «пиксельная сетка».
  const m = thin.length;
  const corners: number[] = [];
  for (let i = 0; i < m; i++) {
    const a = thin[(i + m - 1) % m];
    const b = thin[i];
    const c = thin[(i + 1) % m];
    if (turnAt(a, b, c) >= cornerAngle) corners.push(thin[i].i);
  }

  const n = crack.n;
  // Контур разворачивается в ОТКРЫТЫЙ массив, начинающийся с первого угла (или с точки 0, если
  // углов нет) и повторяющий его в конце. Дальше вся арифметика — по индексам этого массива.
  const start = corners.length ? corners[0] : 0;
  const px = new Float64Array(n + 1);
  const py = new Float64Array(n + 1);
  for (let k = 0; k <= n; k++) {
    const i = (start + k) % n;
    px[k] = crack.x[i];
    py[k] = crack.y[i];
  }

  const window = Math.max(2, Math.round(3 * tol));
  const marks: number[] = [0];
  for (const c of corners) {
    const k = (c - start + n) % n;
    if (k > 0) marks.push(k);
  }
  marks.sort((a, b) => a - b);
  marks.push(n);

  // ПОДПИКСЕЛЬНАЯ ОЦЕНКА КРАЯ, по которой считает подгонка. Довод — у `SMOOTH_RADIUS`.
  const rad = Math.max(1, Math.round(SMOOTH_RADIUS * tol));
  const qx = new Float64Array(n + 1);
  const qy = new Float64Array(n + 1);
  if (corners.length === 0) {
    smoothCyclic(px, py, n, rad, qx, qy);
  } else {
    for (let s = 0; s + 1 < marks.length; s++) smoothRun(px, py, marks[s], marks[s + 1], rad, qx, qy);
  }

  const pieces: Piece[] = [];
  // РАЗВИЛКА ПО ЧИСЛУ УГЛОВ, А НЕ ПО ЧИСЛУ ПРОГОНОВ. Один-единственный угол даёт РОВНО ОДИН
  // прогон — от него вокруг всего контура обратно к нему, — то есть столько же меток, сколько
  // даёт контур вовсе без углов. Развилка по меткам приняла бы такой контур за гладкий и
  // скруглила бы единственное острое место, которое на нём есть.
  if (corners.length === 0) {
    // Ни одного угла: замкнутая гладкая кривая. Режем пополам и шьём шов двусторонней касательной.
    const half = n >> 1;
    const q = Math.max(1, Math.min(window, half, n - half));
    let sx = qx[q] - qx[n - q];
    let sy = qy[q] - qy[n - q];
    let sl = Math.hypot(sx, sy);
    if (sl < EPS) {
      sx = 1;
      sy = 0;
      sl = 1;
    }
    sx /= sl;
    sy /= sl;
    let hx = qx[Math.min(n, half + q)] - qx[Math.max(0, half - q)];
    let hy = qy[Math.min(n, half + q)] - qy[Math.max(0, half - q)];
    let hl = Math.hypot(hx, hy);
    if (hl < EPS) {
      hx = 1;
      hy = 0;
      hl = 1;
    }
    hx /= hl;
    hy /= hl;
    pieces.push(...fitRun(qx, qy, 0, half, sx, sy, -hx, -hy, tol, window, nodeCap));
    pieces.push(...fitRun(qx, qy, half, n, hx, hy, -sx, -sy, tol, window, nodeCap));
  } else {
    for (let s = 0; s + 1 < marks.length; s++) {
      const a = marks[s];
      const b = marks[s + 1];
      if (b <= a) continue;
      const [t1x, t1y] = sideTangent(qx, qy, a, +1, window, a, b);
      const [t2x, t2y] = sideTangent(qx, qy, b, -1, window, a, b);
      pieces.push(...fitRun(qx, qy, a, b, t1x, t1y, t2x, t2y, tol, window, nodeCap));
    }
  }
  if (!pieces.length) return null;

  // ── ОТЧЁТНОЕ ЧИСЛО МЕРЯЕТСЯ ПО СЫРОЙ ГРАНИЦЕ ──────────────────────────────────────────────
  //
  // Подгонка считала по подпиксельной ОЦЕНКЕ края (см. `SMOOTH_RADIUS`) — и сверять кривую с той
  // самой оценкой, из которой её и вывели, значило бы удостоверять себя собой: такая цифра всегда
  // укладывается в допуск и не доказывает ничего. Здесь берутся ТОЧКИ САМОГО РАСТРА, поэтому
  // названное отклонение честно включает и полпикселя лестницы, которую сетка накладывает на
  // любую кривую линию. Оно ПОЭТОМУ и бывает больше допуска — об этом сказано словами в `notes`.
  // ГЕОМЕТРИЯ ОТДАЁТСЯ ИЗ СГЛАЖЕННОГО МАССИВА ЦЕЛИКОМ — и узлы, и ручки. Взять узел из сырого, а
  // ручку из сглаженного значило бы разорвать кривую в каждом внутреннем разрезе на те самые
  // полпикселя, ради которых сглаживание и заведено. На концах прогонов — на углах — оба массива
  // совпадают по построению (`smoothRun` их не двигает), поэтому угол остаётся ровно там, где его
  // поставили пиксели.
  const pts: [number, number][] = [[qx[0], qy[0]]];
  const segs: (CubicSeg | null)[] = [];
  let error = 0;
  let sum = 0;
  let count = 0;
  let from = 0;
  for (const p of pieces) {
    pts.push([qx[p.end], qy[p.end]]);
    segs.push(p.seg);
    const raw = deviateRaw(px, py, from, p.end, qx[from], qy[from], p.seg, qx[p.end], qy[p.end]);
    if (raw.error > error) error = raw.error;
    sum += raw.sum;
    count += p.end - from + 1;
    from = p.end;
  }
  return { pts, segs, error, sum, count };
}

/**
 * ОТКЛОНЕНИЕ ГОТОВОГО КУСКА ОТ СЫРЫХ ТОЧЕК РАСТРА. Концы берутся у КРИВОЙ (то есть из сглаженного
 * массива), а точки — у растра: меряется ровно то, что человек увидит на экране, против ровно
 * того, что нарисовано в пикселях.
 */
function deviateRaw(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  p0x: number,
  p0y: number,
  seg: CubicSeg | null,
  p3x: number,
  p3y: number,
): { error: number; sum: number } {
  let error = 0;
  let sum = 0;
  if (!seg) {
    const dx = p3x - p0x;
    const dy = p3y - p0y;
    const len2 = dx * dx + dy * dy;
    for (let i = a; i <= b; i++) {
      const t = len2 <= EPS ? 0 : clamp(((px[i] - p0x) * dx + (py[i] - p0y) * dy) / len2, 0, 1);
      const d = Math.hypot(px[i] - (p0x + t * dx), py[i] - (p0y + t * dy));
      sum += d;
      if (d > error) error = d;
    }
    return { error, sum };
  }
  // Кривая: расстояние до неё берётся по плотной выборке — искать ближайшую точку кубики ТОЧНО
  // значит решать уравнение пятой степени на КАЖДЫЙ пиксель контура, а выборка в четыре шага на
  // точку даёт ответ с запасом много меньше сотой пикселя.
  //
  // Ближайший образец ищется ХОДОМ ВПЕРЁД, а не полным перебором: и контур, и кривая идут в одну
  // сторону, поэтому минимум не может уехать назад. Полный перебор стоил бы квадрата длины куска —
  // на прогоне в тысячу точек это миллионы сравнений РАДИ ОДНОЙ ОТЧЁТНОЙ ЦИФРЫ.
  const steps = Math.max(16, (b - a) * 4);
  const cx = new Float64Array(steps + 1);
  const cy = new Float64Array(steps + 1);
  for (let k = 0; k <= steps; k++) {
    const t = k / steps;
    cx[k] = bez(p0x, seg[0], seg[2], p3x, t);
    cy[k] = bez(p0y, seg[1], seg[3], p3y, t);
  }
  let k = 0;
  for (let i = a; i <= b; i++) {
    const d2 = (j: number) => (px[i] - cx[j]) ** 2 + (py[i] - cy[j]) ** 2;
    let bestK = k;
    let best = d2(k);
    for (let j = k + 1; j <= steps; j++) {
      const nd = d2(j);
      if (nd < best) {
        best = nd;
        bestK = j;
      } else if (j > bestK + 8) break;
    }
    k = bestK;
    const d = Math.sqrt(best);
    sum += d;
    if (d > error) error = d;
  }
  return { error, sum };
}


