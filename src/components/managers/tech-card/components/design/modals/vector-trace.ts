/** Сколько раз уточнять параметризацию Ньютоном, прежде чем признать подгонку неудачной. */
const NEWTON_PASSES = 4;

/**
 * РАДИУС СГЛАЖИВАНИЯ ОЦЕНКИ КРАЯ, В ТОЧКАХ КОНТУРА, НА ЕДИНИЦУ ДОПУСКА.
 *
 * ── ЭТО НЕ УКРАШЕНИЕ. ЭТО ШАГ, БЕЗ КОТОРОГО ДОПУСК НЕ ИМЕЕТ СМЫСЛА ──────────────────────────
 *
 * Трещинная граница идёт по решётке целых чисел, поэтому на КРИВОМ участке её точки лежат то на
 * полпикселя внутри идеального края, то на полпикселя снаружи — пилой. Никакая гладкая кривая не
 * может пройти ближе чем в ~0.7 px от ВСЕХ таких точек: это не ошибка подгонки, это сама сетка.
 *
 * ЗАМЕРЕНО, И ЦЕНА ОШИБКИ БЫЛА ВИДНА ЧИСЛОМ. Пока критерий стоял на сырых точках, круг R = 120
 * при допуске 1 px возвращался ПЯТЬЮДЕСЯТЬЮ ЧЕТЫРЬМЯ узлами вместо четырёх: четверть окружности
 * подгонялась с ошибкой 1.045 — то есть промахивалась мимо порога на четыре сотых, ЦЕЛИКОМ
 * состоящих из шума решётки, — и делилась снова и снова, пока куски не становились так коротки,
 * что проходили как ПРЯМЫЕ. Результат был не «кривая с запасом точности», а МНОГОУГОЛЬНИК: из
 * 4674 узлов на чертеже кривыми были ДВА. Ровно та many-node mush, которую владелец запретил.
 *
 * Лечится тем же приёмом, что и у potrace, где он называется vertex adjustment: перед подгонкой
 * строится ПОДПИКСЕЛЬНАЯ ОЦЕНКА КРАЯ — скользящее среднее по контуру, — и критерий стоит на ней.
 * Пила усредняется, настоящая кривизна остаётся: сдвиг радиуса от окна ±2 на круге R = 8 меньше
 * десятой пикселя.
 *
 * УГЛЫ ИЗ СГЛАЖИВАНИЯ ИСКЛЮЧЕНЫ, И ОКНО НЕ ПЕРЕХОДИТ ЧЕРЕЗ НИХ: усреднить прямой угол значило бы
 * срезать его до подгонки, и никакая односторонняя касательная его потом не вернула бы.
 *
 * А ОТЧЁТНОЕ ЧИСЛО МЕРЯЕТСЯ ПО СЫРОЙ ГРАНИЦЕ, а не по этой оценке. Иначе движок сверял бы себя с
 * собственным приближением и всегда получал бы «в допуске» — цифра, которая ничего не удостоверяет.
 */
const SMOOTH_RADIUS = 2;

/** Скользящее среднее по ЗАМКНУТОМУ контуру целиком — для контура, на котором нет ни одного угла. */
function smoothCyclic(
  px: Float64Array,
  py: Float64Array,
  n: number,
  r: number,
  qx: Float64Array,
  qy: Float64Array,
): void {
  const span = 2 * r + 1;
  for (let k = 0; k < n; k++) {
    let sx = 0;
    let sy = 0;
    for (let j = -r; j <= r; j++) {
      const i = (((k + j) % n) + n) % n;
      sx += px[i];
      sy += py[i];
    }
    qx[k] = sx / span;
    qy[k] = sy / span;
  }
  qx[n] = qx[0];
  qy[n] = qy[0];
}

/** То же по одному прогону: окно упирается в его концы, а сами концы — углы — не двигаются. */
function smoothRun(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  r: number,
  qx: Float64Array,
  qy: Float64Array,
): void {
  for (let k = a; k <= b; k++) {
    if (k === a || k === b) {
      qx[k] = px[k];
      qy[k] = py[k];
      continue;
    }
    const lo = Math.max(a, k - r);
    const hi = Math.min(b, k + r);
    let sx = 0;
    let sy = 0;
    for (let i = lo; i <= hi; i++) {
      sx += px[i];
      sy += py[i];
    }
    qx[k] = sx / (hi - lo + 1);
    qy[k] = sy / (hi - lo + 1);
  }
}

/** Ниже этой длины отрезок считается вырожденным и касательная по нему не строится. */
const EPS = 1e-9;

type Fitted = { seg: CubicSeg | null; error: number };

/**
 * ОДНА КУБИКА ПО ТОЧКАМ `px[a..b]` С ЗАДАННЫМИ КАСАТЕЛЬНЫМИ, метод наименьших квадратов Шнайдера.
 *
 * `t1` смотрит ИЗ начала внутрь кривой, `t2` — ИЗ конца назад внутрь: контрольные точки тогда
 * `p0 + α1·t1` и `p3 + α2·t2`, и обе α ищутся из системы 2×2. Вырожденный случай (определитель в
 * ноль, отрицательная α) закрывается классической запаской «треть хорды» — не потому, что она
 * хороша, а потому, что она даёт ЗАВЕДОМО разумную кривую, чью ошибку тут же и померят.
 */
function fitOne(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  t1x: number,
  t1y: number,
  t2x: number,
  t2y: number,
  u: Float64Array,
): [number, number, number, number] {
  const p0x = px[a];
  const p0y = py[a];
  const p3x = px[b];
  const p3y = py[b];
  let c00 = 0;
  let c01 = 0;
  let c11 = 0;
  let x0 = 0;
  let x1 = 0;
  for (let i = a; i <= b; i++) {
    const t = u[i - a];
    const s = 1 - t;
    const b0 = s * s * s;
    const b1 = 3 * s * s * t;
    const b2 = 3 * s * t * t;
    const b3 = t * t * t;
    const a1x = t1x * b1;
    const a1y = t1y * b1;
    const a2x = t2x * b2;
    const a2y = t2y * b2;
    c00 += a1x * a1x + a1y * a1y;
    c01 += a1x * a2x + a1y * a2y;
    c11 += a2x * a2x + a2y * a2y;
    const tx = px[i] - ((b0 + b1) * p0x + (b2 + b3) * p3x);
    const ty = py[i] - ((b0 + b1) * p0y + (b2 + b3) * p3y);
    x0 += a1x * tx + a1y * ty;
    x1 += a2x * tx + a2y * ty;
  }
  const det = c00 * c11 - c01 * c01;
  let al1 = 0;
  let al2 = 0;
  if (Math.abs(det) > EPS) {
    al1 = (x0 * c11 - x1 * c01) / det;
    al2 = (c00 * x1 - c01 * x0) / det;
  }
  const chord = Math.hypot(p3x - p0x, p3y - p0y);
  if (!(al1 > EPS) || !(al2 > EPS) || !Number.isFinite(al1) || !Number.isFinite(al2)) {
    al1 = chord / 3;
    al2 = chord / 3;
  }
  return [p0x + al1 * t1x, p0y + al1 * t1y, p3x + al2 * t2x, p3y + al2 * t2y];
}

/** Точка кубики при параметре `t`. Голая арифметика Бернштейна — библиотеки здесь нет. */
function bez(
  p0: number,
  c1: number,
  c2: number,
  p3: number,
  t: number,
): number {
  const s = 1 - t;
  return s * s * s * p0 + 3 * s * s * t * c1 + 3 * s * t * t * c2 + t * t * t * p3;
}

/** Максимум отклонения кривой от точек и НОМЕР точки, где он достигнут. */
function worstOf(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  seg: CubicSeg,
  u: Float64Array,
): { error: number; at: number; sum: number } {
  const p0x = px[a];
  const p0y = py[a];
  const p3x = px[b];
  const p3y = py[b];
  let error = 0;
  let at = a + ((b - a) >> 1);
  let sum = 0;
  for (let i = a; i <= b; i++) {
    const t = u[i - a];
    const dx = bez(p0x, seg[0], seg[2], p3x, t) - px[i];
    const dy = bez(p0y, seg[1], seg[3], p3y, t) - py[i];
    const d = Math.hypot(dx, dy);
    sum += d;
    if (d > error) {
      error = d;
      at = i;
    }
  }
  return { error, at, sum };
}

/**
 * УТОЧНЕНИЕ ПАРАМЕТРИЗАЦИИ НЬЮТОНОМ. Длина хорды — только первое приближение параметра; без этого
 * шага подгонка честно минимизирует ошибку НЕ ТАМ, и разбиение случается там, где кривая на самом
 * деле хороша, — то есть узлы тратятся зря.
 */
function reparam(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  seg: CubicSeg,
  u: Float64Array,
): void {
  const p0x = px[a];
  const p0y = py[a];
  const p3x = px[b];
  const p3y = py[b];
  const c1x = seg[0];
  const c1y = seg[1];
  const c2x = seg[2];
  const c2y = seg[3];
  for (let i = a; i <= b; i++) {
    const t = u[i - a];
    const s = 1 - t;
    const qx = s * s * s * p0x + 3 * s * s * t * c1x + 3 * s * t * t * c2x + t * t * t * p3x;
    const qy = s * s * s * p0y + 3 * s * s * t * c1y + 3 * s * t * t * c2y + t * t * t * p3y;
    const d1x = 3 * (s * s * (c1x - p0x) + 2 * s * t * (c2x - c1x) + t * t * (p3x - c2x));
    const d1y = 3 * (s * s * (c1y - p0y) + 2 * s * t * (c2y - c1y) + t * t * (p3y - c2y));
    const d2x = 6 * (s * (c2x - 2 * c1x + p0x) + t * (p3x - 2 * c2x + c1x));
    const d2y = 6 * (s * (c2y - 2 * c1y + p0y) + t * (p3y - 2 * c2y + c1y));
    const ex = qx - px[i];
    const ey = qy - py[i];
    const num = ex * d1x + ey * d1y;
    const den = d1x * d1x + d1y * d1y + ex * d2x + ey * d2y;
    if (Math.abs(den) < EPS) continue;
    const next = t - num / den;
    if (Number.isFinite(next)) u[i - a] = clamp(next, 0, 1);
  }
}

/** Параметризация по длине хорды на отрезке `a..b`, в предоставленный буфер. */
function chordParam(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
  u: Float64Array,
): void {
  u[0] = 0;
  for (let i = a + 1; i <= b; i++) {
    u[i - a] = u[i - a - 1] + Math.hypot(px[i] - px[i - 1], py[i] - py[i - 1]);
  }
  const total = u[b - a];
  if (total <= EPS) {
    for (let i = a; i <= b; i++) u[i - a] = (i - a) / Math.max(1, b - a);
    return;
  }
  for (let i = a; i <= b; i++) u[i - a] /= total;
}

/**
 * ОТРЕЗОК ИЛИ КРИВАЯ. Прямая проверяется ПЕРВОЙ и по самим точкам: если все они лежат в допуске от
 * хорды, интервал прямой, и в документ идёт `null` — то, что означает «дословно прямая», а не
 * кубика с контрольными точками на хорде. Разница видна: прямую сторону чертежа человек будет
 * тянуть за концы, а не разгибать четыре ручки.
 */
function straightError(
  px: Float64Array,
  py: Float64Array,
  a: number,
  b: number,
): { error: number; sum: number } {
  const ax = px[a];
  const ay = py[a];
  const bx = px[b];
  const by = py[b];
  const dx = bx - ax;
  const dy = by - ay;
  const len2 = dx * dx + dy * dy;
  let error = 0;
  let sum = 0;
  for (let i = a; i <= b; i++) {
    let d: number;
    if (len2 <= EPS) {
      d = Math.hypot(px[i] - ax, py[i] - ay);
    } else {
      const t = clamp(((px[i] - ax) * dx + (py[i] - ay) * dy) / len2, 0, 1);
      d = Math.hypot(px[i] - (ax + t * dx), py[i] - (ay + t * dy));
    }
    sum += d;
    if (d > error) error = d;
  }
  return { error, sum };
}

