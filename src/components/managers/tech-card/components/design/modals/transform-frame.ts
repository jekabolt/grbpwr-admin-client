/**
 * ТРАНСФОРМ-РАМКА — ОДИН ПРИМИТИВ НА ТРИ ХОЗЯИНА (G-3, G-13, G-4).
 *
 * Дословно от владельца (G-3): «слой с картинкой должен быть как механика слоя в фотошопе что бы
 * можно было его искривлять с помощью направляющих крутить». И (G-13): «когда с помощью выделения
 * делаешь вставку вставленным объектом нужно что бы было можно управлять пока мы его не заплейсим».
 *
 * ── ПОЧЕМУ ОДИН ПРИМИТИВ, А НЕ ТРИ ПОХОЖИХ ──────────────────────────────────────────────────
 *
 * Шаблон, вставка и кроп — три РАЗНЫХ содержимых под ОДНИМ жестом: тянуть тело, тянуть ручку,
 * крутить за углом, Ctrl-тянуть угол. Три копии этой арифметики разошлись бы на первой же правке
 * (ровно так разъехались бы два рисовальщика превью, о чём написано в `vector-modal.tsx`), и
 * человек получил бы три рамки, ведущие себя по-разному в трёх местах одного экрана.
 *
 * Здесь НЕТ ни React, ни DOM, ни состояния приложения: только квад и редукторы над ним. Всё, что
 * знает про экран, живёт в `transform-frame-overlay.tsx`; всё, что знает про документ, — в
 * `vector-modal.tsx`.
 *
 * ── ИСТИНА — КВАД, А НЕ «ЦЕНТР + МАСШТАБ + УГОЛ» ────────────────────────────────────────────
 *
 * Четыре угла в ЮНИТАХ ПЛАТЫ (мир шириной `PLATE_W`), по часовой от левого верхнего: TL, TR, BR,
 * BL. Тройка «центр/масштаб/поворот» выразить перспективу не может в принципе — у неё нет для неё
 * чисел, — а перспектива тут заявленная работа (corner pin). Квад выражает всё: сдвиг, масштаб по
 * каждой оси (в том числе ОТРИЦАТЕЛЬНЫЙ, то есть отражение), поворот и перспективу.
 *
 * ── СЕТКА WARP (G-16 / H-4): ОНА ЖИВЁТ В ДОМЕНЕ КВАДА, А НЕ В ЮНИТАХ ПЛАТЫ ──────────────────
 *
 * Всё, что рисует содержимое рамки, спрашивает ОДНУ функцию: «где на плате лежит точка (u,v)
 * источника». Она объявлена как `warpMapper(warp)` и возвращает замыкание `f(u, v)`. Без сетки
 * `f` — гомография квада; с сеткой `f` — КОМПОЗИЦИЯ: `f(u,v) = H(quad)( patch(grid, u, v) )`.
 *
 * ⚠ ПОЧЕМУ КОМПОЗИЦИЯ, А НЕ АБСОЛЮТНЫЕ ТОЧКИ. Контрольные точки заданы В ЕДИНИЧНОМ ДОМЕНЕ КВАДА
 * (u, v ≈ 0…1, вынос за границы законен), поэтому ВСЯКИЙ писатель квада — сдвиг, масштаб,
 * поворот, corner pin, `keepQuadReachable`, `clampBackdrop` — увозит сетку с собой БЕСПЛАТНО и
 * не зная о ней. Держи мы шестнадцать точек в юнитах платы, каждый из этих шести редукторов был
 * бы ОБЯЗАН помнить про них, и первый забывший разъехался бы молча: картинка поехала бы, а сетка
 * осталась. Цена решения названа честно: перевод точки руки в домен требует ОБРАТНОЙ гомографии
 * (`invertMat3` / `applyHInv` ниже), и это единственное место, где она нужна.
 *
 * ⚠ ИНТЕРПОЛЯЦИЯ — БИКУБИЧЕСКИЙ ПАТЧ БЕЗЬЕ, А НЕ БИЛИНЕЙНАЯ РЕШЁТКА. Билинейная даёт C0-излом по
 * границам клеток: сдвинул один узел — на соседних линиях видна складка, а «warp» у фотошопа это
 * именно ГЛАДКАЯ поверхность. Тензорное произведение кубических Бернштейнов даёт C1 внутри всего
 * патча и ТОЧНОЕ ТОЖДЕСТВО на равномерной сетке (сумма бернштейнов, взвешенных узлами i/3, равна
 * параметру), поэтому вход в режим не двигает картинку ни на пиксель. Билинейная ветка
 * (`gridPoint`) осталась — она понадобится решёткам плотнее 4×4, где кубика на клетку нет.
 *
 * Вид ветки назван ПОЛЕМ (`kind`), а не выведен из размеров: «4×4 значит Безье» — это правило,
 * которое сломается в тот день, когда появится вторая сетка 4×4 с другим смыслом.
 */

export type Pt = readonly [number, number];

/** Четыре угла по часовой от левого верхнего: TL, TR, BR, BL. */
export type Quad = readonly [Pt, Pt, Pt, Pt];

/**
 * Сетка контрольных точек (H-4). `pts` — ПОСТРОЧНО, `rows × cols` штук, В ЕДИНИЧНОМ ДОМЕНЕ КВАДА
 * (не в юнитах платы — довод в шапке файла); тождественная сетка это `pts[i*cols+j] = [j/(cols−1),
 * i/(rows−1)]`. `kind` называет ветку интерполяции явно: `bezier` — тензорный кубик (только 4×4),
 * `bilinear` — решётка по клеткам.
 */
export type WarpGrid = {
  rows: number;
  cols: number;
  pts: Pt[];
  kind?: 'bilinear' | 'bezier';
};

export type Warp = { quad: Quad; grid?: WarpGrid };

/** Сколько узлов вдоль стороны у сетки, которую строит редактор. Четыре — как в фотошопе. */
export const WARP_SIZE = 4;

/** Насколько далеко узлу позволено уехать из домена. Вынос законен, бесконечность — нет. */
const NODE_DOMAIN = 1;

/**
 * СКОЛЬКО ШАГОВ ПАРАМЕТРА КЛАДЁТ РИСОВАЛЬЩИК НА СТОРОНУ — И ЭТИМ ЖЕ ЧИСЛОМ МЕРЯЮТ ЕГО ОБРАЗ.
 *
 * ⚠ ЧИСЛО ЖИВЁТ ЗДЕСЬ, А НЕ У ХОЛСТА, И ЭТО ПОЧИНКА ЗАМЕРЕННОГО ДЕФЕКТА. Коробка образа
 * снималась сеткой 13×13, а `drawWarped` кладёт углы треугольников в 25×25 параметрических точек —
 * СТРОГОЕ НАДМНОЖЕСТВО. Замер на квадe 1000×1000 с одним узлом на клампе: рисовальщик вылезал за
 * снятую коробку на 5.14 юнита (узлы 1/2 в `[2,2]`/`[-1,-1]`), 3.99 у внутренних, — при запасе
 * коробки в 2 юнита это до трёх юнитов шаблона, молча срезанных кромкой холста. Пока число одно
 * на обоих, надмножества не существует: коробка снимается РОВНО по тем точкам, которые рисуются.
 */
export const WARP_DRAW_STEPS = 24;

/**
 * ПОЛ ДЕЛИТЕЛЯ ГОМОГРАФИИ. `w = g·u + h·v + 1` безразмерен (`m[8]` тождественно единица), поэтому
 * порог здесь — чистое число, одинаковое для платы любого размера.
 *
 * ЗАЧЕМ ОН ЕСТЬ. Контрольные точки клампятся в `[-1, 2]`, но КЛАМП НЕ ЗНАЕТ, ГДЕ ЛИНИЯ СХОДА: у
 * перспективного квада она лежит внутри этого домена. Замер на трапеции (верх 120 юнитов на
 * y=420, низ 900 на y=1150): `h = −0.8667`, то есть горизонт стоит на `v = 1.1538` — на треть
 * ближе клампа. Узел, уведённый в точку листа (20, 80), садится в домен `(2, 1.72)`, где
 * `w = −0.49`: поверхность между ним и соседями ПЕРЕСЕКАЕТ ноль, `applyH` подменяет его на 1e-12,
 * и «бесконечность» приезжает конечным числом порядка 1e5 — фильтр `Number.isFinite` её пропускает.
 *
 * ПОЧЕМУ 0.02. Тождественная поверхность той же трапеции доходит до `w = 0.133`; узел, честно
 * уведённый за нижнюю кромку до `v = 1.1`, даёт 0.047 — и обязан пройти. Ноль стоит на 1.1538.
 * Порог 0.02 отсекает полосу шириной 2 % делителя вплотную к горизонту и пропускает всё, что
 * человек может осмысленно захотеть. На квадe без перспективы `g = h = 0`, `w ≡ 1` — порог не
 * трогает ни одного жеста вовсе.
 */
export const HORIZON_EPS = 0.02;

/**
 * ТОЖДЕСТВЕННАЯ СЕТКА. Строится при входе в режим и НЕ СОХРАНЯЕТСЯ при коммите (`gridIsIdentity`):
 * запись, отличающаяся от прежней сеткой, которая ничего не делает, заставила бы превью уйти на
 * канвас без единой причины и объявила бы шаблон изменённым, хотя человек только заглянул.
 */
export function identityGrid(rows = WARP_SIZE, cols = WARP_SIZE): WarpGrid {
  const pts: Pt[] = [];
  for (let i = 0; i < rows; i++) {
    for (let j = 0; j < cols; j++) pts.push([j / (cols - 1), i / (rows - 1)]);
  }
  return { rows, cols, pts, kind: rows === 4 && cols === 4 ? 'bezier' : 'bilinear' };
}

/** Сетка, которая ничего не делает. ε в долях домена: 1e-4 домена — это 0.1 юнита платы. */
export function gridIsIdentity(g: WarpGrid | undefined, eps = 1e-4): boolean {
  if (!g) return true;
  const id = identityGrid(g.rows, g.cols);
  return g.pts.every(
    (p, k) => Math.abs(p[0] - id.pts[k][0]) < eps && Math.abs(p[1] - id.pts[k][1]) < eps,
  );
}

/** Сетка жива и целá. Половина сетки — не сетка: интерполяция читала бы `undefined`. */
export const gridIsUsable = (g: WarpGrid | undefined): g is WarpGrid =>
  !!g && g.rows >= 2 && g.cols >= 2 && g.pts.length === g.rows * g.cols;

/**
 * ПОДВИНУТЬ УЗЕЛ. Точка приходит В ДОМЕНЕ (её переводит вызывающий обратной гомографией) и
 * КЛАМПИТСЯ: узел, уехавший на десять доменов, растягивает патч так, что содержимое перестаёт
 * помещаться в любую разумную коробку превью, а вернуть его нечем — самого узла на экране уже нет.
 */
export function moveGridNode(g: WarpGrid, index: number, to: Pt): WarpGrid {
  if (index < 0 || index >= g.pts.length || !finite(to[0]) || !finite(to[1])) return g;
  const pts = g.pts.slice();
  pts[index] = [clampDomain(to[0]), clampDomain(to[1])];
  return { ...g, pts };
}

/** Одна координата в домене. Число одно, и правило одно — см. `clampGridDomain`. */
export const clampDomain = (n: number): number =>
  !finite(n) ? 0 : Math.min(1 + NODE_DOMAIN, Math.max(-NODE_DOMAIN, n));

/**
 * ВСЯ СЕТКА В ДОМЕНЕ — ТЕМ ЖЕ ЧИСЛОМ, ЧТО У ДРАГА УЗЛА.
 *
 * ⚠ ЭТО НЕ ДУБЛЬ КЛАМПА, А ЕГО ВТОРАЯ ДВЕРЬ, И ОНА ОБЯЗАНА БЫТЬ. `moveGridNode` стережёт ЖЕСТ, но
 * сетка приезжает ещё и из ХРАНИЛИЩА, а записи там переживают бандл: запись с точками на ±30
 * доменов проходила разбор без единой жалобы и поднимала холст 30724 × 38404 ПРЯМО НА ОТКРЫТИИ,
 * без единого движения руки (замерено). Кламп у одного входа — это кламп, которого нет.
 */
export function clampGridDomain(g: WarpGrid): WarpGrid {
  let dirty = false;
  const pts = g.pts.map((p) => {
    const q: Pt = [clampDomain(p[0]), clampDomain(p[1])];
    if (q[0] !== p[0] || q[1] !== p[1]) dirty = true;
    return q;
  });
  return dirty ? { ...g, pts } : g;
}

/**
 * ВОСЕМЬ РУЧЕК В ПОРЯДКЕ ЧТЕНИЯ, и порядок здесь — не вкус: он же уезжает в разметку
 * (`data-frame-handle="0..7"`), и проба, которая жмёт «правую» ручку, обязана уметь назвать её
 * числом, не считая по картинке.
 *
 *   0 1 2
 *   3   4
 *   5 6 7
 */
export const HANDLE_UV: readonly Pt[] = [
  [0, 0],
  [0.5, 0],
  [1, 0],
  [0, 0.5],
  [1, 0.5],
  [0, 1],
  [0.5, 1],
  [1, 1],
];

/** Ручки-углы, в том же порядке, что углы квада (TL, TR, BR, BL). */
export const CORNER_HANDLES: readonly number[] = [0, 2, 7, 5];

/** Ручка — угол? Только у углов есть поворот и перспектива. */
export const isCornerHandle = (h: number): boolean => CORNER_HANDLES.includes(h);

/**
 * САМАЯ КОРОТКАЯ СТОРОНА, КОТОРУЮ РАМКЕ ПОЗВОЛЕНО ИМЕТЬ, в юнитах платы. Ноль вырождает квад:
 * определитель гомографии обращается в ноль, обратного отображения не существует, и содержимое
 * исчезает БЕЗ ВОЗВРАТА — вернуть его нечем, потому что «на сколько растянуть обратно» больше не
 * записано нигде. Двенадцать юнитов — это ещё видимая полоска, за которую можно взяться.
 */
export const MIN_FRAME_SIDE = 12;

const sub = (a: Pt, b: Pt): Pt => [a[0] - b[0], a[1] - b[1]];
const add = (a: Pt, b: Pt): Pt => [a[0] + b[0], a[1] + b[1]];
const mul = (a: Pt, k: number): Pt => [a[0] * k, a[1] * k];
const finite = (n: number): boolean => Number.isFinite(n);

/** Квад из осе-выровненного прямоугольника — начало всякой рамки и единственная форма кропа. */
export function quadFromRect(x: number, y: number, w: number, h: number): Quad {
  return [
    [x, y],
    [x + w, y],
    [x + w, y + h],
    [x, y + h],
  ];
}

/** Габарит по осям. Им меряют «уехала ли рамка» и им же клампят её в пределы досягаемости. */
export function quadBounds(q: Quad): { x0: number; y0: number; x1: number; y1: number } {
  const xs = q.map((p) => p[0]);
  const ys = q.map((p) => p[1]);
  return { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
}

/**
 * ═══ ОСЕ-ВЫРОВНЕННАЯ РАМКА, ПРИВЕДЁННАЯ К ЗАДАННОМУ ОТНОШЕНИЮ (E-18) ════════════════════════
 *
 * Владелец: «для кропа должна быть возможность выбрать aspect ratio». Отношение — это ОГРАНИЧЕНИЕ
 * НА ФОРМУ, а не число в панели: рамка обязана держать его сама, что бы рука с ней ни делала.
 *
 * Три образа действия, и каждый отвечает своему жесту — иначе один и тот же вызов то мешал бы
 * руке, то не слушался её:
 *
 *   `w`    — ширина от руки, высота выводится. Тянут вертикальную сторону или угол.
 *   `h`    — высота от руки, ширина выводится. Тянут горизонтальную сторону.
 *   `area` — площадь сохраняется, меняется только форма. ВЫБОР отношения чипом: рамка не имеет
 *            права ни раздуться, ни схлопнуться от того, что человек назвал форму.
 *   `fit`  — наибольший прямоугольник этого отношения ВНУТРИ нынешнего. Открытие рамки по листу
 *            и починка после клампа: `min` гарантирует, что результат никуда не вылезет.
 *
 * `uv` — точка, остающаяся на месте, в долях САМОЙ рамки: `[0.5, 0.5]` центр, `[0, 0.5]` середина
 * левой стороны. У жеста это всегда ручка, ПРОТИВОПОЛОЖНАЯ той, что в руке: тянут правую сторону
 * — левая обязана стоять, иначе рамка уезжает из-под пальца.
 */
export function fitQuadRatio(
  q: Quad,
  ratio: number,
  mode: 'w' | 'h' | 'area' | 'fit',
  uv: Pt,
): Quad {
  const b = quadBounds(q);
  const w = b.x1 - b.x0;
  const h = b.y1 - b.y0;
  if (!(ratio > 0) || !(w > 1e-9) || !(h > 1e-9)) return q;
  let nw = w;
  let nh = h;
  if (mode === 'w') nh = w / ratio;
  else if (mode === 'h') nw = h * ratio;
  else if (mode === 'fit') {
    nw = Math.min(w, h * ratio);
    nh = nw / ratio;
  } else {
    nw = Math.sqrt(w * h * ratio);
    nh = nw / ratio;
  }
  /* ПОЛ ТОТ ЖЕ, ЧТО У МАСШТАБА. Рамка 4:5, схлопнутая по ширине до нуля, дала бы лист нулевой
     высоты — и восстанавливать его было бы не из чего. */
  if (nw < MIN_FRAME_SIDE) {
    nw = MIN_FRAME_SIDE;
    nh = nw / ratio;
  }
  if (nh < MIN_FRAME_SIDE) {
    nh = MIN_FRAME_SIDE;
    nw = nh * ratio;
  }
  const ax = b.x0 + uv[0] * w;
  const ay = b.y0 + uv[1] * h;
  return quadFromRect(ax - uv[0] * nw, ay - uv[1] * nh, nw, nh);
}

export const quadCenter = (q: Quad): Pt => [
  (q[0][0] + q[1][0] + q[2][0] + q[3][0]) / 4,
  (q[0][1] + q[1][1] + q[2][1] + q[3][1]) / 4,
];

/**
 * ТОЧКА РАМКИ ПО (u,v) — БИЛИНЕЙНО, а не гомографией, и это не небрежность.
 *
 * Гомография отвечает на вопрос «куда уехал ПИКСЕЛЬ источника» — ей и рисуют содержимое. Ручка же
 * — орган РАМКИ: человек ждёт её ровно посередине стороны, которую видит, и на сильной перспективе
 * гомографическая «середина» уезжает к дальнему краю, то есть ручка перестаёт быть там, куда
 * человек целится. Фотошоп держит ручки на самой рамке по той же причине.
 *
 * В углах обе формулы совпадают тождественно, поэтому расхождение не касается ни одного угла — а
 * перспективу двигают именно за углы.
 */
export function framePoint(q: Quad, u: number, v: number): Pt {
  const top: Pt = [q[0][0] + (q[1][0] - q[0][0]) * u, q[0][1] + (q[1][1] - q[0][1]) * u];
  const bot: Pt = [q[3][0] + (q[2][0] - q[3][0]) * u, q[3][1] + (q[2][1] - q[3][1]) * u];
  return [top[0] + (bot[0] - top[0]) * v, top[1] + (bot[1] - top[1]) * v];
}

/** Положение ручки на рамке. */
export const handlePoint = (q: Quad, h: number): Pt => framePoint(q, HANDLE_UV[h][0], HANDLE_UV[h][1]);

