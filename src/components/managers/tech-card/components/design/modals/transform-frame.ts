/** Построчно: `[a, b, c, d, e, f, g, h, i]`, точка (u, v, 1) умножается справа. */
export type Mat3 = [number, number, number, number, number, number, number, number, number];

/**
 * ГОМОГРАФИЯ ЕДИНИЧНОГО КВАДРАТА В КВАД — метод адъюгаты, без единой зависимости.
 *
 * Вывод классический (Heckbert): три коэффициента снимаются из условия «диагонали квада проходят
 * через образ центра», остальные шесть — прямой подстановкой углов. Вырожденный случай (стороны
 * параллельны) отделён явно: там `g = h = 0`, то есть отображение аффинно, и общая формула делила
 * бы ноль на ноль.
 */
export function homographyFromQuad(q: Quad): Mat3 {
  const [p0, p1, p2, p3] = q;
  const dx1 = p1[0] - p2[0];
  const dx2 = p3[0] - p2[0];
  const dx3 = p0[0] - p1[0] + p2[0] - p3[0];
  const dy1 = p1[1] - p2[1];
  const dy2 = p3[1] - p2[1];
  const dy3 = p0[1] - p1[1] + p2[1] - p3[1];

  if (Math.abs(dx3) < 1e-9 && Math.abs(dy3) < 1e-9) {
    return [
      p1[0] - p0[0],
      p3[0] - p0[0],
      p0[0],
      p1[1] - p0[1],
      p3[1] - p0[1],
      p0[1],
      0,
      0,
      1,
    ];
  }
  const den = dx1 * dy2 - dy1 * dx2;
  if (Math.abs(den) < 1e-12) {
    // Вырожденный квад (три угла на одной прямой). Возвращается аффинная ветка: она не «правильна»,
    // но она конечна, а NaN в матрице уносит с экрана и содержимое, и рамку.
    return [
      p1[0] - p0[0],
      p3[0] - p0[0],
      p0[0],
      p1[1] - p0[1],
      p3[1] - p0[1],
      p0[1],
      0,
      0,
      1,
    ];
  }
  const g = (dx3 * dy2 - dy3 * dx2) / den;
  const h = (dx1 * dy3 - dy1 * dx3) / den;
  return [
    p1[0] - p0[0] + g * p1[0],
    p3[0] - p0[0] + h * p3[0],
    p0[0],
    p1[1] - p0[1] + g * p1[1],
    p3[1] - p0[1] + h * p3[1],
    p0[1],
    g,
    h,
    1,
  ];
}

/** Точка (u, v) единичного квадрата через гомографию. */
export function applyH(m: Mat3, u: number, v: number): Pt {
  const w = m[6] * u + m[7] * v + m[8];
  const k = Math.abs(w) < 1e-12 ? 1e-12 : w;
  return [(m[0] * u + m[1] * v + m[2]) / k, (m[3] * u + m[4] * v + m[5]) / k];
}

/**
 * ОБРАТНАЯ ГОМОГРАФИЯ — АДЪЮГАТА, БЕЗ ДЕЛЕНИЯ НА ОПРЕДЕЛИТЕЛЬ. Матрица проективна, то есть задана
 * с точностью до множителя, и общий делитель сокращается в `applyHInv` сам: считать его значило бы
 * потерять точность там, где она ничего не покупает. Вырожденный квад отдаёт `null` — вызывающий
 * обязан отказаться от жеста, а не двигать узел в NaN.
 */
export function invertMat3(m: Mat3): Mat3 | null {
  const a = m[4] * m[8] - m[5] * m[7];
  const b = m[5] * m[6] - m[3] * m[8];
  const c = m[3] * m[7] - m[4] * m[6];
  const det = m[0] * a + m[1] * b + m[2] * c;
  if (!finite(det) || Math.abs(det) < 1e-12) return null;
  return [
    a,
    m[2] * m[7] - m[1] * m[8],
    m[1] * m[5] - m[2] * m[4],
    b,
    m[0] * m[8] - m[2] * m[6],
    m[2] * m[3] - m[0] * m[5],
    c,
    m[1] * m[6] - m[0] * m[7],
    m[0] * m[4] - m[1] * m[3],
  ];
}

/** Точка платы → домен квада. Единственный потребитель — драг узла сетки. */
export function applyHInv(inv: Mat3, p: Pt): Pt | null {
  const w = inv[6] * p[0] + inv[7] * p[1] + inv[8];
  if (!finite(w) || Math.abs(w) < 1e-12) return null;
  return [
    (inv[0] * p[0] + inv[1] * p[1] + inv[2]) / w,
    (inv[3] * p[0] + inv[4] * p[1] + inv[5]) / w,
  ];
}

/** Точка платы в домене этого квада, либо `null` у вырожденного. */
export function quadToDomain(q: Quad, p: Pt): Pt | null {
  const inv = invertMat3(homographyFromQuad(q));
  return inv ? applyHInv(inv, p) : null;
}

/**
 * ГДЕ НА ПЛАТЕ НАРИСОВАН УЗЕЛ. Это образ КОНТРОЛЬНОЙ ТОЧКИ, а не точка поверхности: у кубика
 * поверхность проходит только через четыре угловых, а внутренние ТЯНУТ её — ровно как рукоятки
 * кривой у пера в этом же редакторе. Рука берётся за то, что двигает, и это одно и то же место.
 */
export function warpNodePoint(q: Quad, g: WarpGrid, index: number): Pt {
  const m = homographyFromQuad(q);
  const c = g.pts[index] ?? [0, 0];
  return applyH(m, c[0], c[1]);
}

/** Все узлы на плате, в порядке разметки (`data-warp-node="0..15"`), построчно. */
export const warpNodePoints = (q: Quad, g: WarpGrid): Pt[] =>
  g.pts.map((_, i) => warpNodePoint(q, g, i));

/**
 * КАКОЙ УЗЕЛ ПОД УКАЗАТЕЛЕМ. Порог приходит в юнитах платы, уже поделённый на зум — тем же
 * правилом, что у ручек рамки: десять экранных пикселей значат десять экранных на любом
 * приближении. Ближайший, а не первый попавшийся: у сильно стянутой сетки узлы налезают друг на
 * друга, и «первый в списке» отдал бы руке не тот, в который она целилась.
 */
export function hitWarpNode(q: Quad, g: WarpGrid, p: Pt, grab: number): number | null {
  const pts = warpNodePoints(q, g);
  let best: { i: number; d: number } | null = null;
  for (let i = 0; i < pts.length; i++) {
    const d = Math.hypot(p[0] - pts[i][0], p[1] - pts[i][1]);
    if (d <= grab && (!best || d < best.d)) best = { i, d };
  }
  return best ? best.i : null;
}

/**
 * ОБРАЗ ИЗОЛИНИИ ДОМЕНА — ломаная в юнитах платы. Ею рисуется вся сетка на экране, и берётся она
 * ИЗ ТОГО ЖЕ `warpMapper`, который положит картинку при коммите: два построителя одной геометрии
 * разошлись бы молча, и первым узнал бы об этом человек, у которого шаблон прыгнул на Enter
 * (правило «геометрия — одна система»).
 */
export function warpIsoline(
  warp: Warp,
  axis: 'u' | 'v',
  t: number,
  steps = 24,
): Pt[] {
  const f = warpMapper(warp);
  const out: Pt[] = [];
  for (let k = 0; k <= steps; k++) {
    const s = k / steps;
    out.push(axis === 'u' ? f(t, s) : f(s, t));
  }
  return out;
}

/**
 * ГДЕ ЛЕЖИТ ТОЧКА (u,v) ИСТОЧНИКА — ЕДИНСТВЕННАЯ ФУНКЦИЯ, КОТОРУЮ СПРАШИВАЮТ РИСОВАЛЬЩИКИ.
 *
 * Возвращает замыкание, а не считает по точке: гомография строится один раз на жест, а спрашивают
 * её сотни раз на кадр (сетка треугольников). Здесь же и точка расширения G-16 — см. шапку файла.
 */
export function warpMapper(warp: Warp): (u: number, v: number) => Pt {
  const m = homographyFromQuad(warp.quad);
  const grid = warp.grid;
  if (gridIsUsable(grid)) {
    /* КОМПОЗИЦИЯ, А НЕ ЗАМЕНА: патч отвечает «куда точка уехала ВНУТРИ домена», гомография —
       «где этот домен лежит на плате». Порядок обязателен и в эту сторону: поставь их наоборот,
       и перспектива считалась бы от уже искривлённых координат. */
    const patch = patchOf(grid);
    return (u, v) => {
      const p = patch(grid, u, v);
      return applyH(m, p[0], p[1]);
    };
  }
  return (u, v) => applyH(m, u, v);
}

/**
 * КАКАЯ ВЕТКА ИНТЕРПОЛЯЦИИ У ЭТОЙ СЕТКИ — ОДНО ПРАВИЛО НА ВЕСЬ ФАЙЛ. Спрошенное во второй раз
 * своими словами, оно разошлось бы с первым молча: отображатель клал бы кубик, а сторож горизонта
 * мерил бы билинейную решётку и разрешал жест, которого рисовальщик не переживёт.
 */
const patchOf = (g: WarpGrid): ((g: WarpGrid, u: number, v: number) => Pt) =>
  g.kind === 'bezier' && g.rows === 4 && g.cols === 4 ? bezierPatchPoint : gridPoint;

/**
 * ПОВЕРХНОСТЬ ПЕРЕСЕКАЕТ ЛИНИЮ СХОДА — ЖЕСТ ОБЯЗАН БЫТЬ ОТКЛОНЁН (P2 ревю H-4).
 *
 * ⚠ ЗДЕСЬ СМОТРЯТ НА ДЕЛИТЕЛЬ ДО ДЕЛЕНИЯ, И В ЭТОМ ВСЯ СУТЬ. После деления «бесконечность» уже
 * неотличима от «очень далеко»: `applyH` подменяет нулевой `w` на 1e-12, и точка приезжает
 * конечной — фильтр `Number.isFinite` в снятии коробки пропускал её, а холст просил у браузера
 * битмап 195146 × 291827 и получал пустоту вместо шаблона (замерено).
 *
 * Семплируется ТА ЖЕ поверхность и ТЕМИ ЖЕ шагами, что рисует `drawWarped` (`WARP_DRAW_STEPS`):
 * сторож, меряющий реже рисовальщика, пропускает ровно то, на чём рисовальщик и ломается.
 *
 * ⚠ ПОЧЕМУ ОТКАЗ, А НЕ КЛАМП. Клампить некуда: узел уже в домене, вне домена его нет, а «поджать
 * до горизонта» значило бы поставить его туда, куда рука не целилась, и вернуть оттуда нечем.
 * Отказ ведёт себя как стена: узел стоит на последнем хорошем месте, рука ушла — и он идёт дальше.
 */
export function warpCrossesHorizon(warp: Warp, steps = WARP_DRAW_STEPS): boolean {
  return warpHorizonMargin(warp, steps) < HORIZON_EPS;
}

/**
 * НАСКОЛЬКО ДАЛЕКО ПОВЕРХНОСТЬ ОТ ЛИНИИ СХОДА — ЧИСЛОМ, А НЕ ДА/НЕТ.
 *
 * Это МИНИМАЛЬНЫЙ делитель гомографии по той же сетке семплов, которой пользуется
 * `warpCrossesHorizon`; «пересекает» — ровно `margin < HORIZON_EPS`. Функция выделена не ради
 * красоты: сторожу у двери рамки понадобилось отличать «плохо» от «ХУЖЕ», а «хуже» обязано
 * меряться ТЕМ ЖЕ, чем меряется «плохо». Спрошенное во второй раз своими словами это разошлось бы
 * с первым молча — тот самый довод, что записан выше у `patchOf`.
 *
 * ⚠ СЕМПЛЕР ТЕПЕРЬ ОДИН НА ОБА ВОПРОСА: `warpCrossesHorizon` стал тонкой обёрткой над этой
 * функцией, а не вторым проходом по той же поверхности.
 *
 * `-Infinity` — «хуже некуда»: матрица невырожденной не получилась либо делитель ушёл в NaN. Такое
 * состояние не может стать «не хуже» ничем, кроме выхода из него, и это правильный ответ.
 */
export function warpHorizonMargin(warp: Warp, steps = WARP_DRAW_STEPS): number {
  const m = homographyFromQuad(warp.quad);
  if (!m.every(finite)) return -Infinity;
  const g = warp.grid;
  /**
   * ⚠ ТОЖДЕСТВЕННАЯ СЕТКА ИДЁТ ПО ТОЙ ЖЕ ВЕТКЕ, ЧТО И ОТСУТСТВИЕ СЕТКИ, И ЭТО НЕ ОПТИМИЗАЦИЯ.
   *
   * Вход в режим узлов ставит ТОЖДЕСТВЕННУЮ сетку — геометрически это no-op, значит и для запаса
   * обязан быть no-op. Через патч Безье он им НЕ БЫЛ: сумма базисов `((b₀+b₁)+b₂)+b₃` при
   * `u = i/24` превышает единицу на 3 из 25 семплов ровно на 2.220446049250313e-16, и при `h < 0`
   * это ломает ничью ВНИЗ. На трапеции с горизонтальными верхом и низом (`g === 0` ТОЧНО — вся
   * каноническая перспективная форма) минимум лежит не в углу домена, а вдоль всей строки `v = 1`,
   * то есть по всем 25 точкам, — и вход в warp «ухудшал» запас на один ulp. `putFrame` честно
   * отказывал, чип не делал ничего и молчал (замерено на 6 из 6 таких трапеций, дельта одна и та же).
   *
   * Довод «минимум сидит в углу, а угол патч воспроизводит точно» верен ТОЛЬКО при `g ≠ 0` и
   * `h ≠ 0`. Здесь он закрыт ПО ПОСТРОЕНИЮ, а не допуском: одна ветка — один результат, бит в бит.
   *
   * ⚠ «А НЕ МЕРИТ ЛИ БЫСТРЫЙ ПУТЬ НЕ ТУ ПОВЕРХНОСТЬ?» — ВОПРОС ЗАДАН ДВАЖДЫ РАЗНЫМИ ЧИТАТЕЛЯМИ,
   * ОТВЕТ ЗАПИСАН ЗДЕСЬ, ЧТОБЫ ТРЕТИЙ ЕГО НАШЁЛ. Опасение звучит так: `eps = 1e-4` пускает
   * ПОЧТИ тождественную сетку по ветке «без сетки», и тогда сторож мерил бы гомографию, а
   * рисовальщик всё равно строил бы патч — то есть разные поверхности.
   *
   * ЭТО НЕ ТАК, И ПРИЧИНА НЕ В МАЛОСТИ ДОПУСКА, А В ТОМ, ЧТО ПРЕДИКАТ ОДИН. `backdropWarpBox`
   * ветвится тем же самым `!gridIsIdentity(...)`, поэтому почти тождественная сетка и
   * ОТРИСОВЫВАЕТСЯ через `<img>` + `quadCss`, то есть через ту же неподправленную гомографию,
   * которую здесь и померили. Сторож и рисовальщик согласны ПО ПОСТРОЕНИЮ, а не по совпадению
   * величин; разойтись они могут только если кто-то заведёт им ВТОРОЙ предикат.
   *
   * Остаток, который допуск вообще способен пропустить, ограничен независимо: смещение узла не
   * больше `1e-4` домена двигает знаменатель не больше чем на `(|g| + |h|) · 1e-4`, что на
   * рабочих квадах даёт 1.49e-4 — в 134 раза ниже `HORIZON_EPS`. Даже будь предикаты разными,
   * до порога это не дотягивается.
   */
  const patch = gridIsUsable(g) && !gridIsIdentity(g) ? patchOf(g) : null;
  const n = Math.max(2, Math.round(steps));
  let min = Infinity;
  for (let j = 0; j <= n; j++) {
    for (let i = 0; i <= n; i++) {
      const p = patch && g ? patch(g, i / n, j / n) : ([i / n, j / n] as Pt);
      const w = m[6] * p[0] + m[7] * p[1] + m[8];
      if (!finite(w)) return -Infinity;
      if (w < min) min = w;
    }
  }
  return min;
}

/** Коробка образа в юнитах платы — место и размер холста превью. */
export type WarpBox = { x: number; y: number; w: number; h: number };

/**
 * ВО СКОЛЬКО ГАБАРИТОВ САМОЙ РАМКИ ОБРАЗУ ПОЗВОЛЕНО ВЫЛЕЗТИ, прежде чем холст перестаёт его
 * догонять. Число выведено, а не выбрано: контрольные точки лежат в `[-1, 2]`, поэтому на квадe
 * БЕЗ перспективы образ не выходит за габарит рамки больше чем на ОДИН такой габарит в каждую
 * сторону (`x = m₀u + m₁v + m₂`, оба параметра в домене шириной три). Двойка — тот же вывод с
 * запасом вдвое; перспектива больше этого добирает уже только за счёт близости к горизонту, а её
 * стережёт `HORIZON_EPS`.
 */
const SURFACE_WINDOW = 2;

/** Запас коробки в юнитах платы: тонкая нить по краю не имеет права срезаться округлением. */
export const WARP_BOX_PAD = 2;

/**
 * САМАЯ ТОНКАЯ ПОВЕРХНОСТЬ, КОТОРУЮ ЕЩЁ ИМЕЕТ СМЫСЛ РИСОВАТЬ, в юнитах платы (до запаса).
 *
 * ⚠ НОЛЬ ЗДЕСЬ НЕ РАБОТАЕТ, И ЭТО ЗАМЕРЕНО. У сетки, все шестнадцать точек которой сведены в одну,
 * образ алгебраически ОДНА точка — но суммы бернштейнов складываются в разном порядке для разных
 * параметров, и габарит выходит порядка 1e-13, то есть строго положительным. Проверка `x1 <= x0`
 * его пропускала, и вместо запасной картинки на экран вставал холст 4 × 4 пикселя (два запаса) —
 * подложка исчезала ровно так же, как от `null`, только другим способом. Тысячная юнита стоит на
 * десять порядков выше шума и на четыре ниже всего, что человек способен выставить руками.
 */
const MIN_SURFACE_SIDE = 1e-3;

/**
 * КОРОБКА ОБРАЗА — ОДИН ПОСТРОИТЕЛЬ НА ВСЕХ (H-3 / ревю H-4).
 *
 * Снимается СЕМПЛИРОВАНИЕМ САМОЙ ПОВЕРХНОСТИ, а не выводится из контрольных точек: свойство
 * выпуклой оболочки верно В ДОМЕНЕ, а гомография не аффинна и через себя его не проносит.
 *
 * ⚠ И ОНА ЗАЖАТА В ОКНО ДОСЯГАЕМОСТИ. Без окна размер коробки не ограничен ничем: у поверхности,
 * подошедшей к линии схода, он уходит в сотни тысяч юнитов, а холст такого размера браузер не
 * выдаёт вовсе — шаблон исчезал целиком. Окно строится ОТ САМОЙ РАМКИ, а не от платы: шаблон
 * законно бывает и много меньше листа, и много больше него, и «плюс полплаты» значило бы для этих
 * двух случаев совершенно разное.
 *
 * `null` — коробки нет (вырожденная поверхность: все шестнадцать узлов в точке, схлопывание в
 * линию, NaN в матрице). Вызывающий обязан показать шаблон ДРУГИМ рисовальщиком, а не пустотой.
 */
export function warpSurfaceBox(
  warp: Warp,
  pad = WARP_BOX_PAD,
  steps = WARP_DRAW_STEPS,
): WarpBox | null {
  const f = warpMapper(warp);
  const n = Math.max(2, Math.round(steps));
  let x0 = Infinity;
  let y0 = Infinity;
  let x1 = -Infinity;
  let y1 = -Infinity;
  for (let j = 0; j <= n; j++) {
    for (let i = 0; i <= n; i++) {
      const p = f(i / n, j / n);
      if (!finite(p[0]) || !finite(p[1])) continue;
      if (p[0] < x0) x0 = p[0];
      if (p[1] < y0) y0 = p[1];
      if (p[0] > x1) x1 = p[0];
      if (p[1] > y1) y1 = p[1];
    }
  }
  if (!finite(x0) || !finite(y0)) return null;
  if (x1 - x0 < MIN_SURFACE_SIDE || y1 - y0 < MIN_SURFACE_SIDE) return null;

  const qb = quadBounds(warp.quad);
  const reach = SURFACE_WINDOW * Math.max(qb.x1 - qb.x0, qb.y1 - qb.y0);
  if (!finite(reach)) return null;
  const wx0 = Math.max(x0 - pad, qb.x0 - reach);
  const wy0 = Math.max(y0 - pad, qb.y0 - reach);
  const wx1 = Math.min(x1 + pad, qb.x1 + reach);
  const wy1 = Math.min(y1 + pad, qb.y1 + reach);
  if (!(wx1 > wx0) || !(wy1 > wy0)) return null;
  return { x: wx0, y: wy0, w: wx1 - wx0, h: wy1 - wy0 };
}

/**
 * ТОЧКА БИКУБИЧЕСКОГО ПАТЧА БЕЗЬЕ 4×4 — тензорное произведение кубических Бернштейнов: сначала
 * четыре строки сворачиваются по `u`, затем полученная четвёрка — по `v`.
 *
 * ⚠ ПАРАМЕТР НЕ КЛАМПИТСЯ, в отличие от билинейной ветки. Патч определён многочленом на всей
 * прямой, а зажимать `u` в [0..1] значило бы приклеивать всё, что снаружи, к кромке: у вставки,
 * чей регион `WarpRegion` меньше единичного, это ровно нормальный рабочий случай, а у превью —
 * законный вынос картинки за рамку.
 *
 * ТОЖДЕСТВО ТОЧНОЕ: при `pts[i][j] = [j/3, i/3]` сумма `Σ B_i(t)·(i/3)` равна `t` алгебраически,
 * поэтому вход в режим warp не двигает ни одного пикселя — это утверждается пробой 2 `qa-warp`.
 */
export function bezierPatchPoint(g: WarpGrid, u: number, v: number): Pt {
  const bu = bern3(u);
  const bv = bern3(v);
  let x = 0;
  let y = 0;
  for (let i = 0; i < 4; i++) {
    for (let j = 0; j < 4; j++) {
      const w = bv[i] * bu[j];
      const p = g.pts[i * 4 + j];
      x += w * p[0];
      y += w * p[1];
    }
  }
  return [x, y];
}

/** Четыре кубических бернштейна в точке t. */
function bern3(t: number): [number, number, number, number] {
  const s = 1 - t;
  return [s * s * s, 3 * s * s * t, 3 * s * t * t, t * t * t];
}

/**
 * ТОЧКА СЕТКИ — билинейно внутри клетки контрольных точек. Ветка для решёток плотнее 4×4, где
 * кубика на клетку нет; редактор её пока не строит, но `kind` уже умеет её назвать.
 */
export function gridPoint(g: WarpGrid, u: number, v: number): Pt {
  const cx = (g.cols - 1) * Math.min(1, Math.max(0, u));
  const cy = (g.rows - 1) * Math.min(1, Math.max(0, v));
  const i0 = Math.min(g.cols - 2, Math.floor(cx));
  const j0 = Math.min(g.rows - 2, Math.floor(cy));
  const fx = cx - i0;
  const fy = cy - j0;
  const at = (i: number, j: number): Pt => g.pts[j * g.cols + i];
  const top = add(mul(at(i0, j0), 1 - fx), mul(at(i0 + 1, j0), fx));
  const bot = add(mul(at(i0, j0 + 1), 1 - fx), mul(at(i0 + 1, j0 + 1), fx));
  return add(mul(top, 1 - fy), mul(bot, fy));
}

/**
 * CSS-МАТРИЦА ДЛЯ ЭЛЕМЕНТА `natW × natH` с `transform-origin: 0 0`.
 *
 * Тот же довод, что у `backdropMatrix`: юнит платы и CSS-пиксель мирового блока — одно и то же
 * число, поэтому матрица ложится в него без пересчёта. `matrix3d` вместо `matrix` потому, что
 * перспективу двумерная матрица выразить не может — у неё нет строки `g h`.
 */
export function quadCss(q: Quad, natW: number, natH: number): string {
  const m = homographyFromQuad(q);
  const sx = natW > 0 ? 1 / natW : 1;
  const sy = natH > 0 ? 1 / natH : 1;
  const a = m[0] * sx;
  const b = m[3] * sx;
  const g = m[6] * sx;
  const c = m[1] * sy;
  const d = m[4] * sy;
  const h = m[7] * sy;
  const q3 = (n: number) => Math.round(n * 1e6) / 1e6;
  // Столбцами, как требует CSS: (a b 0 g)(c d 0 h)(0 0 1 0)(e f 0 1).
  return `matrix3d(${[a, b, 0, g, c, d, 0, h, 0, 0, 1, 0, m[2], m[5], 0, 1].map(q3).join(', ')})`;
}

