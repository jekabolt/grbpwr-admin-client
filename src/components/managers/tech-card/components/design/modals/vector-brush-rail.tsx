/**
 * РЕЙКА КИСТЕЙ полноэкранного векторного редактора — все органы, которые НЕ являются холстом.
 *
 * ОДНА РЕЙКА, НЕСКОЛЬКО КОНТЕКСТОВ, И ЭТО ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА. Пока ничего не выбрано, рейка
 * правит КИСТЬ В РУКЕ — вид шва, размер, цвет и «строительность» СЛЕДУЮЩЕГО штриха. Как только
 * инструмент `select` взял штрих, ровно те же органы правят ВЫБРАННЫЙ штрих. А когда в руке
 * круглый ниб (ластик или штамп), орган размера правит ЕГО диаметр — третий контекст того же
 * органа. Отдельные пульты на одни и те же свойства разъехались бы первой же правкой (у одного
 * появился бы орган, которого нет у другого), а человек получил бы два места, где «вид шва»
 * отвечает по-разному. Заголовок группы всегда говорит, каким из контекстов она сейчас является.
 *
 * ОБРАЗЦЫ РИСУЕТ ТОТ ЖЕ `strokeGeometry`, ЧТО СЦЕНУ, ЭКСПОРТ И РАСТР, — и в боксе 200 юнитов,
 * то есть в масштабе обычного чертежа, БЕЗ подмены scaleRef. Прежний пикер рисовал образец
 * 44×12 и девять видов были неотличимы: волна зигзага в 44-юнитовом боксе — полтора пикселя.
 * Образец шириной в честные 200 юнитов, показанный 1:1, — это тот же штрих, каким он ляжет на
 * плату, и различимость здесь свойство геометрии, а не увеличения. ОБРАЗЕЦ ТЕПЕРЬ ОДИН — вида,
 * выбранного в списке (Y-6); довод о честном боксе этим не тронут: он о масштабе, а не о числе
 * образцов, и девять боксов по 200 юнитов уносили под нижний край всё, что крутят чаще.
 *
 * ЗДЕСЬ ЖЕ ЖИВУТ ЗНАЧКИ ИНСТРУМЕНТОВ (`TOOL_ICONS`, `ToolIcon`) — их рисует не полоса над
 * холстом, а этот файл, потому что рисующая идиома (инлайновый `<svg>` под `currentColor`) уже
 * заведена здесь `StitchSample`, и второй такой же набор в соседнем файле разошёлся бы с этим
 * первой же правкой толщины линии.
 */

/** Бокс образца, в юнитах И в пикселях разом (1:1 — см. довод в шапке). */
const SAMPLE_W = 200;

/**
 * ФОРМЫ КАДРА, НАЗВАННЫЕ ИМЕНАМИ (E-18). Значение — ровно то, что написано на чипе: ширина,
 * делённая на высоту, поэтому «16:9» это альбом, а «4:5» — портрет, и переворачивает их чип ⇄.
 * Читать значение с ярлыка нельзя (`'4:5'` пришлось бы парсить на каждом кадре), но писать их
 * порознь — значит однажды разойтись: пара живёт одной строкой.
 */
const CROP_RATIOS: readonly { label: string; value: number }[] = [
  { label: '1:1', value: 1 },
  { label: '4:5', value: 4 / 5 },
  { label: '3:4', value: 3 / 4 },
  { label: '2:3', value: 2 / 3 },
  { label: '16:9', value: 16 / 9 },
];

/**
 * Одно ли это отношение. Сравнивать дроби на `===` нельзя: `16/9` с провода, `16/9` из чипа и
 * `1/(9/16)` после переворота — три РАЗНЫХ числа с плавающей точкой, и подсветка выбранного чипа
 * гасла бы после каждого ⇄. Допуск в тысячную неразличим на экране: 4:5 и 401:500 — одна рамка.
 */
const sameRatio = (a: number | null, b: number | null): boolean =>
  a !== null && b !== null && Math.abs(a - b) < 1e-3;

/**
 * ВЫСОТА ОБРАЗЦА РАСТЁТ ПО ТОЛЩИНЕ НИТИ — И ТОЛЬКО ПО НЕЙ, потому что поперёк линии меряет она
 * одна. Это та же граница осей, по которой построен `strokeGeometry`: ВДОЛЬ линии (период волны,
 * шаг прокола, ритм пунктира) считает длина стежка, ПОПЕРЁК (амплитуда, зазор между рядами, вылет
 * зубца) — толщина нити. Вдоль линии образец смотрит в СВОЮ ШИРИНУ, а она фиксирована в 200
 * юнитов, так что стежку в этой формуле делать нечего.
 *
 * АРИФМЕТИКА МНОЖИТЕЛЯ, А НЕ ВКУС. Самый широкий поперёк вид — зигзаг: размах ±1.8·G плюс половина
 * нити 0.5·G с каждой стороны, итого 4.6·G во всю ширь (следом идут каверстич 4.2·G и оверлок
 * ≈3.9·G). В боксе шириной 200 юнитов G = gauge × SAMPLE_W / GAUGE_REF = 0.2 × gauge, значит
 * фигура занимает 0.92 × gauge пикселей — 1.1 это тот же множитель с запасом на круглую каппу.
 *
 * 22 — ПОЛ И ПРЕЖНИЙ БОКС. На всём видимом диапазоне нити (MIN_GAUGE..MAX_GAUGE = 1..20) высота
 * так и остаётся 22: 20 × 1.1 = 22 ровно. Расти бокс начинает только на числах, которых рукой не
 * набрать, — у штриха из старого документа, где формат хранит нить до 60. Ветку не убрать: такой
 * штрих можно ВЫБРАТЬ, и тогда образец обязан показать его целиком, а не срезанным краем.
 */
/**
 * ВЫСОТА ОБРАЗЦА — ПОД ВЫЛЕТ ИМЕННО ЭТОГО ВИДА, А НЕ ПОД САМЫЙ ШИРОКИЙ ИЗ ВСЕХ (круг 15).
 *
 * Прежняя формула `max(22, gauge·5)` держала одно число «5», выведенное для самого широкого
 * СИММЕТРИЧНОГО вида (зигзаг, ±1.8·G плюс нить = 4.6·G). С приходом односторонних видов она
 * начала врать в обе стороны разом: safety тянется на 6·G ВНИЗ и был бы срезан краем бокса, а
 * `plain` получал бы бокс ростом с зигзаг. Теперь вылет спрашивается у самой геометрии
 * (`strokeAcross`), то есть у той же таблицы констант, из которой фигура и строится, — разойтись
 * им негде по построению.
 *
 * ПУТЬ У ОДНОСТОРОННЕГО ВИДА НЕ ПО ЦЕНТРУ БОКСА. Фигура центрируется целиком, а линия садится
 * туда, где ей положено относительно фигуры, — иначе обмётка висела бы половиной за краем.
 */
const sampleBox = (brush: StitchKey, gauge: number) => {
  const a = strokeAcross(brush, gauge);
  const fig = a.up + a.down + gauge;
  const h = Math.max(22, Math.ceil(fig + gauge));
  return { h, y: (h - fig) / 2 + a.up + gauge / 2 };
};

/**
 * ПОТОЛОК ВЫСОТЫ ОБРАЗЦА НА ЭКРАНЕ (круг 15, J-37).
 *
 * Владелец: «когда мы меняем thred превью линии может настолько сильно увеличиться, что неудобно
 * с этим работать — надо, чтобы превью бокс не увеличивался так сильно». Замерено на этом дереве
 * (после волны стежков, переписавшей формулу на `strokeAcross`): нить 2 → 22 px, 8 → 22, 20 → 40,
 * 60 → 120, 200 → 400. Рейка (264 × 818 на экране 900) уходит в скролл на нити 200:
 * `scrollHeight` 1032 против `clientHeight` 818, то есть цвет, ластик и кроп уезжают под нижний
 * край ровно тогда, когда крутят нить.
 *
 * 44 — ДВЕ ВЫСОТЫ БАЗОВОГО БОКСА, и это наибольшая высота, при которой рейка не скроллится ни на
 * одной нити диапазона (замерено). Меньше — и обычные швы теряли бы в различимости зря.
 */
const PREVIEW_MAX_H = 44;

/**
 * ЛЕСТНИЦА НАЗЫВАЕМЫХ ДОЛЕЙ. Масштаб обязан быть ПРОИЗНОСИМЫМ: подпись «shown at ½» — это
 * утверждение о числе, и «shown at 0.367» ни о чём не говорит руке. Поэтому берётся не
 * `44/h`, а первая доля лестницы, при которой образец в потолок ВЛЕЗАЕТ, — тогда подпись верна
 * буквально, а не приблизительно.
 */
const SCALE_LADDER: [number, string][] = [
  [1 / 2, '½'],
  [1 / 3, '⅓'],
  [1 / 4, '¼'],
  [1 / 6, '⅙'],
  [1 / 8, '⅛'],
  [1 / 12, '1⁄12'],
  [1 / 16, '1⁄16'],
  [1 / 24, '1⁄24'],
  [1 / 32, '1⁄32'],
];

/**
 * Во сколько раз образец показан мельче натуральной величины, и как это назвать словом.
 *
 * ⚠ ОБРЕЗАТЬ НЕЛЬЗЯ, И ЭТО НЕ ВКУС. Срезанный краем зигзаг читается как ДРУГАЯ МАШИНА — прямая
 * строчка с зубцами по кромке, — то есть орган выбора начал бы врать о том, что выбирают. Поэтому
 * шов уменьшается целиком, тем же `strokeGeometry`, и масштаб называется вслух.
 */
export const previewScale = (naturalH: number): { k: number; label: string | null } => {
  if (naturalH <= PREVIEW_MAX_H) return { k: 1, label: null };
  for (const [k, label] of SCALE_LADDER) {
    if (naturalH * k <= PREVIEW_MAX_H) return { k, label };
  }
  const last = SCALE_LADDER[SCALE_LADDER.length - 1];
  return { k: last[0], label: last[1] };
};
/** Одна высота на ВСЕ строки списка: разные высоты читались бы как разный вес видов. */
const rowSampleH = (gauge: number) =>
  Math.max(...STITCHES.map((st) => sampleBox(st.key, gauge).h));

/**
 * ОБРАЗЕЦ ГОВОРИТ О ФОРМЕ И РАЗМЕРЕ, НО НЕ О ЦВЕТЕ, и это решение, а не упущение. Цвет нити виден
 * на самой плате и в ряду плашек ниже; окрашенный образец не добавил бы к этому ничего, зато
 * белая нить сделала бы все девять образцов НЕВИДИМЫМИ — пикер машин пропал бы целиком ровно на
 * той настройке, ради которой белую нить и завели (разметка по тёмной фотографии).
 */
export function StitchSample({
  brush,
  gauge,
  step,
  dashed,
  width = SAMPLE_W,
  height,
}: {
  brush: StitchKey;
  gauge: number;
  /**
   * Длина стежка. Она задаёт ритм ВДОЛЬ линии — образец обязан слушать её, иначе покажет не тот
   * шов. В ВЫСОТУ бокса она не входит вовсе: вдоль линии образец смотрит в свою ширину.
   */
  step: number;
  dashed: boolean;
  /** Окно образца в юнитах платы. Список и триггер меряют свою ширину сами — масштаб 1:1. */
  width?: number;
  /** Навязанная высота: у списка она ОДНА на все строки, иначе список «дышит» при прокрутке. */
  height?: number;
}) {
  // ВЫСОТА БОКСА — ПО НИТИ, СТЕЖОК СЮДА НЕ ВХОДИТ (Д-3). Прежний `sampleH(max(gauge, step))`
  // пережил свою причину: он писался, когда поперечные размеры шва считались от стежка, а с тех
  // пор их посадили на нить. На паре «нить 1, стежок 60» настоящий шов остаётся ниткой в пятую
  // долю пикселя, а бокс раздувался до 66 пикселей почти пустого места и уносил нижние органы
  // рейки за нижний край. Образец обязан быть ростом с то, что показывает.
  const box = sampleBox(brush, gauge);
  const h = height ?? box.h;
  // Доля пути в боксе считается от ТОЙ ЖЕ высоты, в которой он рисуется: навязанная строкой
  // высота выше собственной, и центр фигуры обязан ехать вместе с ней, а не остаться на 0.5.
  const yFrac = (box.y + (h - box.h) / 2) / h;
  const g = strokeGeometry(
    {
      tool: 'line',
      brush,
      weight: 'thin',
      gauge,
      step,
      dashed,
      pts: [
        [0.02, yFrac],
        [0.98, yFrac],
      ],
    },
    width,
    h,
    /**
     * ⚠ ОБРАЗЕЦ РИСУЕТСЯ В МАСШТАБЕ ЧЕРТЕЖА, А НЕ КОРОБКИ.
     *
     * Без этого аргумента размеры шва считались долей от ширины коробки (200), то есть впятеро
     * мельче, чем на плате (1000). Пока нить по умолчанию была 6, это ещё сходило: период зигзага
     * выходил 6 px. После того как диапазон нити похудел до умолчания 2, все признаки съехали ниже
     * двух пикселей — период зигзага 2.0, зазор двухигольной 0.8 при толщине 0.4 — и ДЕВЯТЬ РАЗНЫХ
     * МАШИН стали рисовать в пикере одну и ту же серую линию. Переключение вида перестало менять
     * хоть что-то видимое, то есть орган выбора ослеп ровно от починки соседнего.
     */
    GAUGE_REF,
  );
  /* ОБРАЗЕЦ РИСУЕТСЯ В НАТУРАЛЬНЫХ ЮНИТАХ И ПОКАЗЫВАЕТСЯ УМЕНЬШЕННЫМ: `viewBox` остаётся тем же,
     а меняется размер на экране — значит на экране ТОТ ЖЕ шов, просто дальше от глаза. Считать
     геометрию в уменьшенном боксе значило бы построить ДРУГОЙ шов (признаки ушли бы под пиксель),
     то есть ровно ту ложь, ради избавления от которой у `strokeGeometry` есть аргумент масштаба. */
  const shrink = previewScale(h);
  return (
    <svg
      width={Math.round(width * shrink.k)}
      height={Math.round(h * shrink.k)}
      viewBox={`0 0 ${width} ${h}`}
      aria-hidden
      data-preview-scale={shrink.label ?? '1'}
      /* Натуральная высота рядом с показанной — так подпись становится ПРОВЕРЯЕМОЙ: доля из
         подписи, умноженная на неё, обязана дать нарисованное. */
      data-preview-natural-h={h}
      className='block max-w-full shrink-0'
    >
      {g.offsets.map((dy, k) => (
        <path
          key={k}
          d={g.d}
          transform={`translate(0 ${dy})`}
          fill='none'
          stroke='currentColor'
          strokeWidth={g.strokeWidth}
          strokeDasharray={g.dash || undefined}
          strokeLinecap='round'
          strokeLinejoin='round'
        />
      ))}
    </svg>
  );
}

