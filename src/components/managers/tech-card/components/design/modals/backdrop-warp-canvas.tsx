import { useEffect, useRef, useState } from 'react';

import {
  drawWarped,
  FULL_REGION,
  WARP_DRAW_STEPS,
  type Quad,
  type WarpBox,
  type WarpGrid,
} from './transform-frame';

/**
 * ШАБЛОН, ПОКАЗАННЫЙ КАНВАСОМ, — ПОТОМУ ЧТО CSS ЭТОГО НЕ УМЕЕТ (H-4).
 *
 * Без сетки шаблон показывает обычный `<img>` с `matrix3d` из `quadCss`: одна GPU-матрица,
 * идеальная резкость, ноль работы на кадр. Проективное преобразование двумерная CSS-матрица
 * выразить может; ИСКРИВЛЁННУЮ ПОВЕРХНОСТЬ — нет, у неё для этого нет чисел вовсе. Поэтому показ
 * переезжает сюда ровно при ИСКРИВЛЁННОЙ сетке, а не при всякой живой: рисование треугольниками
 * оставляет на плоских заливках диагональную штриховку по швам, и при тождественной сетке —
 * то есть пока человек просто СМОТРИТ на меш, ещё ничего не потянув, — она была бы платой ни за
 * что. Тождество остаётся на `<img>`, резким. А рисует искривление ТА ЖЕ `drawWarped`, которая
 * положит картинку при любом будущем коммите: два рисовальщика одной геометрии разошлись бы
 * молча, и первым узнал бы об этом человек, у которого шаблон прыгнул на Enter.
 *
 * ⚠ РАЗМЕР — ПО КОРОБКЕ ОБРАЗА, А НЕ ПО ПЛАТЕ, И ЭТО УРОК H-3. Холст размером в плату отрезал бы
 * всё, что законно свисает за её край, — ровно та асимметрия «картинку видно, а её края нет»,
 * на которую владелец жаловался про направляющие.
 *
 * ⚠ КОРОБКУ СЧИТАЕТ НЕ ЭТОТ ФАЙЛ, А `warpSurfaceBox`, И ОНА ПРИЕЗЖАЕТ ПРОПОМ. Довод — ревю H-4:
 * у вырожденной поверхности (все шестнадцать узлов в одной точке, схлопывание в линию) коробки
 * НЕТ, и компонент, считавший её сам, в этом случае возвращал `null` — то есть подложка переставала
 * существовать без единого слова. Решение «чем показать шаблон» принимает `renderBackdrop`, у
 * которого есть вторая дверь — резкий `img`; здесь для неё нет ни матрицы, ни разметки. Считать
 * коробку в двух местах было бы хуже вдвойне: два построителя одной геометрии расходятся молча.
 *
 * ⚠ ХОЛСТ НИКУДА НЕ УХОДИТ. Подложка не попадает ни на сервер, ни в сплющенную картинку (см.
 * шапку `vector-backdrop.ts`): `composeScene` строит композит из ЯВНЫХ входов и DOM платы не
 * снимает. Этот элемент — показ, и только показ.
 */

/**
 * ПОТОЛОК БИТМАПА — САМОЕ ВНЕШНЕЕ ОБЕЩАНИЕ ЭТОГО ФАЙЛА: НИ ОДИН ЖЕСТ И НИ ОДНА ЗАПИСЬ НЕ МОГУТ
 * ЗАСТАВИТЬ ЕГО ПОПРОСИТЬ У БРАУЗЕРА БОЛЬШЕ.
 *
 * ⚠ ЧИСЛО ЗАМЕРЕНО С ДВУХ СТОРОН. Снизу: законные холсты этого шаблона — 964 × 1204 при
 * вписывающем зуме и 1504 × 1878 при шести шагах приближения, то есть 2.8 Мпикс худший из
 * наблюдённых. Сверху: обычный драг узла в трапеции просил 195146 × 291827 (57 ГИГАпикселей) —
 * браузер такой холст не выдаёт вовсе, и шаблон исчезал целиком (яркость окна над ним 203.89 →
 * 249.25, бумажно-белое). 4096 — вшестеро больше самого большого законного и на четыре порядка
 * меньше отказного; в память это 67 МБ RGBA, то есть потолок, который никогда не бьёт по руке,
 * но и не даёт превью убить показ.
 *
 * ⚠ ПОТОЛОК СТОИТ НА ПЛОЩАДИ ТОЖЕ, А НЕ ТОЛЬКО НА СТОРОНЕ: 4096 × 4096 браузер держит, а
 * 4096 × 60000 — уже нет, и одной проверки стороны не хватило бы.
 */
const MAX_CANVAS_SIDE = 4096;
const MAX_CANVAS_PX = MAX_CANVAS_SIDE * MAX_CANVAS_SIDE;
/*
 * СКОЛЬКО ТРЕУГОЛЬНИКОВ НА СТОРОНУ КЛАДЁТ РИСОВАЛЬЩИК — `WARP_DRAW_STEPS`, И ЭТО ЧИСЛО ЗАМЕРЕНО.
 *
 * Холст перерисовывается на КАЖДОЕ движение указателя, то есть цена этого числа — кадр под
 * рукой. Замер (`warp-cost.mjs`, шаблон почти во всю плату, 60 движений мыши подряд):
 *   · при вписывающем зуме — холст 964 × 1204, интервал кадра медиана 16.7 мс, p90 16.8, max 17.8;
 *   · при шести шагах приближения — холст 1504 × 1878, медиана 16.7 мс, p90 17.0, max 17.9.
 * То есть 24 клетки на сторону (1152 клипованных треугольника) укладываются в кадр 60 к/с с
 * запасом, и опускать число ради скорости, которой и так хватает, было бы платой швами ни за что.
 *
 * ⚠ ОНО ПЕРЕЕХАЛО В `transform-frame.ts` НЕ РАДИ ПОРЯДКА. Тем же числом снимается коробка образа
 * и им же проверяется горизонт: сторож, меряющий реже рисовальщика, пропускает ровно то, на чём
 * рисовальщик ломается (замерено: при 13 шагах снятия против 25 рисуемых до 5.14 юнита шаблона
 * уходило за кромку холста молча).
 */
/**
 * ПОТОЛОК СУПССЕМПЛА. Один пиксель холста на юнит платы читается мылом на сильном приближении, а
 * выше двух — это уже память и время без прибыли, которую видно глазом: у шаблона непрозрачность
 * 45 % и он под линиями, а не над ними. Замер выше снят В ТОМ ЧИСЛЕ на приближении, где этот
 * потолок работает, — кадр остался шестидесятым.
 */
const MAX_SS = 2;

export function BackdropWarpCanvas({
  src,
  natW,
  natH,
  quad,
  grid,
  box,
  opacity,
  depth,
  zoom,
}: {
  src: string;
  natW: number;
  natH: number;
  quad: Quad;
  grid: WarpGrid;
  /** Коробка образа В ЮНИТАХ ПЛАТЫ, снятая `warpSurfaceBox`. См. довод в шапке. */
  box: WarpBox;
  opacity: number;
  /** Тот же признак, что у `img[data-backdrop]`: под пикселями шаблон или над ними. */
  depth: 'over' | 'under';
  /** Приближение вида — им выбирается супссемпл, и только им (до потолка). */
  zoom: number;
}) {
  const ref = useRef<HTMLCanvasElement | null>(null);
  const [img, setImg] = useState<HTMLImageElement | null>(null);

  /* КАРТИНКА ГРУЗИТСЯ ОДИН РАЗ НА АДРЕС. Ни `crossOrigin`, ни прокси здесь нет нарочно: пиксели у
     этого холста никто не спрашивает (подложка не идёт ни в один сохраняемый композит), значит
     пачкать нечего, а лишний прокси умел бы отказывать по своим причинам и врать про удаление. */
  useEffect(() => {
    if (!src) {
      setImg(null);
      return;
    }
    let live = true;
    const el = new Image();
    el.decoding = 'async';
    el.onload = () => {
      if (live) setImg(el);
    };
    el.onerror = () => {
      if (live) setImg(null);
    };
    el.src = src;
    return () => {
      live = false;
    };
  }, [src]);

  /**
   * СУПССЕМПЛ — ЖЕЛАНИЕ ВИДА, ПРИЖАТОЕ ПОТОЛКОМ БИТМАПА.
   *
   * ⚠ ПОТОЛОК ДЕЙСТВУЕТ ЧЕРЕЗ НЕГО, А НЕ ЧЕРЕЗ ОБРЕЗКУ КОРОБКИ, И ЭТО НАРОЧНО: коробка — это
   * МЕСТО, и урезав её, мы отрезали бы часть шаблона, ничего об этом не сказав. Опущенный
   * супссемпл оставляет на экране ВЕСЬ образ, просто мягче; а окно досягаемости (`warpSurfaceBox`)
   * уже не даёт коробке уйти в сотни тысяч юнитов, поэтому мягче здесь — это единицы процентов,
   * а не мыло.
   */
  const ss = (() => {
    const want = Math.min(MAX_SS, Math.max(1, zoom || 1));
    const w = Math.max(1, box.w);
    const h = Math.max(1, box.h);
    const cap = Math.min(
      MAX_CANVAS_SIDE / w,
      MAX_CANVAS_SIDE / h,
      Math.sqrt(MAX_CANVAS_PX / (w * h)),
    );
    return Number.isFinite(cap) && cap < want ? Math.max(cap, 1e-4) : want;
  })();

  useEffect(() => {
    const c = ref.current;
    if (!c || !img || natW <= 0 || natH <= 0) return;
    const w = Math.max(1, Math.min(MAX_CANVAS_SIDE, Math.round(box.w * ss)));
    const h = Math.max(1, Math.min(MAX_CANVAS_SIDE, Math.round(box.h * ss)));
    if (c.width !== w) c.width = w;
    if (c.height !== h) c.height = h;
    const ctx = c.getContext('2d');
    if (!ctx) return;
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.clearRect(0, 0, w, h);
    /* Квад переводится В ПИКСЕЛИ ЭТОГО ХОЛСТА здесь, один раз: `drawWarped` намеренно не знает
       ни про мир, ни про масштаб — знай она их, у неё было бы два способа сказать одно и то же. */
    const inCanvas = quad.map(
      (p) => [(p[0] - box.x) * ss, (p[1] - box.y) * ss] as [number, number],
    ) as unknown as Quad;
    drawWarped(ctx, img, natW, natH, { quad: inCanvas, grid }, FULL_REGION, WARP_DRAW_STEPS);
  }, [img, box, quad, grid, natW, natH, ss]);

  return (
    <canvas
      ref={ref}
      data-backdrop-warp={depth}
      className='pointer-events-none absolute block max-w-none'
      style={{
        left: `${box.x}px`,
        top: `${box.y}px`,
        width: `${box.w}px`,
        height: `${box.h}px`,
        opacity,
      }}
    />
  );
}
