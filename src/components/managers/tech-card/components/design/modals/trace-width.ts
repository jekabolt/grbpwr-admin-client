/**
 * ═══ ТОЛЩИНА ШТРИХА — ОДНО ПРАВИЛО НА ОБОИХ ЧИТАТЕЛЕЙ ═══════════════════════════════════════
 *
 * Этот файл существует по той же причине, что и `trace-types.ts`: толщину читают ДВОЕ —
 * `trace-measure.ts` (кладёт её в `TraceComponent.width`) и `trace-centerline.ts` (считает её
 * ПОРЕБЁРНО и превращает в `gauge` штриха). Пока правило стояло в обоих файлах своей копией, оно
 * было ОДИНАКОВО НЕВЕРНЫМ; починка в одном месте молча разошлась бы со второй копией, и разошлась
 * бы не сразу, а на первом же чертеже, где перо у ребра и перо у компоненты разные.
 *
 * Правило зовётся `widthFromRadii`, и оно тут ровно одно.
 *
 * ── ЧТО БЫЛО СЛОМАНО: `2·median(dt|skel) − 1` ТОЧНО ТОЛЬКО НА 0° И 90° ───────────────────────
 *
 * Distance transform меряет расстояние до ближайшего ЦЕНТРА пикселя бумаги, а не до края краски.
 * У полосы, лежащей вдоль решётки, этот центр стоит ровно на полпикселя дальше края — «−1» в
 * формуле и есть та компенсация, и калибровка отчёта (3 px → dt 2, 5 → 3, 9 → 5) снята именно
 * так. Под любым другим углом ближайший центр стоит ГДЕ ПРИДЁТСЯ: у полосы 3 px под 30° он лежит
 * по диагонали, dt = √2, и толщина возвращается как 1.83 вместо 3.00 — минус 39 %. Замер, семь
 * углов × три толщины, — `tmp/dsgprobe/angle-width.mjs`:
 *
 *      истинная   0°     15°    30°    45°    60°    75°    90°
 *         3      3.00   3.00   1.83   3.47   1.83   3.00   3.00
 *         5      5.00   3.47   4.66   4.66   4.66   3.47   5.00
 *         9      9.00   7.94   7.94   9.00   7.94   7.94   9.00
 *
 * На настоящем флэте прямых и осевых линий почти нет — кривая пройма, косая кокетка, дуга оката, —
 * поэтому «почти везде» здесь не оборот речи: осевых линий на чертеже единицы.
 *
 * ── ПОЧЕМУ НЕ ПОСТОЯННАЯ ПОПРАВКА И НЕ ПЕРЕДИСКРЕТИЗАЦИЯ ────────────────────────────────────
 *
 * ЛЮБАЯ поправка, зависящая только от dt, обречена: под 30° dt = 1.41 ПРОМАХИВАЕТСЯ МИМО истинных
 * 1.5 В МИНУС (ближайший центр бумаги стоит не по нормали), а под 45° dt = 2.24 промахивается в
 * плюс. Одним знаком это не лечится.
 *
 * ПЕРЕДИСКРЕТИЗАЦИЯ ×k ЗАМЕРЕНА И ОТКЛОНЕНА. Квантование падает как 1/k, то есть ×2 оставляет
 * ±0.25 px на радиусе — ±17 % на толщине 3 px, — а ×4 на плите 1600×2000 стоит 51 млн суб-пикселей
 * и сотен мегабайт. Замер лаборатории (`tmp/dsgprobe/w-lab.mjs`, кандидат A) на семи углах: ×2
 * даёт 2.33…2.66 вместо 3 и 3.50…4.50 вместо 5, то есть МЕСТАМИ ХУЖЕ ИСХОДНОГО. Дело в том, что
 * скелет остаётся в родной решётке, и уточнённая гребневая линия суб-сетки под ним не лежит.
 *
 * ОДНОЙ БИНАРНОЙ МАСКИ НЕ ХВАТАЕТ — и это тоже замер, а не соображение. Порог Otsu под 45°
 * возвращает полосу 3 px как 3.56 px краски на пиксель длины: она РЕАЛЬНО толще на решётке.
 * Профиль, снятый по маске, честно и читает 3.77 (+26 %). Полутон до порога — единственное место,
 * где ширина ещё цела.
 *
 * ── ЧТО СТОИТ ВМЕСТО ЭТОГО: ПРОФИЛЬ ПОКРЫТИЯ ПОПЕРЁК ОСИ ────────────────────────────────────
 *
 * В каждом пикселе скелета берётся локальная КАСАТЕЛЬНАЯ (PCA по пикселям скелета в окне
 * `TANGENT_RADIUS`), и по НОРМАЛИ к ней снимается профиль полутона. Толщина — расстояние между
 * двумя точками ПОЛУСПАДА: там, где темнота падает ниже половины своей вершины.
 *
 * Полуспад ОТ ВЕРШИНЫ, а не от абсолютного 0.5 покрытия, и это существенно дважды:
 *   • серая линия (тон краски 128) не имеет покрытия 0.5 нигде, и абсолютный порог вернул бы ей
 *     нулевую толщину;
 *   • волосяная линия в один пиксель не насыщается совсем, и абсолютный порог съел бы её.
 * От вершины правило БЕЗРАЗМЕРНО: ни белая точка, ни тон краски в него не входят.
 *
 * Марш ОБРЫВАЕТСЯ НА ПЕРВОМ ПЕРЕСЕЧЕНИИ, и это не оптимизация, а защита: двойная отстрочка идёт
 * рядами в 14 px, и интеграл покрытия вдоль нормали втянул бы соседний ряд в толщину этого.
 *
 * Результат правится обратно В ТУ ЖЕ КОЛЕЮ, в которой поле жило раньше: в `dt` кладётся
 * `истинная полутолщина + 0.5`, то есть ровно то число, которое точный EDT дал бы этой полосе,
 * лежи она вдоль решётки. Поэтому «−1» в правиле остаётся на месте и остаётся ОСМЫСЛЕННЫМ — и
 * калибровка отчёта (3 → dt 2, 5 → 3, 9 → 5) остаётся верной буквально.
 *
 * Замер после починки — тот же `angle-width.mjs`, худшая клетка −4.5 %.
 *
 * ── ЧЕГО ЭТО НЕ ДЕЛАЕТ ──────────────────────────────────────────────────────────────────────
 *
 * Уточняются ТОЛЬКО пиксели скелета. Вне оси `dt` остаётся сырым расстоянием до центра ближайшего
 * пикселя бумаги — и это правильно: вне оси поле читают морфологические шаги (эрозия при
 * переоткрытии), которым нужна именно решёточная полудистанция, а не толщина. Толщина же
 * определена на оси и только там.
 */

/** Радиус окна, в котором PCA по пикселям скелета даёт локальную касательную. */
export const TANGENT_RADIUS = 3;

/**
 * Во сколько раз главное собственное число облака скелета должно превышать второе, чтобы
 * касательная считалась определённой. Перекрёсток даёт двумерное облако — там направления нет, и
 * профиль снимать не по чему: такой пиксель остаётся с сырым dt.
 */
export const TANGENT_ANISOTROPY = 4;

/** Шаг марша вдоль нормали, px. 0.25 против 0.1 стоит вчетверо дешевле и хуже на 0.4 % — замерено. */
export const PROFILE_STEP = 0.25;

/** Насколько дальше сырого dt разрешено уходить в поисках полуспада, px. */
export const PROFILE_MARGIN = 3;

/** Полуспад: доля вершины профиля, на которой стоит край краски. */
export const HALF_LEVEL = 0.5;

/** Тон бумаги после выравнивания фона и белой точки. Темнота = `PAPER_TONE − тон`. */
export const PAPER_TONE = 255;

/**
 * Ниже этой темноты в вершине профиль считается шумом, и пиксель остаётся с сырым dt.
 * Один тон из 255 — это ровно порог различимости, а не «запас».
 */
export const MIN_PEAK_DARKNESS = 1;

function median(sorted: number[]): number {
  const n = sorted.length;
  if (!n) return 0;
  const m = n >> 1;
  return n % 2 ? sorted[m] : (sorted[m - 1] + sorted[m]) / 2;
}

/**
 * ТОЛЩИНА ИЗ РАДИУСОВ. ЕДИНСТВЕННОЕ ПРАВИЛО, И ЗОВУТ ЕГО ОБА ЧИТАТЕЛЯ.
 *
 * `radii` — значения поля расстояний на ОСИ: у измерителя это скелет компоненты, у осевой — точки
 * одного ребра. «−1» снимает полпикселя, на которые расстояние до центра пикселя бумаги стоит
 * дальше края краски; на уточнённых `calibrateAxisRadii` значениях она снимает ровно ту же
 * половину, потому что уточнение кладёт в поле `полутолщина + 0.5`.
 *
 * Пол в 1 px существует потому, что штриха тоньше одного пикселя на растре не бывает: то, что
 * нарисовано, занимает хотя бы один пиксель, и ноль здесь означал бы не «тонко», а «не измерено».
 */
export function widthFromRadii(radii: ArrayLike<number>): number {
  if (!radii.length) return 1;
  const s: number[] = [];
  for (let i = 0; i < radii.length; i++) s.push(radii[i]);
  s.sort((a, b) => a - b);
  const w = 2 * median(s) - 1;
  return w > 1 ? w : 1;
}

/** Билинейная выборка тона с зажимом на краю плиты. Край — это бумага, а не обрыв. */
function sampleTone(tone: ArrayLike<number>, w: number, h: number, x: number, y: number): number {
  const x0 = Math.floor(x);
  const y0 = Math.floor(y);
  const fx = x - x0;
  const fy = y - y0;
  const xa = x0 < 0 ? 0 : x0 > w - 1 ? w - 1 : x0;
  const xb = x0 + 1 < 0 ? 0 : x0 + 1 > w - 1 ? w - 1 : x0 + 1;
  const ya = y0 < 0 ? 0 : y0 > h - 1 ? h - 1 : y0;
  const yb = y0 + 1 < 0 ? 0 : y0 + 1 > h - 1 ? h - 1 : y0 + 1;
  const ra = ya * w;
  const rb = yb * w;
  return (
    tone[ra + xa] * (1 - fx) * (1 - fy) +
    tone[ra + xb] * fx * (1 - fy) +
    tone[rb + xa] * (1 - fx) * fy +
    tone[rb + xb] * fx * fy
  );
}

/** Темнота в точке: бумага — 0, самая густая краска — 255. */
function darknessAt(tone: ArrayLike<number>, w: number, h: number, x: number, y: number): number {
  return PAPER_TONE - sampleTone(tone, w, h, x, y);
}

/**
 * УТОЧНИТЬ ПОЛЕ РАССТОЯНИЙ НА ОСИ — НА МЕСТЕ.
 *
 * `dt` приходит сырым (точный EDT до центра ближайшего пикселя бумаги) и уходит с ЗАМЕНЁННЫМИ
 * значениями в пикселях скелета: там теперь стоит `полутолщина по полутону + 0.5`. Вне скелета не
 * трогается ни одно число — там поле читает морфология, и ей нужна решётка.
 *
 * `tone` — полутон ПОСЛЕ выравнивания фона и белой точки, но ДО порога: бумага ≈ 255. Именно до
 * порога, потому что бинаризация и есть тот шаг, на котором ширина косой линии теряется.
 *
 * Возвращает, сколько пикселей оси удалось уточнить: остальные остались сырыми, и это нормально —
 * перекрёстки, одиночные точки и слишком блёклые места профиля не имеют.
 */
export function calibrateAxisRadii(
  dt: Float32Array,
  tone: ArrayLike<number>,
  skel: Uint8Array,
  w: number,
  h: number,
): number {
  const R = TANGENT_RADIUS;
  let refined = 0;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      if (!skel[i]) continue;

      // ── ЛОКАЛЬНАЯ КАСАТЕЛЬНАЯ: PCA по пикселям скелета в окне ──────────────────────────────
      //
      // ОДИН проход, а не два: моменты второго порядка копятся вместе с первыми, а центрирование
      // делается вычитанием в конце. Окно 7×7 обходится на КАЖДОМ пикселе оси, и второй проход
      // стоил замеренных 25 мс на плите 1600×2000 — четверть всей цены калибровки.
      let sx = 0;
      let sy = 0;
      let sxx = 0;
      let sxy = 0;
      let syy = 0;
      let m = 0;
      const yLo = y - R < 0 ? 0 : y - R;
      const yHi = y + R > h - 1 ? h - 1 : y + R;
      const xLo = x - R < 0 ? 0 : x - R;
      const xHi = x + R > w - 1 ? w - 1 : x + R;
      for (let ny = yLo; ny <= yHi; ny++) {
        const row = ny * w;
        const ay = ny - y;
        for (let nx = xLo; nx <= xHi; nx++) {
          if (!skel[row + nx]) continue;
          const ax = nx - x;
          sx += ax;
          sy += ay;
          sxx += ax * ax;
          sxy += ax * ay;
          syy += ay * ay;
          m++;
        }
      }
      if (m < 3) continue;
      const cxx = sxx - (sx * sx) / m;
      const cxy = sxy - (sx * sy) / m;
      const cyy = syy - (sy * sy) / m;
      const tr = cxx + cyy;
      const disc = Math.sqrt(Math.max(0, (tr * tr) / 4 - (cxx * cyy - cxy * cxy)));
      const l1 = tr / 2 + disc;
      const l2 = tr / 2 - disc;
      if (!(l1 > TANGENT_ANISOTROPY * Math.max(l2, 0))) continue;

      // ⚠ СОБСТВЕННЫЙ ВЕКТОР БЕРЁТСЯ ИЗ ДВУХ СТОЛБЦОВ, А НЕ ИЗ ОДНОГО, И ЭТО ЗАМЕР, А НЕ ВКУС.
      // Столбец `(cxy, l1 − cxx)` обращается в НОЛЬ ровно на горизонтали: там cxy = 0 и l1 = cxx.
      // Одного столбца хватало на всех углах, кроме 0° и 90°, — а на них уточнение молча
      // сваливалось на решётку и возвращало прежние числа. Прежние числа на осевой линии ВЕРНЫ,
      // поэтому отказ выглядел как успех: полоса 3 px давала 3.00, 5 → 5.00, 9 → 9.00, и ни один
      // гейт не краснел. Ловилось это только на ЧЁТНОЙ толщине, где решётка врёт и на осях:
      // 2 px читались как 3.00, 4 → 5.00, 6 → 7.00. Второй столбец `(l1 − cyy, cxy)` вырождается
      // на вертикали, и разом с первым — НИКОГДА: `l1 − cxx` и `l1 − cyy` оба неотрицательны и в
      // сумме дают `l1 − l2`, а он строго положителен — за этим и стоят ворота анизотропии выше.
      let vx = l1 - cyy;
      let vy = cxy;
      if (vx * vx + vy * vy < 1e-12) {
        vx = cxy;
        vy = l1 - cxx;
      }
      const len = Math.hypot(vx, vy);
      if (!(len > 1e-9)) continue;
      vx /= len;
      vy /= len;
      const nx = -vy;
      const ny = vx;

      // ── ВЕРШИНА ПРОФИЛЯ: максимум темноты в пределах ±1 px от оси ──────────────────────────
      //
      // Не темнота самого пикселя: утоньшение ставит ось с точностью до пикселя, и на полосе
      // чётной толщины она законно стоит на полпикселя в стороне от настоящего гребня. Взять
      // вершиной значение в стороне значило бы опустить уровень полуспада и вернуть линию толще.
      let peak = 0;
      for (let u = -1; u <= 1.0001; u += 0.25) {
        const v = darknessAt(tone, w, h, x + nx * u, y + ny * u);
        if (v > peak) peak = v;
      }
      if (peak < MIN_PEAK_DARKNESS) continue;
      const half = peak * HALF_LEVEL;
      const centre = darknessAt(tone, w, h, x, y);
      if (centre < half) continue; // ось вне собственного штриха — мерить нечего

      // ── ДВА ПЛЕЧА ДО ПОЛУСПАДА ────────────────────────────────────────────────────────────
      const limit = dt[i] + PROFILE_MARGIN;
      let ok = true;
      let sum = 0;
      for (let s = -1; s <= 1; s += 2) {
        let prev = centre;
        let arm = -1;
        for (let u = PROFILE_STEP; u <= limit; u += PROFILE_STEP) {
          const v = darknessAt(tone, w, h, x + nx * s * u, y + ny * s * u);
          if (v < half) {
            const drop = prev - v;
            arm = u - PROFILE_STEP + PROFILE_STEP * (drop > 1e-6 ? (prev - half) / drop : 0);
            break;
          }
          prev = v;
        }
        if (arm < 0) {
          ok = false;
          break;
        }
        sum += arm;
      }
      if (!ok) continue;

      // Полутолщина + полпикселя — та же колея, в которой поле жило до починки.
      dt[i] = sum / 2 + 0.5;
      refined++;
    }
  }
  return refined;
}
