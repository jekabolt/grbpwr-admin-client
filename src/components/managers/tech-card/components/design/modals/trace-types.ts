/** Класс компоненты. Выводится из толщины (пики KDE) и непрерывности (длина скелета). */
export type TraceClass =
  /** Стежок пунктирной строчки: короткий, вытянутый, с коллинеарными соседями. */
  | 'dash'
  /** Сплошной штрих: контур, шов, конструктивная линия. */
  | 'stroke'
  /** Залитое пятно: пуговица, люверс, лейбл. Обводится по границе, а не по оси. */
  | 'blob'
  /** Грязь: не прошла ни поддержку соседей, ни аварийный выход по площади. */
  | 'speckle';

/**
 * Одна связная компонента чернил со всем, что о ней измерено.
 *
 * Координаты — В ПИКСЕЛЯХ РАСТРА, а не в долях платы: измерение живёт в той же сетке, в которой
 * стоит distance transform, и перевод в мир платы делает тот, кто эмитит штрихи. Переводить здесь
 * значило бы округлять дважды.
 */
export type TraceComponent = {
  id: number;
  /** Пикселей чернил. */
  area: number;
  /** x0, y0, x1, y1 — включительно. */
  bbox: [number, number, number, number];
  cx: number;
  cy: number;
  /** Ориентация главной оси PCA, радианы, приведённые к [0, π): у линии нет направления. */
  theta: number;
  /** L1/L2 собственных чисел PCA. Круглая пуговица ≈ 1, стежок ≈ 4–5. */
  elongation: number;
  /**
   * ТОЛЩИНА ШТРИХА, `w = 2·median(dt|skel) − 1`.
   *
   * «−1» не косметика: 3-px линия даёт dt = 2 в центре, 5-px → 3, 9-px → 5, и без вычитания
   * единицы все три восстанавливаются на пиксель толще, чем нарисованы. Калибровка проверена.
   */
  width: number;
  /** Длина скелета в пикселях — она же признак «сплошной штрих или стежок». */
  skelLength: number;
  /** area / площадь bbox. Залитое пятно ≈ 1, штрих по диагонали мал. */
  fillRatio: number;
  /** Концы скелета (точки степени 1), в пикселях растра. */
  ends: [number, number][];
  klass: TraceClass;
};

/** Что вернул измеритель. Маски идут вместе с компонентами: по ним работают оба потребителя. */
export type TraceMeasurement = {
  w: number;
  h: number;
  /** 1 — чернила, 0 — бумага. Длина w·h. */
  mask: Uint8Array;
  /** Distance transform по чернилам, L2. Длина w·h. */
  dt: Float32Array;
  /** Утоньшённый скелет, 1 — ось. Длина w·h. */
  skel: Uint8Array;
  components: TraceComponent[];
  /**
   * Найденные моды толщины, по возрастанию. Технический чертёж рисуется дискретным набором перьев,
   * и моды реально разделены — поэтому пики KDE, а не фиксированные пороги.
   */
  widthModes: number[];
  /** То, что человек обязан прочитать: что было выброшено, что переоткрыто, где мерили наугад. */
  notes: string[];
};
