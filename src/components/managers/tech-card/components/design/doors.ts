import { revealField } from 'utils/field-errors';

import { studioSwitchSolo } from './history-recall';

/**
 * АДРЕСА ОРГАНОВ ПОЛОСЫ DESIGN — «куда идти», отдельно от «что показать».
 *
 * ЭТОТ МОДУЛЬ РОДИЛСЯ ИЗ СНОСА, А НЕ ИЗ ЗАМЫСЛА, и сказать это честнее, чем сделать вид, что он
 * был задуман. Обе функции жили в `mint-dialog.tsx` — файле, который к минту относился только
 * наполовину: вторая половина была общим словарём полосы, и на неё ссылались экраны, минта не
 * знающие вовсе (`render/what-model-gets.tsx`, `modals/what-model-gets-modal.tsx`). Когда минт
 * снесли по слову владельца («PRINT — MINTS V1 вообще этот функционал не нужен как и VERSIONS»),
 * эти двери остались бы висеть в удалённом файле и утащили бы за собой чужие экраны.
 *
 * Словарь ВИДОВ при этом сюда не переехал: он уже есть в `./views`, и `mint-dialog` держал его
 * УСТАРЕВШУЮ КОПИЮ (с меткой `SIDE L` против `side L` в `views.ts`) — ровно ту рассинхронизацию,
 * ради которой `views.ts` и заводили. Копия умерла вместе с файлом; второй раз её заводить незачем.
 */

/**
 * ДВЕРНОЙ АДРЕС СЛОТА ВЕРСТАКА.
 *
 * `revealField` (`utils/field-errors`) — это запрос по DOM к `[data-field]`, а не поиск по форме:
 * он доходит до «отрисованной вещи по этому адресу» и подсвечивает её, и на этом построено всё
 * поведение тех-карты «отказ ведёт к месту». Верстак — серверное состояние, своего пути в форме у
 * него нет, поэтому полоса объявляет свои адреса здесь, один раз, а орган верстака их штампует.
 * Унаследовать механизм стоит одного атрибута; переписать — второго «доскроллить и мигнуть»,
 * который разойдётся с первым.
 */
export function benchDoor(slot: { viewKey?: string; id?: number }): string {
  const view = (slot.viewKey ?? '').trim();
  if (view && view !== 'detail') return `design.bench.${view}`;
  return `design.bench.slot.${slot.id ?? 0}`;
}

/**
 * Дойти до двери; сказать, где она была, если двери на экране нет (закрытая вкладка, старая
 * карточка). Молчаливый неуспех здесь читался бы как сломанная кнопка, а не как «оно на другой
 * вкладке».
 */
export function openDoor(path: string, where: string, say: (m: string, t: 'error') => void): void {
  if (revealField(path)) return;
  say(`${where} — it is not on this tab`, 'error');
}

/**
 * ДВЕРЬ ЧЕРЕЗ ВИД СТУДИИ — когда поле живёт не на том экране, с которого на него показывают.
 *
 * `openDoor` выше умеет ровно одно: найти поле ЗДЕСЬ И СЕЙЧАС. Этого хватало, пока показывающий и
 * показываемое стояли на одной вкладке. Панель «what the model gets» открывается из FABRIC RENDER и
 * из 3D, а описание изделия живёт в INPUT — REFERENCES, то есть на FLAT: со стороны рендера блок
 * РАЗМОНТИРОВАН, и честный `openDoor` не соврёт — но и не поможет, он скажет «не на этой вкладке» и
 * оставит человека делать переход руками.
 *
 * ПОРЯДОК ЗДЕСЬ НЕСУЩИЙ, а не косметика:
 *   1) закрыть модалку — иначе подсветка сработает ЗА ней, и жест выглядит как «кнопка ничего не
 *      сделала», хотя поле подсвечено под самым большим прямоугольником на экране;
 *   2) если поле уже на экране, довести до него и уйти — переключать вид ради поля, которое видно,
 *      значило бы менять человеку экран без причины;
 *   3) иначе переключить студию и подождать МОНТАЖА, а не кадра: React ставит блок асинхронно, и
 *      один `requestAnimationFrame` попадает в промежуток, где поля ещё нет. Поэтому опрос —
 *      ограниченный, и его исчерпание это НЕ молчание: человек всё равно узнаёт, где искать.
 */
export function openDoorAcrossKind(
  path: string,
  needKind: 'flat' | 'render' | 'threed',
  where: string,
  say: (m: string, t: 'error') => void,
  close?: () => void,
): void {
  close?.();
  if (revealField(path)) return;

  const sw = studioSwitchSolo();
  if (!sw || sw.kind === needKind) {
    say(`${where} — it is not on this tab`, 'error');
    return;
  }
  sw.go(needKind);

  // Потолок в кадрах, а не в миллисекундах: считать надо перерисовки, а не время — на медленной
  // машине таймер истечёт раньше, чем React смонтирует блок, и дверь соврёт про отсутствие поля.
  let left = 60;
  const tick = (): void => {
    if (revealField(path)) return;
    if (--left <= 0) {
      say(`${where} — it is not on this tab`, 'error');
      return;
    }
    requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}
