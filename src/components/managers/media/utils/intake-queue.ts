/**
 * ОЧЕРЕДЬ ПРИЁМКИ: ЧТО ПРОИСХОДИТ СО ВТОРЫМ ⌘V.
 *
 * До сих пор вторая вставка ЗАМЕЩАЛА первую (`useMediaIntake`: `setQueue(accepted.slice(…))`), да
 * и до замещения обычно не доходило — приёмка гасила приём, пока была открыта. То есть очередь
 * жила ровно один жест, и «вставил два скриншота подряд» означало «в слоте один».
 *
 * Здесь та одна развилка, из-за которой это можно поменять, не трогая ни одного вызывающего:
 * очередь ДОБАВЛЯЕТ, но не больше, чем у слота осталось мест.
 */

export type MergeResult = {
  /** Новая очередь. Если брать было нечего — ТОТ ЖЕ массив, что пришёл: лишняя перерисовка
   *  приёмки на пустой вставке сбросила бы вид, в котором человек сейчас работает. */
  queue: File[];
  /** Сколько из ПРИНЕСЁННОГО не влезло. Молчать про это нельзя: их принесли осознанно. */
  dropped: number;
};

export function mergeQueue(prev: File[], incoming: File[], limit?: number): MergeResult {
  if (!incoming.length) return { queue: prev, dropped: 0 };

  // СЛОТ НА ОДНУ КАРТИНКУ ЗАМЕЩАЕТ, А НЕ ОТКАЗЫВАЕТ. «Вставил не тот скриншот, вставил
  // правильный» — это то, ради чего человек жмёт ⌘V второй раз на одиночном слоте; отказ
  // заставлял бы сначала искать крестик у первого. Ровно то же делал сегодняшний `slice(0, 1)`,
  // только вход у него всегда был пустой очередью.
  if (limit === 1) return { queue: [incoming[0]], dropped: incoming.length - 1 };

  const room = limit == null ? incoming.length : Math.max(0, limit - prev.length);
  const taken = incoming.slice(0, room);
  return {
    queue: taken.length ? [...prev, ...taken] : prev,
    dropped: incoming.length - taken.length,
  };
}
