// Постраничная обвязка печатного документа: бегущий колонтитул и «стр. N / M».
//
// ЗАЧЕМ. Печатный комплект уезжает в цех стопкой листов, которую там разбирают руками. До этого
// модуля идентификация документа жила ОДНОЙ строкой в самом конце потока — то есть на последней
// странице. Лист, вынутый из середины, не отвечал ни на «чей это стиль», ни на «какая партия»,
// ни на «сколько всего страниц было».
//
// ЧЕМ. `@page` margin boxes: `string-set` кладёт строку документа в именованную строку CSS, а
// `@top-center`/`@bottom-right` печатают её и счётчики страниц на КАЖДОЙ странице. Это Chrome
// 131+; Safari margin boxes не умеет вовсе. Деградация тихая и безвредная — колонтитула просто
// нет, документ печатается как раньше, — поэтому политика «печатать из Chrome» написана словами
// на тулбаре, а не зашита проверкой браузера.
//
// ОГРАНИЧЕНИЯ, которые НЕ надо пытаться обойти:
//  1. Нумерация СКВОЗНАЯ по документу. Сброс counter(page) на каждой тетради в Chrome не
//     подтверждён; «стр. 1 / 4» на каждой тетради выглядело бы честнее, но проверить это можно
//     только на живом Chrome, а неподтверждённый сброс даёт молча неверные номера.
//  2. `@page` глобален на документ, и `<PageFurniture>` в документе должен быть РОВНО ОДИН.
//     Это выполнимо лишь потому, что печатные маршруты живут в механике A (см. sheet.tsx) —
//     один печатный документ на страницу.
//  3. Собственные колонтитулы браузера (галка «Headers and footers» в диалоге печати) рисуются
//     ПОВЕРХ и от нас не зависят. Оператор их снимает сам.
//
// Здесь же — единственное объявление `@page` (размер и поля). Раньше их объявляли обе печатные
// страницы в своих PRINT_CSS; два объявления @page в одном документе — это конфликт, который
// разрешается порядком подключения, а не смыслом.

const PAGE_CSS = `
@media print {
  @page {
    size: A4 portrait;
    margin: 14mm 12mm;

    @top-center {
      content: string(docline);
      font-size: 7pt;
      letter-spacing: 0.06em;
      text-transform: uppercase;
      color: #444;
    }
    @bottom-right {
      content: counter(page) " / " counter(pages);
      font-size: 7pt;
      color: #444;
    }
  }
}
.print-docline {
  position: absolute;
  left: -10000px;
  top: 0;
  width: 1px;
  height: 1px;
  overflow: hidden;
  string-set: docline content();
}
`;

// line — то, чем лист идентифицируется на столе: стиль, колорвей, партия, ревизия. Держать
// коротким: margin box не переносится, лишнее просто обрежется.
export function PageFurniture({ line }: { line: string }) {
  return (
    <>
      <style>{PAGE_CSS}</style>
      {/* Элемент обязан РЕНДЕРИТЬСЯ (не display:none), иначе string-set не сработает: строка
          берётся из содержимого живого элемента. Поэтому он уводится за край, а не прячется. */}
      <div className='print-docline' aria-hidden>
        {line}
      </div>
    </>
  );
}

// Строка колонтитула из частей: пустые и прочерки отбрасываются, разделитель один.
export function furnitureLine(...parts: Array<string | undefined | null>): string {
  return parts
    .map((p) => (p ?? '').trim())
    .filter((p) => p !== '' && p !== '—')
    .join(' · ');
}
