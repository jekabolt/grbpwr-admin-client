import type { UseFormSetValue } from 'react-hook-form';
import type { FittingFormData } from './schema';

// РАЗЖАЛОВАНИЕ УКАЗАНИЯ В НУМЕРОВАННУЮ ТОЧКУ — ОДНО ПРАВИЛО НА ВСЕ ПУТИ.
//
// Путей три, и все три означают одно и то же событие: «фигура больше не стоит там, где стояла».
//   · «сделать точкой» в редакторе — человек сам убирает неудачную геометрию;
//   · перепривязка к другому снимку — доли кадра осмысленны только на СВОЁМ кадре;
//   · снятие фотографии — кадра, в котором жили якоря, больше нет.
//
// Копий этого правила было три, и они уже разошлись, пока их писали: гасить пунктир и штриховку
// помнил только редактор. Расхождение стоит не данных (сервер приводит бессмысленные флаги сам), а
// доверия к форме: сохранённая примерка немедленно возвращается «изменённой», потому что форма
// помнит пунктир у точки, а хранимое — нет.
//
// НОМЕР И ЗАПИСКА НЕ ТРОГАЮТСЯ. Номер — единственная личность выноски, им на неё ссылается
// замечание; записку писал человек, и она переживает и картинку, и фигуру.
export function demoteCalloutToPin(
  setValue: UseFormSetValue<FittingFormData>,
  index: number,
): void {
  const opts = { shouldDirty: true } as const;
  setValue(`callouts.${index}.kind`, 'pin', opts);
  setValue(`callouts.${index}.points`, [], opts);
  // У точки нет ни линии, ни площади: пунктир и штриховка на ней не значат ничего.
  setValue(`callouts.${index}.dashed`, false, opts);
  setValue(`callouts.${index}.filled`, false, opts);
}

/** Есть ли у указания нарисованные якоря — то, что разжалование безвозвратно уничтожит. */
export function hasDrawnGeometry(c?: { kind?: string; points?: { x: string; y: string }[] }): boolean {
  return (c?.points?.length ?? 0) > 0;
}
