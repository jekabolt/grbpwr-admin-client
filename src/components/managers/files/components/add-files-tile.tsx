import { Tile, Tiles } from 'ui/components/tiles';

/**
 * ПЛИТКА-ПРИГЛАШЕНИЕ В ПРОЕКТЕ.
 *
 * Просьба владельца: внутри проекта первым блоком всегда стоит плейсхолдер, которым в проект
 * добавляют файл. Плитка, а не кнопка в шапке, — по тому же доводу, что и слот медиа: место, куда
 * кладут, обязано выглядеть как то, что там лежит, иначе пустой проект не показывает, чего ему
 * не хватает.
 *
 * СТОИТ ВСЕГДА, В ТОМ ЧИСЛЕ НА ПУСТОМ ПРОЕКТЕ. Пустое состояние страницы объясняет, почему тут
 * ничего нет; плитка отвечает на следующий вопрос — «и что делать». Поэтому она живёт СВОИМ
 * рядом над секциями, а не первой ячейкой внутри одной из них: секции пропадают вместе с
 * файлами, и приглашение исчезало бы ровно там, где оно нужнее всего.
 *
 * В РЕЖИМЕ ЧТЕНИЯ ЕЁ НЕТ ВОВСЕ: она не сообщает ничего о проекте (в отличие от выключенной
 * кнопки, которая говорит «так бывает»), а место в сетке занимает.
 */
export function AddFilesTile({ label, onClick }: { label: string; onClick: () => void }) {
  return (
    <Tiles min={190}>
      <Tile
        dashed
        name='+ add files'
        sub={label}
        title='pick files that are already in the library'
        onClick={onClick}
        media={
          <div className='flex aspect-square w-full items-center justify-center bg-bgSecondary text-2xl leading-none text-labelColor'>
            +
          </div>
        }
      />
    </Tiles>
  );
}
