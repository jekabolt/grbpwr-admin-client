import { adminService } from 'api/api';

/**
 * Словарь тем — свой модуль, отдельно от `filesService`.
 *
 * Экран управления темами живёт своей жизнью: он не листает файлы и не грузит их, а
 * `filesService` не переименовывает и не сливает. Один общий модуль означал бы, что оба
 * экрана правят один файл каждый раз, когда меняется любой из них.
 */
export const topicsService = {
  /**
   * ЭКРАН СЛОВАРЯ ПРОСИТ АРХИВ, ХОЛСТ — НЕТ, и это не настройка, а разные вопросы.
   *
   * Холст спрашивает «чем сузить сетку», и заархивированный проект там только мешает.
   * Словарь спрашивает «что у нас вообще заведено», и без архива он врёт: тема никуда не
   * делась, её просто убрали с глаз. Поэтому умолчание здесь ПРОТИВОПОЛОЖНО умолчанию
   * `filesService.listTopics` — и это осознанно, а не рассинхрон.
   */
  list: (includeArchived = true) => adminService.ListFileTopics({ includeArchived }),
  /** Имя И описание одним вызовом: описание — это то, что объясняет новичку, что сюда класть. */
  create: (name: string, description = '') => adminService.CreateFileTopic({ name, description }),
  /** Один диалог правит и имя, и описание — контракт принимает оба поля вместе. */
  rename: (id: number, name: string, description = '') =>
    adminService.RenameFileTopic({ id, name, description }),
  remove: (id: number) => adminService.DeleteFileTopic({ id }),
  /**
   * ВЕЩИ, ЧЬЯ КАРТОЧКА ПОКАЗЫВАЕТ НА ЭТОТ ПРОЕКТ.
   *
   * Нужен ровно затем, чтобы назвать число ДО необратимого нажатия: удаление темы и понижение
   * проекта уносят эти привязки каскадом, и «узнаете после» — плохой ответ там, где ответ есть
   * до. В `ListFileTopics` этого счёта нет (он считает файлы и только их), поэтому на каждой
   * строке таблицы словаря его дёшево не показать — а в модалке, открытой на одной теме, вполне.
   *
   * Право у него `files:read`, то есть заведомо есть у всякого, кто дошёл до кнопки удаления:
   * ей нужен `files:write`.
   */
  listStyles: (topicId: number) => adminService.ListFileTopicStyles({ topicId }),
  /**
   * Слияние — единственный выход из дублей свободного словаря («бирки» и «бирка»).
   * Удаление отказывает на непустой теме, а сливать надо ровно такую: связи переезжают на
   * цель, источник исчезает. Обратно не разбирается.
   */
  merge: (sourceId: number, targetId: number) =>
    adminService.MergeFileTopics({ sourceId, targetId }),
  /**
   * ТИП, ДАТЫ И АРХИВ — ОТДЕЛЬНЫМ СООБЩЕНИЕМ, а не полями к `rename`.
   *
   * Сообщение новое, и поэтому замена набора целиком здесь безопасна: другого клиента у него
   * нет, каждый зовущий шлёт всю форму. Допиши мы `kind` в `RenameFileTopic` — клиент, который
   * про поле не знает, слал бы его пустым и молча понижал проект до обычной темы на первом же
   * переименовании. Ровно так проект уже терял поля (черновик тех-карты стирал отсутствующие),
   * так что это не гипотеза.
   *
   * ПОНИЖЕНИЕ ПРОЕКТА ОБНУЛЯЕТ РОЛИ и возвращает их число в `clearedRoles`. Число обязано
   * дойти до человека: понижение, тихо снявшее сорок ярлыков, выглядит точно так же, как
   * понижение, не снявшее ни одного.
   */
  updateMeta: (a: {
    topicId: number;
    kind: 'plain' | 'project';
    startsAt: string;
    endsAt: string;
    archived: boolean;
  }) => adminService.UpdateFileTopicMeta(a),
  /**
   * СЛОВАРЬ РОЛЕЙ С АРХИВОМ — умолчание противоположно `filesService.listRoles`, ровно по тому
   * же доводу, что и у тем: холст спрашивает «чем сузить», словарь — «что вообще заведено».
   */
  // `projectTopicId: 0` — см. довод у `filesService.listRoles`.
  listRoles: (includeArchived = true) =>
    adminService.ListFileRoles({ includeArchived, projectTopicId: 0 }),
  /**
   * ЕДИНСТВЕННЫЙ путь, которым роль появляется на свет. Ни `newTopics` при загрузке, ни
   * приёмная модалка, ни групповая простановка тем роль завести не могут: они пишут в темы, а
   * роли живут не там. Словарь закрыт намеренно — «все исходники по всем съёмкам» значит
   * что-нибудь только пока «исходники» везде одно и то же.
   */
  upsertRole: (a: { id: number; name: string; sortOrder: number; archived: boolean }) =>
    // `projectTopicId: 0` на правке значит «владельца не трогать» — то же, что слал клиент до
    // регена. Заведение роли В ПРОЕКТЕ приезжает своей волной.
    adminService.UpsertFileRole({ ...a, projectTopicId: 0 }),
  /**
   * Слияние ролей — починка словаря, который всё-таки разъехался. Оно ПРОЩЕ слияния тем: роль
   * это колонка, а не связь, дедуплицировать нечего — ни одна строка не может нести обе.
   */
  mergeRoles: (sourceId: number, targetId: number) =>
    adminService.MergeFileRoles({ sourceId, targetId }),
};
