/**
 * Разбор отказа gRPC-шлюза для трёх секций карточки файла (задачи, обсуждение, доступ).
 *
 * Секции карточки — единственное место раздела, где клиент СТАРШЕ сервера: биндинги приезжают
 * с зеркальной ветки контракта раньше, чем соответствующий бэкенд встаёт на стенд. До выката
 * шлюз отвечает на неизвестный путь 404/501, и без этого различения человек читал бы «файл не
 * найден» под секцией, которая просто ещё не существует.
 *
 * `requestHandler` (`src/api/api.ts`) кладёт HTTP-код на ошибку полем `status` — по нему и
 * различаем «нельзя» (403), «сервер не знает такого запроса» (404/501/405) и всё остальное.
 */
export function errorStatus(e: unknown): number | undefined {
  if (!e || typeof e !== 'object') return undefined;
  const s = (e as { status?: unknown }).status;
  return typeof s === 'number' ? s : undefined;
}

/** Отказ по правам — секции показывают запрет словами, а не сообщением сервера. */
export function isForbidden(e: unknown): boolean {
  return errorStatus(e) === 403;
}

/**
 * Шлюз не знает этого запроса.
 *
 * 501 — честный ответ незнающего шлюза, 405 — путь есть, метода нет, 404 — и то и другое
 * сразу: на выкаченном бэкенде тот же 404 означает «файла нет». Разделить их клиент не может
 * и не притворяется, что может: формулировка секции называет ОБА исхода.
 */
export function isUnknownRoute(e: unknown): boolean {
  const s = errorStatus(e);
  return s === 404 || s === 405 || s === 501;
}

/** Слова сервера, если он их дал; иначе — переданный запасной текст. */
export function errorText(e: unknown, fallback: string): string {
  return e instanceof Error && e.message ? e.message : fallback;
}
