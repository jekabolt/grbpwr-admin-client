// Адрес публичной ссылки в двух написаниях, и различать их обязан кто угодно, кто её показывает.
//
// Бэкенд минтит ссылку как `{PublicBaseURL}/api/f/{token}` — это САМ МАРШРУТ: он отвечает 302 и
// отдаёт байты немедленно. Работает, но мимо страницы приземления: получатель не увидит ни имени,
// ни размера, а по мёртвой ссылке получит голый 404 браузера вместо фразы.
//
// Страница приземления живёт на админском домене по адресу `/f/{token}` (ROUTES.publicFile) и
// ведёт к тем же байтам через одну кнопку. Показывать людям надо ЕЁ, а маршрут оставить тем, кто
// тянет файл программно.
//
// Модуль ЧИСТЫЙ и без импортов — его одинаково законно позвать и из админского экрана, и из
// публичной страницы.

/** Токен из адреса маршрута. Пусто, если это не адрес публичной ссылки на файл. */
export function shareTokenOf(backendUrl?: string): string {
  const m = /\/api\/f\/([^/?#]+)/.exec((backendUrl ?? '').trim());
  return m ? m[1] : '';
}

/**
 * Адрес СТРАНИЦЫ приземления по адресу маршрута. Пусто, если токен не разобрался — а пустое
 * значит «показывать нечего»: строка-обманка, ведущая в никуда, хуже отсутствующей кнопки.
 *
 * `origin` параметром, а не жёстко `window.location.origin`, ровно затем, чтобы функция
 * оставалась чистой и проверяемой; по умолчанию — домен той вкладки, где её позвали.
 */
export function publicFilePageUrl(
  backendUrl?: string,
  origin: string = typeof window === 'undefined' ? '' : window.location.origin,
): string {
  const token = shareTokenOf(backendUrl);
  return token ? `${origin.replace(/\/$/, '')}/f/${token}` : '';
}
