// Адрес публичной ссылки в двух написаниях, и различать их обязан кто угодно, кто её показывает.
//
// Бэкенд минтит ссылку как `{PublicBaseURL}/api/f/{token}` — это САМ МАРШРУТ: он отвечает 302 и
// отдаёт байты немедленно. Работает, но мимо страницы приземления: получатель не увидит ни имени,
// ни размера, а по мёртвой ссылке получит голый 404 браузера вместо фразы.
//
// Страница приземления живёт на админском домене по адресу `/f/{token}` (ROUTES.publicFile) и
// ведёт к тем же байтам через одну кнопку. Показывать людям надо ЕЁ, а маршрут оставить тем, кто
// тянет файл программно.
//
// Модуль без единого импорта из `api/**` — его одинаково законно позвать и из админского
// экрана, и из публичной страницы. Единственная зависимость такая же чистая: `viewerOrigin`
// читает переменную сборки и `window.location`, и больше ничего.
import { viewerOrigin } from 'utils/viewer-origin';

/** Токен из адреса маршрута. Пусто, если это не адрес публичной ссылки на файл. */
export function shareTokenOf(backendUrl?: string): string {
  const m = /\/api\/f\/([^/?#]+)/.exec((backendUrl ?? '').trim());
  return m ? m[1] : '';
}

/**
 * ЗАВЕДОМО ЭФЕМЕРНЫЙ ХОСТ — тот, по которому не придёт никто, кроме сидящего за этой машиной.
 *
 * Список нарочно короткий и состоит только из того, что проверяется по самому имени, без
 * догадок: своя машина (в том числе по числам — LAN-адрес соседа по студии годится не лучше),
 * Bonjour-имя и превью-алиас Vercel, который живёт до переименования ветки и стоит за SSO.
 * Всё остальное — обычный домен, на который кто-то сознательно направил эту SPA, и адрес
 * вкладки на нём и есть адрес продукта.
 */
function ephemeralHost(host: string): boolean {
  const h = host.toLowerCase();
  if (h === 'localhost' || h.endsWith('.localhost') || h === '::1' || h === '[::1]') return true;
  if (/^\d{1,3}(\.\d{1,3}){3}$/.test(h)) return true;
  if (h.endsWith('.local')) return true;
  return h.endsWith('.vercel.app') || h.endsWith('.vercel.sh');
}

/**
 * ОТКУДА БЕРЁТСЯ ДОМЕН ПУБЛИЧНОЙ ССЫЛКИ — и почему вкладке верят не всегда.
 *
 * `window.location.origin` — это домен ТОЙ ВКЛАДКИ, где нажали «скопировать». Нажали на
 * превью Vercel или на локальной сборке — и подрядчику уедет адрес, который у него не
 * откроется, молча и не сразу: тост при этом честно говорит «скопировано», потому что
 * скопировалось действительно то, что показали. Репозиторий уже платил за это бумагой из цеха
 * и завёл `VITE_PATTERN_VIEWER_ORIGIN`; та же переменная годится и здесь, потому что все
 * публичные страницы (`/p/`, `/r/`, `/f/`) живут на одном хосте — это одна SPA.
 *
 * `VITE_FILE_SHARE_ORIGIN` стоит ПЕРЕД ней и только как отступление: в спеку деплоя ничего
 * дописывать не нужно, а если публичную страницу файла когда-нибудь вынесут на отдельный
 * домен (условный files.grbpwr.com), её не придётся отцеплять от вьюеров правкой кода.
 *
 * ПУСТО — ЗНАЧИТ ПОКАЗЫВАТЬ НЕЧЕГО, и это третья ветка, а не ошибка. Переменных нет, а вкладка
 * стоит на заведомо эфемерном хосте — собрать адрес не из чего, и оба зовущих (блок доступа
 * карточки файла и витрина открытого) прячут и поле, и кнопку, потому что оба уже проверяют
 * результат на пустоту. Показать localhost с кнопкой «скопировать» хуже, чем не показать
 * ничего: пустое место человек заметит, а мёртвый адрес — нет.
 *
 * А ВОТ СТАБИЛЬНЫЙ ХОСТ БЕЗ ПЕРЕМЕННОЙ ОСТАЁТСЯ РАБОЧИМ, и это тоже решение: на
 * admin.grbpwr.com адрес вкладки И ЕСТЬ адрес продукта, страница `/f/{token}` — часть этой же
 * SPA. Глушить его за незаполненную переменную значило бы выключить кнопку на контуре, где она
 * работает правильно, — и выключить молча, потому что фразу «домен не настроен» пришлось бы
 * писать в двух чужих экранах сразу. Переменную всё равно надо выставлять на каждом контуре
 * (`.env.example`, `CLAUDE.md`): она страхует от нового эфемерного хоста, о котором здешний
 * список ещё не знает.
 */
export function fileShareOrigin(): string {
  const configured = (import.meta.env.VITE_FILE_SHARE_ORIGIN as string | undefined)?.trim();
  if (configured) return configured.replace(/\/$/, '');
  if (typeof window === 'undefined') return '';
  // Переменная вьюеров читается через своего владельца, а не вторым разбором: `viewerOrigin`
  // отвечает за срез хвостового слэша и за то, что имя переменной живёт в одном месте.
  if ((import.meta.env.VITE_PATTERN_VIEWER_ORIGIN as string | undefined)?.trim()) {
    return viewerOrigin();
  }
  return ephemeralHost(window.location.hostname) ? '' : window.location.origin;
}

/**
 * Адрес СТРАНИЦЫ приземления по адресу маршрута. Пусто, если токен не разобрался ИЛИ если
 * домен не из чего собрать, — а пустое значит «показывать нечего»: строка-обманка, ведущая в
 * никуда, хуже отсутствующей кнопки.
 *
 * Пустой `origin` НЕ склеивается в «/f/{token}»: относительный путь непуст, то есть прошёл бы
 * все проверки зовущих и уехал бы в буфер обмена куском адреса, который у получателя
 * достроится от ЕГО вкладки. Это ровно та молчаливая мёртвая ссылка, ради которой всё и
 * считается.
 *
 * `origin` параметром, а не жёстко внутри, ровно затем, чтобы функция оставалась чистой и
 * проверяемой; по умолчанию — настроенный домен контура, а не домен текущей вкладки.
 */
export function publicFilePageUrl(backendUrl?: string, origin: string = fileShareOrigin()): string {
  const base = origin.trim().replace(/\/$/, '');
  const token = shareTokenOf(backendUrl);
  return base && token ? `${base}/f/${token}` : '';
}
