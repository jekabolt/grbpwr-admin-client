import type { ReactNode } from 'react';

/**
 * ГОЛЫЙ АДРЕС В ТЕКСТЕ — ЭТО ССЫЛКА.
 *
 * Адрес вставляют скопированным из строки браузера, а не оформляют `[текст](адрес)`: так пишут
 * и описание задачи, и заметку, и комментарий. Нарисованный простым текстом, он заставлял
 * выделять его и копировать обратно в строку браузера — то есть ссылкой не был.
 *
 * Два места читают адреса (разметчик `doc.tsx` и простой текст задачи `task-text.tsx`), и оба
 * рисуют их ЭТОЙ функцией: иначе один и тот же адрес был бы ссылкой в описании и текстом в
 * комментарии.
 *
 * ТОЛЬКО `http://` и `https://` (в любом регистре). Любая другая схема (`javascript:`, `data:`) —
 * исполняемая или подменяющая страницу ссылка, которую может написать любой, кто пишет текст.
 *
 * Две формы: голая `https://…` и в угловых скобках `<https://…>` — вторую ставят, чтобы отделить
 * адрес от соседней пунктуации, и сами скобки к адресу не относятся.
 *
 * РАЗМЕТЧИКУ ОТДАЁТСЯ ТОЛЬКО ПРОСТОЙ ТЕКСТ МЕЖДУ ЕГО ТОКЕНАМИ. Символы разметки (`!`, `[`, `*`)
 * законны внутри адреса, и адрес, искомый наравне с токенами, проглатывал бы следующую за ним
 * конструкцию целиком: `https://x.com/![снимок](…)` становился одной длинной ссылкой вместо
 * ссылки и картинки.
 */
const AUTOLINK_SOURCE = String.raw`<https?:\/\/[^\s<>]+>|https?:\/\/[^\s<>]+`;

/**
 * КОНЕЦ ФРАЗЫ — НЕ ЧАСТЬ АДРЕСА. «см. https://x.com/a.» — точка закрывает предложение, и ссылка
 * на `a.` вела бы на другую страницу. Закрывающие кавычки-ёлочки, лапки и многоточие —
 * туда же: «https://x.com/a» в русском тексте пишут именно так.
 *
 * `*`, `_` и `~` НЕ ОТРЕЗАЮТСЯ, хотя GFM их режет: там они разметка, а здесь `_` и `~` разметкой
 * не являются вовсе, `*` разметчик отделяет своими токенами ДО автоссылок, а текст комментария
 * разметки не знает. Зато `?q=sku:GRB*` — обычный поисковый адрес, и звёздочка — его часть.
 */
const TRAILING = /[.,:;!?'"»”’…]/;

export interface Autolink {
  href: string;
  /**
   * Сколько символов найденного куска заняла ссылка. Остаток (отрезанная пунктуация)
   * возвращается в текст.
   */
  length: number;
}

/**
 * Разбирает кусок, найденный по `AUTOLINK_SOURCE`. `null` — адреса в нём нет (например,
 * `https://.` после отрезания точки), и кусок остаётся текстом.
 *
 * Закрывающая скобка на конце отрезается, только если она НЕПАРНАЯ: «(https://x.com/a)» —
 * скобка фразы, у `…/wiki/Foo_(bar)` — своя. Баланс считается ОДИН раз и дальше только
 * уменьшается: пересчёт на каждом отрезанном символе делал разбор квадратичным, и строка из
 * десятков тысяч `)` вешала бы вкладку — в том числе публичную страницу присланной заметки.
 */
export function readAutolink(token: string): Autolink | null {
  const angled = token.startsWith('<');
  let href = angled ? token.slice(1, -1) : token;

  if (!angled) {
    let parens = 0;
    let brackets = 0;
    for (const c of href) {
      if (c === ')') parens += 1;
      else if (c === '(') parens -= 1;
      else if (c === ']') brackets += 1;
      else if (c === '[') brackets -= 1;
    }
    let end = href.length;
    while (end > 0) {
      const ch = href[end - 1];
      if (TRAILING.test(ch)) end -= 1;
      else if (ch === ')' && parens > 0) {
        parens -= 1;
        end -= 1;
      } else if (ch === ']' && brackets > 0) {
        brackets -= 1;
        end -= 1;
      } else break;
    }
    href = href.slice(0, end);
  }

  // Без хоста это не адрес, а начало фразы про протокол.
  try {
    if (!new URL(href).hostname) return null;
  } catch {
    return null;
  }
  return { href, length: angled ? token.length : href.length };
}

/**
 * Простой текст → текст и ссылки в новую вкладку. Элементы собираются react-узлами, поэтому
 * текст остаётся текстом по построению.
 *
 * ГОЛЫЙ АДРЕС — ВСЕГДА ССЫЛКА, А НЕ СНИМОК, даже если оканчивается на `.jpg`. Правило «адрес
 * картинки становится картинкой» (`isPictureHref` в `doc.tsx`) касается оформленной ссылки
 * `[текст](адрес)`: у неё есть подпись. Голый адрес вставляют, чтобы по нему ПЕРЕЙТИ, и кадр на
 * его месте спрятал бы сам адрес.
 *
 * Длинный адрес без пробелов не имеет точки переноса и распирал бы колонку — отсюда `anywhere`.
 */
export function autolinkNodes(text: string, keyPrefix: string): ReactNode[] {
  // Свой экземпляр на вызов: у `g`-регулярки есть `lastIndex`, и общий экземпляр отдавал бы
  // разный результат в зависимости от того, кто разбирал текст до этого вызова.
  const re = new RegExp(AUTOLINK_SOURCE, 'gi');
  const out: ReactNode[] = [];
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    const link = readAutolink(m[0]);
    if (!link) continue;
    if (m.index > last) out.push(text.slice(last, m.index));
    out.push(
      <a
        key={`${keyPrefix}-a${m.index}`}
        href={link.href}
        target='_blank'
        rel='noreferrer noopener'
        className='text-highlightColor underline [overflow-wrap:anywhere]'
      >
        {link.href}
      </a>,
    );
    last = m.index + link.length;
    // Отрезанная пунктуация («…/a.») остаётся текстом и в следующий адрес не попадает.
    re.lastIndex = last;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}
