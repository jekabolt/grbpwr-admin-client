// Таблицы вьюера наряда — это ui/DataTable variant='grid' плюс две поправки на цех.
//
// Грамматику таблиц (10px серые заголовки, hairline между строками, tabular-nums, зебра первой
// колонки, горизонтальная обёртка) держит примитив; переписывать её здесь значило бы завести вторую
// таблицу этого админа, которая расходится с первой ровно на те два грея, про которые в DESIGN.md
// написано, что перепутать их — самый заметный способ промахнуться мимо системы.
//
// ПОПРАВКА 1: min-w-max. У DataTable ширина 100%, и матрица на восемь размеров ужалась бы в экран
// телефона переносами вместо того, чтобы прокручиваться. min-w-max превращает сжатие в скролл —
// ЕЗДИТ ТАБЛИЦА, А НЕ СТРАНИЦА: уедь страница, у шапки и у плашки «план изменился» уехал бы левый
// край, то есть единственное, что цех обязан прочитать первым.
//
// ПОПРАВКА 2: липкая первая колонка. Проскроллив до размера L, надо всё ещё видеть, ЧЬЯ это строка.
// Липкая клетка обязана быть непрозрачной — в grid-варианте первая колонка уже залита зеброй, и
// именно поэтому липкость вешается на него, а не на обычный список.
// ПОПРАВКА 3: размер ячейки. `DataTable` называет свой (12px админа) сам, поэтому 16px, которые
// вьюер ставит на страницу целиком (см. Shell в page.tsx: цех, телефон, зум запрещён), до ячеек
// НЕ доходят — а цифры кроя и есть то, ради чего эту страницу открывают.
export const RUNPACK_GRID = [
  'min-w-max',
  '[&_td]:text-base',
  '[&_th:first-child]:sticky [&_th:first-child]:left-0 [&_th:first-child]:z-20',
  '[&_td:first-child]:sticky [&_td:first-child]:left-0 [&_td:first-child]:z-10',
].join(' ');

// Потолок ширины описательной клетки. min-w-max выше меряет таблицу по max-content, а max-content
// текстовой клетки — это ВСЯ строка без переносов: одно длинное имя артикула («сукно шерстяное
// двухслойное 340 г/м², поставщик …») растянуло бы таблицу на экран в ширину и утащило бы за собой
// все размерные колонки. Потолок возвращает клетке право переноситься, не отменяя скролла у
// числовых колонок, ради которых он и заведён.
export const DESC_CELL = 'max-w-[45vw] whitespace-normal lg:max-w-[22rem]';
