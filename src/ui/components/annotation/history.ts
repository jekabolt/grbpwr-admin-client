import { useCallback, useRef } from 'react';

// ОТКАТ ШАГА ПРАВКИ (⌘Z / Ctrl+Z).
//
// Указание ставится и правится ЖЕСТОМ: клик, перетаскивание, росчерк. У жеста нет «отмены» так же,
// как у него нет подтверждения, — промахнулся ручкой на три пикселя, и вернуть мерку на место
// можно только на глаз. Именно это и делает откат здесь обязательным, а не приятным: единственный
// способ вернуть точное прежнее положение — помнить его.
//
// ГРАНИЦА НАМЕРЕННАЯ: история помнит ЖЕСТЫ НАД ФИГУРАМИ — постановку, перенос точки, перетаскивание
// подписи, удаление. Правку ТЕКСТА она не трогает: текст живёт в обычном поле ввода, и там ⌘Z
// принадлежит браузеру. Перехватить его значило бы отменять целое указание вместо буквы, которую
// человек только что напечатал, — и это ровно тот случай, когда «умный» откат хуже никакого.
//
// СНИМКИ ПО ЗАПРОСУ, А НЕ ПО СРАВНЕНИЮ. Список приезжает из `useWatch` новой ссылкой на каждый
// рендер, поэтому «запоминать, когда изменилось» здесь означало бы сравнивать содержимое на каждом
// рендере — то есть сериализовать сотни точек следа маркера ради того, чтобы почти всегда узнать
// «не изменилось». Поверхность вместо этого ЗОВЁТ `record()` ровно перед тем, как что-то менять.

/** Сколько шагов помним. Глубже никто не отматывает, а список указаний может быть тяжёлым. */
const LIMIT = 40;

export type EditHistory<T> = {
  /** Запомнить текущее состояние. Зовётся ПЕРЕД мутацией, а не после. */
  record: () => void;
  /** Вернуть последнее запомненное. Ничего не делает, если история пуста. */
  undo: () => void;
  canUndo: () => boolean;
  /** Забыть всё — при смене того, что вообще правится (другой снимок, другая карточка). */
  reset: () => void;
};

/**
 * `current` читается через ref: `record()` зовут из обработчика события, который живёт дольше
 * рендера, и замыкание отдало бы список, каким он был при подписке.
 */
export function useEditHistory<T>(current: T[], apply: (next: T[]) => void): EditHistory<T> {
  const live = useRef({ current, apply });
  live.current = { current, apply };
  const past = useRef<T[][]>([]);

  const record = useCallback(() => {
    // Копия ВЕРХНЕГО уровня достаточна: владельцы пишут строки заменой (`{...a, ...fields}`), а не
    // правкой на месте, поэтому вложенное состояние прошлых снимков не разделяется с текущим.
    past.current.push(live.current.current.slice());
    if (past.current.length > LIMIT) past.current.shift();
  }, []);

  const undo = useCallback(() => {
    const prev = past.current.pop();
    if (!prev) return;
    live.current.apply(prev);
  }, []);

  const canUndo = useCallback(() => past.current.length > 0, []);
  const reset = useCallback(() => {
    past.current = [];
  }, []);

  return { record, undo, canUndo, reset };
}
