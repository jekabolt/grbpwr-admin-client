export type AnsurUntypedFieldEstimatePredictorV1 =
  (typeof ANSUR_UNTYPED_FIELD_ESTIMATE_PREDICTORS_V1)[number];
export type AnsurUntypedFieldEstimateKeyV1 = (typeof ANSUR_UNTYPED_FIELD_ESTIMATE_KEYS_V1)[number];
export type AnsurUntypedFieldEstimateGroupV1 = 'female' | 'male' | 'pooled';

export interface AnsurUntypedFieldRelationV1 {
  /** ANSUR II column the line predicts (lower-cased public-release header). */
  readonly ansurColumn: string;
  readonly interceptMm: number;
  readonly coefficients: Readonly<Record<AnsurUntypedFieldEstimatePredictorV1, number>>;
  /** 0.5 % and 99.5 % of the column on the training half; guesses are clamped into it. */
  readonly rangeMm: readonly [minimum: number, maximum: number];
  /** Prediction minus person on the holdout half (mm). */
  readonly holdout: Readonly<{ n: number; biasMm: number; medianAbsMm: number; p90AbsMm: number }>;
}

function relation(
  ansurColumn: string,
  interceptMm: number,
  [heightMm, chestCircumferenceMm, hipCircumferenceMm, shoulderBreadthMm]: readonly [
    number,
    number,
    number,
    number,
  ],
  rangeMm: readonly [number, number],
  [n, biasMm, medianAbsMm, p90AbsMm]: readonly [number, number, number, number],
): AnsurUntypedFieldRelationV1 {
  return Object.freeze({
    ansurColumn,
    interceptMm,
    coefficients: Object.freeze({
      heightMm,
      chestCircumferenceMm,
      hipCircumferenceMm,
      shoulderBreadthMm,
    }),
    rangeMm: Object.freeze([rangeMm[0], rangeMm[1]] as const),
    holdout: Object.freeze({ n, biasMm, medianAbsMm, p90AbsMm }),
  });
}

