/** Female and male bases use their own sex's lines; the neutral (and raw) base uses the pooled fit. */
export function ansurUntypedFieldEstimateGroupV1(
  basisKind: MakeHumanOpenReferenceBasisKindV1,
): AnsurUntypedFieldEstimateGroupV1 {
  if (basisKind === 'female') return 'female';
  if (basisKind === 'male') return 'male';
  return 'pooled';
}

export interface AnsurUntypedFieldEstimatesV1 {
  readonly version: typeof ANSUR_UNTYPED_FIELD_ESTIMATES_V1;
  readonly group: AnsurUntypedFieldEstimateGroupV1;
  /** Only fields the user left empty; empty when a predictor is missing or implausible. */
  readonly estimates: Readonly<Partial<Record<AnsurUntypedFieldEstimateKeyV1, number>>>;
  /** Guesses that hit the training range and were clamped into it. */
  readonly clamped: readonly AnsurUntypedFieldEstimateKeyV1[];
  readonly skippedReason?: 'predictor-missing-or-implausible';
}

/**
 * Fills each ANSUR-estimable field the user left empty. Typed values are never touched. Returns no
 * guesses when any predictor is missing or outside the form's plausibility interval.
 */
export function estimateUntypedMeasurementsFromAnsurV1(options: {
  readonly basisKind: MakeHumanOpenReferenceBasisKindV1;
  readonly measurements: CanonicalBodyMeasurementsMm;
  readonly keys?: readonly AnsurUntypedFieldEstimateKeyV1[];
}): AnsurUntypedFieldEstimatesV1 {
  const group = ansurUntypedFieldEstimateGroupV1(options.basisKind);
  for (const predictor of ANSUR_UNTYPED_FIELD_ESTIMATE_PREDICTORS_V1) {
    const value = options.measurements[predictor];
    const [minimum, maximum] = CANONICAL_MEASUREMENT_PLAUSIBILITY_MM[predictor];
    if (!Number.isFinite(value) || value < minimum || value > maximum) {
      return Object.freeze({
        version: ANSUR_UNTYPED_FIELD_ESTIMATES_V1,
        group,
        estimates: Object.freeze({}),
        clamped: Object.freeze([]),
        skippedReason: 'predictor-missing-or-implausible' as const,
      });
    }
  }
  const estimates: Partial<Record<AnsurUntypedFieldEstimateKeyV1, number>> = {};
  const clamped: AnsurUntypedFieldEstimateKeyV1[] = [];
  for (const key of options.keys ?? ANSUR_UNTYPED_FIELD_ESTIMATE_KEYS_V1) {
    if (options.measurements[key] != null) continue;
    const line = ANSUR_UNTYPED_FIELD_RELATIONS_V1[group][key];
    let valueMm = line.interceptMm;
    for (const predictor of ANSUR_UNTYPED_FIELD_ESTIMATE_PREDICTORS_V1) {
      valueMm += line.coefficients[predictor] * options.measurements[predictor];
    }
    const [minimum, maximum] = line.rangeMm;
    if (valueMm < minimum || valueMm > maximum) clamped.push(key);
    estimates[key] = Math.round(Math.min(maximum, Math.max(minimum, valueMm)) * 10) / 10;
  }
  return Object.freeze({
    version: ANSUR_UNTYPED_FIELD_ESTIMATES_V1,
    group,
    estimates: Object.freeze(estimates),
    clamped: Object.freeze(clamped),
  });
}
