/**
 * Guesses for body fields the user did not type, from the fields they did type.
 *
 * Without a guess an untyped field keeps the MakeHuman base proportion at the typed height, which
 * runs small on real people (ANSUR II study, 17.11: neck about -35 mm, wrist -30 mm, thigh -8..-12
 * cm, chest depth -2 cm with chest breadth +2..+5 cm). These relations replace that default with
 * one ordinary least-squares line per field and sex.
 *
 * Source: Gordon CC, Blackwell CL, Bradtmiller B, et al. "2012 Anthropometric Survey of U.S. Army
 * Personnel: Methods and Summary Statistics", Technical Report NATICK/TR-15/007, U.S. Army Natick
 * Soldier RD&E Center, 2014 (ANSUR II public release: 1986 women, 4082 men, all lengths in mm).
 *
 * Fit (`scripts/anthropometry/ansur-fit.mjs`): per sex, subjects sorted by subjectid and shuffled
 * with seed 20261117; the first half trains, the second half is the holdout. `holdout` below is
 * prediction minus person on that untouched half. `pooled` (the neutral base) uses both sexes
 * with each sex carrying half the weight, so it carries a sex bias by construction (for example
 * neck +5.9 mm on women, -5.0 mm on men).
 *
 * Definitions, and what was NOT converted:
 * - Predictors are only typed fields whose ANSUR definition matches the form: stature (height),
 *   chest circumference (at the chest point), buttock circumference (hip), biacromial breadth
 *   (across shoulder; ANSUR measures it sitting, used as is).
 * - Waist is never a predictor: ANSUR waist is at the navel, ours at the natural waist, and ANSUR
 *   has no natural-waist girth. Waist depth is not guessed for the same reason.
 * - Biceps is not guessed: ANSUR biceps is flexed, ours relaxed. Knee, under bust and high hip have
 *   no ANSUR field and are not guessed.
 * - Neck: ANSUR neck circumference is taken just below the Adam's apple; the engine solves its own
 *   mid-neck plane. Used as is (approximate landmark), no conversion.
 * - Thigh (gluteal furrow), calf (maximum), wrist (styloid) and ankle (minimum) are ANSUR landmarks;
 *   the engine's limb stations are a geometric rule. Used as is (approximate landmark).
 *
 * A guess is a visual default only. It is clamped to the 0.5-99.5 % range of the training half,
 * never shown as a typed value, and the beta shape runtime drops all guesses whenever they would
 * cost a typed field. No garment fit, clinical accuracy or population representativeness is
 * claimed: ANSUR is a survey of soldiers (17-58, leaner than the general public).
 */
export const ANSUR_UNTYPED_FIELD_ESTIMATES_V1 = 'ansur-untyped-field-estimates/v1' as const;

