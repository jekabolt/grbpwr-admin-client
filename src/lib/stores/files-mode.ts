/**
 * Режим раздела файлов: писать или только читать.
 *
 * ТУМБЛЕР ВЫШЕ ЛЮБОГО ЭКРАНА, потому что писатели раздела — тоже. Пока он жил в состоянии
 * холста, полоса загрузки — мебель ВСЕГО раздела, живущая в сторе и переживающая уход на
 * другой экран, — на экране тем получала `writable` уже без него: человек поставил «чтение»,
 * ушёл разбирать темы, и там снова оказался писателем. Тумблер, который молча перестаёт
 * действовать, хуже отсутствующего.
 *
 * ПРАВО И ТУМБЛЕР — РАЗНЫЕ ВЕЩИ, и здесь лежит только тумблер. Право (`files:write`) читается
 * из `usePermissions` на каждом экране: без него режим принудительно «чтение», и хранить это
 * в сторе значило бы держать вторую копию ответа, который и так есть. Отсюда `filesWritable`:
 * одно место, где право и тумблер сходятся, — чтобы «оба положения глушат один и тот же набор
 * контролов» оставалось правдой на всех экранах сразу.
 *
 * Состояние модульное, как у очереди: переживает переходы внутри вкладки и не переживает
 * перезагрузку — добровольный режим чтения защищает от собственной руки в текущем сеансе, а
 * не от прав, и запоминать его на будущее не за чем.
 */
import { create } from 'zustand';

export type FilesMode = 'write' | 'read';

interface FilesModeStore {
  mode: FilesMode;
  setMode: (mode: FilesMode) => void;
}

export const useFilesModeStore = create<FilesModeStore>((set) => ({
  mode: 'write',
  setMode: (mode) => set({ mode }),
}));

/** Тумблер сам по себе: экрану он нужен, чтобы нарисовать положение и объяснить отказ. */
export function useFilesMode(): FilesMode {
  return useFilesModeStore((s) => s.mode);
}

/**
 * Можно ли сейчас писать: право И тумблер. Право экран передаёт сам — оно приходит из
 * `usePermissions`, а стор про react-query ничего не знает.
 */
export function useFilesWritable(mayWrite: boolean): boolean {
  return useFilesModeStore((s) => mayWrite && s.mode === 'write');
}
