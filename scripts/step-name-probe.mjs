// Карта примерки и редактор искали подпись класса КАЖДЫЙ СВОИМ `seamClassOptions.find(...)` с
// собственной проверкой UNKNOWN. Текстом они пока не расходились — карта подписей у обоих одна, —
// но два поиска по одному массиву это две редакции одного правила, и первая же ступень, дописанная
// в одну из них, стала бы третьим прочтением одного поля. Цитата стоит НА СВЕРКЕ, а не на тексте:
// именно расхождение и надо запретить.
head('П. класс шва назван ОДНИМ ярлыком на обеих поверхностях');
await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '12' });
const clsMap = (await mapSpec(0))?.[0]?.split(' · ')[0];
await openStep(0);
const clsEditor = (await editorSeam()).split(' · ')[0];
ck(clsMap === 'SS — plain seam', 'карта примерки называет класс его подписью', String(clsMap));
ck(clsEditor === 'SS — plain seam', 'редактор — той же', String(clsEditor));
ck(clsMap === clsEditor, 'и это ОДНА подпись, а не две совпавшие', `${clsMap} / ${clsEditor}`);

// ── РАЗВИЛКА ФОЛБЭКА: ОДИН ТОКЕН, ДВА РАЗНЫХ ОТВЕТА — И ЭТО НАМЕРЕННО ───────────────────────────
//
// ПОДПИСИ У ЖИВЫХ ЭКРАНОВ И У АРХИВА ОДНИ (`SEAM_CLASS_LABELS`), А ФОЛБЭКИ РАЗНЫЕ, и разойтись им
// приказано. Живому экрану сырой `TECH_CARD_SEAM_CLASS_…` хуже пустоты: пустота ВИДИМО неполна, а
// токен ВЫГЛЯДИТ ответом, и технолог читает его как назначение. Архиву правило обратное и сильнее:
// строка подписана, и потерять её нельзя даже ценой некрасивого токена.
//
// БЕЗ ЭТОЙ ЦИТАТЫ РАЗНИЦА ЧИТАЕТСЯ КАК НЕДОСМОТР. Две почти одинаковые функции с одним именем в
// двух файлах — первое, что следующий ревьюер захочет свести, и свести их можно в ЛЮБУЮ сторону:
// в одну — на живой экран выезжает токен, в другую — из подписанного документа пропадает строка.
// Обе стороны закрыты мутациями (`--mutate-liveclass`, `--mutate-releaseclass`) — по одной на
// каждое направление «починки», иначе половина развилки осталась бы без сторожа.
//
// ЧИТАЕТСЯ СТЕНД БЕЗ СТУПЕНЕЙ ПРИПУСКА: ни карточного стандарта, ни цехового. Тогда строка
// спецификации состоит ровно из класса шва и якоря-лапки, и «класс промолчал» нельзя спутать с
// «его заслонил припуск».
head('П (продолжение). незнакомый класс: живые экраны молчат, ПОДПИСАННЫЙ документ печатает токен');
pageErrors.length = 0;
shopAllowance = '';
await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '' });
ck(pageErrors.length === 0, 'стенд развилки смонтировался без исключений', pageErrors[0] ?? '');

// ТОЧНЫМ РАВЕНСТВОМ С ЯКОРЕМ: узел обязан состоять РОВНО из лапки. Так одно чтение отвечает сразу
// на два вопроса — класс шва не сказал ничего И строка при этом не исчезла.
const clsUnknownMap = await mapSpec(4);
ck(
  clsUnknownMap?.[0] === FOOT,
  'КЛАСС НЕ НАЗВАН — карта примерки молчит, а строка спецификации цела',
  String(clsUnknownMap?.[0]),
);
const clsGoneMap = await mapSpec(5);
ck(
  clsGoneMap?.[0] === FOOT,
  'токен, УШЕДШИЙ ИЗ КОНТРАКТА, на живом экране тоже молчит — сырого токена там нет',
  String(clsGoneMap?.[0]),
);
await openStep(5);
const clsGoneEditor = await editorSeam();
ck(
  !clsGoneEditor.includes('TECH_CARD_'),
  'и редактор его не печатает: у живых поверхностей ОДИН ярлык, значит и одно молчание',
  clsGoneEditor,
);

// ...А ПОДПИСАННЫЙ ДОКУМЕНТ ПЕЧАТАЕТ ЕГО ТОКЕНОМ. Экран настоящий, снимок приезжает по сети.
await mountReleases(11);
const goneRow = await releaseRow('default seam class');
ck(
  goneRow === GONE_CLASS,
  'АРХИВ РЕЛИЗОВ печатает тот же токен ТОКЕНОМ: подписанная строка не имеет права пропасть',
  goneRow,
);
// СВЕРКА — ГЛАВНАЯ ЦИТАТА СЕКЦИИ, а не сумма двух предыдущих: она утверждает, что ответы РАЗНЫЕ, и
// тем запрещает свести их в любую из двух сторон. Порознь обе половины зеленели бы и в мире, где
// развилки нет вовсе.
ck(
  goneRow !== String(clsGoneMap?.[0]) && goneRow === GONE_CLASS && clsGoneMap?.[0] === FOOT,
  'ОДИН токен — ДВА разных ответа, и разными они сделаны НАМЕРЕННО',
  `архив: ${goneRow} / живой экран: ${clsGoneMap?.[0]}`,
);
// И ГРАНИЦА РАЗВИЛКИ: расходятся они РОВНО на незнакомом токене. «Не назван» архив печатает так же,
// как живой экран, — пустотой; иначе «архив всё показывает сырьём» было бы столь же согласно с
// цитатой выше, а это уже другое правило.
await mountReleases(12);
const unknownRow = await releaseRow('default seam class');
ck(
  unknownRow === '(строки нет)',
  'а НЕ НАЗВАННЫЙ класс архив тоже не печатает: расходится ровно фолбэк незнакомого токена',
  unknownRow,
);

// ── ПЕРЕПИСЬ ПЕЧАТНОГО ЛИСТА ────────────────────────────────────────────────────────────────────
//
// ЧТО ОБЩЕГО У ПЯТИ ЦИТАТ НИЖЕ. Все они об одном классе дефекта: лист держал СВОЮ редакцию чтения,
// которое экраны берут у общего составителя. Ни одна из копий не врала числом — они расходились
// СЛОВОМ, и потому ни одна не была видна иначе как сверкой бумаги с экраном той же карточки.
head('С. зона и класс шва на листе — ТЕ ЖЕ ярлыки, что в заголовке и на карте примерки');
pageErrors.length = 0;
shopAllowance = '';
await mount(SHEET_STEPS, SHEET_CARD);
ck(pageErrors.length === 0, 'стенд переписи смонтировался без исключений', pageErrors[0] ?? '');
const shRail = [];
for (let i = 0; i < SHEET_STEPS.length; i++) shRail.push(await railTitle(i));
await sheetNames(SHEET_STEPS.length);
// ЧИТАЕМ СТРОКИ ЛИСТА ПО ИНДЕКСУ, А НЕ ПО ПОРЯДКУ В DOM. Лист ГРУППИРУЕТ шаги (узлами, а без
// разметки — зонами), и шаг БЕЗ зоны уходит последней группой: на этом стенде такой есть, и
// порядок в документе перестал совпадать с порядком в форме. `sheetNames` возвращает DOM-порядок и
// для прежних стендов верен — там зона у всех одна, — а здесь сравнение поехало бы на один шаг.
const shSheet = [];
for (let i = 0; i < SHEET_STEPS.length; i++) shSheet.push(await sheetName(i));
const zoneCell = await sheetCell(0, 'zone');
ck(zoneCell === 'front', 'колонка «zone» называет зону подписью словаря', String(zoneCell));
// СВЕРКА, А НЕ КОНСТАНТА: хвост заголовка шага — это тот же ярлык зоны, и обе поверхности обязаны
// брать его в одном месте. Равенство с литералом зеленело бы и в мире, где они совпали случайно.
ck(
  shRail[0].endsWith(` · ${zoneCell}`),
  'и это ТО ЖЕ слово, которым зону называет заголовок шага',
  `${shRail[0]} / ${zoneCell}`,
);
const seamCell = await sheetCell(0, 'seam');
const mapClass = (await mapSpec(0))?.[0]?.split(' · ')[0];
ck(
  String(seamCell).startsWith('SS — plain seam'),
  'колонка «seam» называет класс подписью словаря',
  String(seamCell),
);
ck(
  String(seamCell).startsWith(String(mapClass)),
  'и это ТА ЖЕ подпись, что на карте примерки',
  `${seamCell} / ${mapClass}`,
);

// ── ИМЯ ШАГА, У КОТОРОГО СВОЕГО СЛОВА НЕТ ───────────────────────────────────────────────────────
//
// ДВЕ ДЫРЫ ОДНОЙ ВЕТКИ, и вторая дороже первой. У дублирования слово ЕСТЬ, просто лист брал его из
// чужого словаря (список процессов ПРЕССА, который отвечает «для какого процесса написан профиль»,
// а не «что делает шаг»), — расхождение в один символ. У ручной работы слова нет вовсе, композитор
// доходит до заметки, и лист, не дойдя до композитора, печатал подпись КАТЕГОРИИ вместо
// единственного осмысленного имени, какое у шага было.
head('Т. шаг без собственного слова зовётся на листе ТЕМ ЖЕ, ЧЕМ на экранах');
ck(shSheet[1] === 'fuse', 'дублирование на бумаге — глагол шага, а не процесс профиля', String(shSheet[1]));
ck(
  shSheet[1] === shRail[1].split(' · ')[0],
  'и это то же слово, что в рельсе',
  `${shSheet[1]} / ${shRail[1]}`,
);
ck(shSheet[1] !== 'fusing', 'слова из словаря профилей пресса на листе нет', String(shSheet[1]));
ck(shSheet[2] === NOTE_HAND, 'ручная работа на бумаге зовётся ЗАМЕТКОЙ', String(shSheet[2]));
ck(shSheet[2] === shRail[2], 'тем же именем, что в рельсе', `${shSheet[2]} / ${shRail[2]}`);
// ЗАМЕТКА НЕ ПЕЧАТАЕТСЯ ДВАЖДЫ. Имя пришло из неё, а под именем у листа стоит своя строка заметки —
// без глушения одна фраза стояла бы в клетке подряд два раза.
const handCell = await sheetCell(2, 'operation');
ck(
  handCell === NOTE_HAND,
  'и в клетке она стоит ОДИН раз, а не именем и заметкой подряд',
  String(handCell),
);

// ── РЯДЫ ОТСТРОЧКИ ──────────────────────────────────────────────────────────────────────────────
//
// ПОЛЕ, КОТОРОЕ ЧЕЛОВЕК ЗАПОЛНЯЕТ РУКАМИ, А ВИДНО ЕГО БЫЛО ТОЛЬКО НА БУМАГЕ. Число рядов знал лист
// и не знала карта примерки: технолог, глядя на карту, видел одну строчку там, где швея по листу
// прокладывала две.
head('У. ряды отстрочки названы НА ОБЕИХ поверхностях, одним составителем');
const tsMap = (await mapSpec(0)) ?? [];
// КОЛОНКА «seam», А НЕ «machine / mode»: лист печатает и отстрочку, и плотность в клетке шва —
// там же, где класс и припуск. Первая редакция этой цитаты искала их в колонке машинки и краснела
// впустую, доказывая только то, что автор не открывал бумагу.
const tsSeam = await sheetCell(0, 'seam');
ck(
  tsMap.some((t) => t.includes('topstitch 2 × 6 mm from the edge')),
  'карта примерки называет ДВА ряда — прежде она о них молчала',
  JSON.stringify(tsMap),
);
ck(
  String(tsSeam).includes('topstitch 2 × 6 mm from the edge'),
  'и лист печатает ту же фразу',
  String(tsSeam),
);

// ── ПЛОТНОСТЬ, КОТОРОЙ НЕ БЫВАЕТ ────────────────────────────────────────────────────────────────
//
// ЗДЕСЬ ПРАВА БЫЛА БУМАГА, И ТЕМ ЦИТАТА ИНТЕРЕСНЕЕ: сведение чинит ЭКРАН. Ультразвук соединяет
// теплом — стежка у него нет вовсе (оттого нет и номера по ISO 4915), — и карточные «4 st/cm»
// описывали бы строчку, которой на этой машине не бывает. Лист держал предикат, редактор передавал
// карточную плотность безусловно.
head('Ф. карточная плотность наследуется ТОЛЬКО там, где есть строчка');
await openStep(0);
const sewMachine = await editorMachine();
ck(
  sewMachine.includes('4 st/cm (2.5 mm)'),
  'на швейном шаге карточная плотность наследуется — как и раньше',
  sewMachine,
);
ck(
  String(await sheetCell(0, 'seam')).includes('4 st/cm (2.5 mm)'),
  'и на бумаге у него та же плотность',
  String(await sheetCell(0, 'seam')),
);
await openStep(3);
const weldMachine = await editorMachine();
ck(
  !weldMachine.includes('st/cm'),
  'а на сварочной машине сводка редактора о плотности МОЛЧИТ',
  weldMachine,
);
ck(
  !String(await sheetCell(3, 'seam')).includes('st/cm'),
  'и бумага молчит о ней тоже — как молчала всегда',
  String(await sheetCell(3, 'seam')),
);

// ── ДОЛЕВАЯ ─────────────────────────────────────────────────────────────────────────────────────
//
// РАСКРОЙНЫЙ ЛИСТ, и цена ошибки тут не в слове: `lengthwise` и `crosswise`, стоящие в столбик,
// различаются ОДНОЙ БУКВОЙ В СЕРЕДИНЕ. Глиф для того и заведён — его читают, не дочитывая слово.
head('Х. долевая печатается СТРЕЛКОЙ И СЛОВОМ, как на вкладке деталей');
const grainCells = await sheetGrainCells();
ck(grainCells.length > 0, 'долевая вообще напечаталась', JSON.stringify(grainCells));
ck(
  grainCells.every((t) => t.startsWith('↑')),
  'и каждая клетка ведёт СТРЕЛКОЙ, а не голым словом',
  JSON.stringify(grainCells),
);

// ── ЗАПИСЬ ДО 0306 ──────────────────────────────────────────────────────────────────────────────
//
// ДВЕ ПОЛОВИНЫ ОДНОГО ПЕРЕЕЗДА, И ОБЕ ОБЯЗАТЕЛЬНЫ. Имя такого шага теперь собирает композитор — то
// есть бумага зовёт его так же, как панель релизов, единственный второй экран, где он вообще виден.
// А номер по ISO 4915, который держался в подписи типа, переехал в колонку «на чём»: там же, где он
// стоит у современного шага, и там же, где его печатает панель релизов своей строкой рядом с
// заголовком. Проверять надо ОБЕ: имя без номера — это молча потерянный стежок, номер без имени —
// расхождение, ради которого перепись и заводилась.
head('Ч. запись до 0306: имя — композитором, номер стежка — в своей колонке');
ck(shSheet[4] === 'join', 'лист зовёт легаси-шаг ГЛАГОЛОМ, как и все экраны', String(shSheet[4]));
ck(
  shSheet[4] === shRail[4].split(' · ')[0],
  'и это то же слово, что в рельсе',
  `${shSheet[4]} / ${shRail[4]}`,
);
const legacyMode = await sheetCell(4, 'machine / mode');
// РАВЕНСТВО, А НЕ ВХОЖДЕНИЕ, И ЭТО ПОПРАВКА ПО СУЩЕСТВУ. `includes` здесь однажды уже пропустил
// то, ради чего цитата написана: клетка печатала «join — lockstitch 301», то есть НАЧИНАЛАСЬ
// глаголом, повторяя имя шага из соседней колонки, — а обещание цитаты («как у современного шага»)
// было неправдой, потому что у современного там стоит «zigzag 304» без всякого глагола. Подстрока
// на такое не жалуется по построению: приклеенное спереди слово ей не мешает. Равенство жалуется.
ck(
  String(legacyMode).trim() === 'lockstitch 301',
  'НОМЕР СТЕЖКА не потерян и стоит ОДИН — клетка той же формы, что у современного шага',
  String(legacyMode),
);
// Прочерка тут быть не может: до правки клетка была ПУСТА, и «—» означало бы, что переезд не
// состоялся, а номер просто исчез с бумаги.
ck(legacyMode !== '—' && !!legacyMode, 'и клетка не пуста — до переезда она была именно пустой', String(legacyMode));

// СВОЕЙ ЦИТАТЫ У РЕЛИЗНОЙ ПЕЧАТИ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ДЫРА. Путь до клетки «на чём» у
// живой и у замороженной бумаги буквально один: `freeze()` снимает со строк только `work`, а `head`
// его не читает вовсе. Легаси-шаг при этом живёт в стенде листа, а не в стенде релиза, так что
// вторая цитата проверяла бы, что `renderSheet(frozen)` зовёт ту же функцию, — то есть стенд, а не
// продукт. Расхождение экрана архива с бумагой сторожит своя пара цитат (`--mutate-releaselive`,
// `--mutate-releaseclass`), и легаси-ступень панели релизов лежит в той же ветке, что они читают.

// ── ТАБЛИЦА ЛЕГАСИ-ФАКТОВ ───────────────────────────────────────────────────────────────────────
//
// ЦИТАТА ВЫШЕ ДОКАЗЫВАЕТ ПРОВОДКУ, ЭТА — СОДЕРЖИМОЕ. На бумаге фикстуры легаси-шаг ОДИН, поэтому
// отрендеренная клетка отвечает за одного члена из девяти: восьмерых остальных на листе нет вовсе,
// и любая ошибка в их строках прошла бы мимо. Спрашиваем модуль напрямую.
//
// ОЖИДАНИЯ ПОИМЁННЫЕ, И ИНАЧЕ НЕЛЬЗЯ. «Факт непуст» проходит у семи и НЕ ПРОХОДИТ у двух, а «факт
// содержит число» ложно упало бы на трёх: номер по ISO 4915 несут шестеро, `twin needle` — факт об
// оборудовании без числа, а у петли и пришивания пуговицы подпись РАВНА глаголу, и говорить о
// машине им нечего. Один инвариант на всех девятерых был бы либо пустым, либо ложным.
//
// ДВЕ ПУСТЫЕ СТРОКИ ЗДЕСЬ — РЕШЕНИЕ, А НЕ ПРОПУСК, и написаны они вслух именно поэтому: у этих
// двух клетка «на чём» честно пуста, ровно как была до переезда, и следующий читатель не должен
// счесть их забытыми.
const LEGACY_FACT_EXPECTED = {
  TECH_CARD_OPERATION_TYPE_LOCKSTITCH: 'lockstitch 301',
  TECH_CARD_OPERATION_TYPE_DOUBLE_NEEDLE: 'twin needle',
  TECH_CARD_OPERATION_TYPE_OVERLOCK: '504 / 514 / 516',
  TECH_CARD_OPERATION_TYPE_COVERSTITCH: '602 / 605',
  TECH_CARD_OPERATION_TYPE_CHAINSTITCH: '401',
  TECH_CARD_OPERATION_TYPE_BLINDHEM: '103',
  TECH_CARD_OPERATION_TYPE_BARTACK: '304',
  TECH_CARD_OPERATION_TYPE_BUTTONHOLE: '',
  TECH_CARD_OPERATION_TYPE_BUTTON_ATTACH: '',
};
const legacyFacts = await page.evaluate(() => window.__stepName.legacyFacts());
const legacyFactMap = Object.fromEntries(legacyFacts);
ck(
  legacyFacts.length === Object.keys(LEGACY_FACT_EXPECTED).length,
  'группа легаси — та же девятка, что и была: карта не потеряла и не приобрела члена',
  `в карте ${legacyFacts.length}, ожидалось ${Object.keys(LEGACY_FACT_EXPECTED).length}: ${legacyFacts
    .map(([t]) => t.replace('TECH_CARD_OPERATION_TYPE_', ''))
    .join(', ')}`,
);
// `undefined` ЗДЕСЬ — НЕСУЩАЯ ДЕТАЛЬ, А НЕ ШУМ, И `?? ''` ЗАПРЕЩЁН. Таблица идёт по ВЫВОДИМОМУ
// массиву, поэтому два отказа выглядят по-разному: `''` значит «член в группе, факта у него нет»
// (законно, ожидается у петли и пуговицы), а `undefined` — «член выпал из группы» (дефект).
// Припиши кто-нибудь `?? ''`, чтобы «не сравнивать с undefined», — и выпадение ровно тех двух
// членов, у которых ожидание и есть `''`, станет неотличимо от их законной пустоты: ожидалось
// пусто, получено пусто, зелено. Счёт выше упал бы, а поимённая строка соврала бы — то есть два
// разных отказа схлопнулись бы в один.
for (const [type, want] of Object.entries(LEGACY_FACT_EXPECTED)) {
  const got = legacyFactMap[type];
  const short = type.replace('TECH_CARD_OPERATION_TYPE_', '');
  ck(
    got === want,
    want === ''
      ? `${short}: клетка «на чём» пуста — его подпись не говорит о машине ничего сверх глагола`
      : `${short}: клетка «на чём» говорит «${want}» — факт из подписи, без глагола`,
    `получено ${JSON.stringify(got)}`,
  );
}

