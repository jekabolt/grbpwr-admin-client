const releaseRow = (label) =>
  page.evaluate((label) => {
    const hits = [...document.querySelectorAll('#releases span')].filter(
      (s) => (s.textContent ?? '').replace(/\s+/g, ' ').trim() === label,
    );
    if (hits.length === 0) return '(строки нет)';
    if (hits.length > 1) return `(строк ${hits.length})`;
    return (hits[0].nextElementSibling?.textContent ?? '').replace(/\s+/g, ' ').trim();
  }, label);

