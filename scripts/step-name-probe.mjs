async function mount(ops = STEPS, card) {
  await page.goto('http://probe.local/');
  await page.addScriptTag({ content: bundle });
  await page.evaluate(([s, c]) => window.__stepName.mount(s, c), [ops, card]);
  await page.waitForSelector(`[data-rail-step="${ops.length - 1}"]`, { timeout: 20000 });
  // Каталог — сетевой запрос, и он приезжает ПОСЛЕ первого кадра. Ждём по признаку, а не по
  // таймеру: иначе «имя не то» смешалось бы с «каталог ещё не приехал».
  await page.waitForTimeout(500);
}

/** Заголовок строки рельса — ИЗ `title`, а не из textContent: в узле рядом лежат номер и норма. */
const railTitle = (i) => page.getAttribute(`[data-rail-step="${i}"]`, 'title');
/** Имя шага в карте примерки — узел, в котором лежит ТОЛЬКО имя. */
const mapName = async (i) =>
  ((await page.locator(`#map [data-map-step="${i}"]`).textContent()) ?? '').trim();
/**
 * СТРОКА СПЕЦИФИКАЦИИ карты примерки — соседи узла с именем внутри той же ячейки строки.
 *
 * Своего `data-*` у неё нет, и заводить его ради пробы не стоит: имя размечено, а спецификация
 * стоит РЯДОМ С НИМ в одном родителе, так что «всё, что в ячейке кроме имени» — адрес не менее
 * точный. Возвращается СПИСОК УЗЛОВ, а не склеенный текст ячейки: склейка соседей — известный
 * способ получить зелёную цитату там, где орган на самом деле пуст, а нужное слово принесла
 * соседняя строка («not pinned to the sketch» стоит здесь же, сразу под спецификацией).
 */
const mapSpec = (i) =>
  page.evaluate((i) => {
    const name = document.querySelector(`#map [data-map-step="${i}"]`);
    const wrap = name?.parentElement;
    if (!wrap) return null;
    return [...wrap.children]
      .filter((n) => n !== name)
      .map((n) => (n.textContent ?? '').replace(/\s+/g, ' ').trim());
  }, i);

