//   М — СХЕМА СБОРКИ не приделывает к композитору СВОЮ СТУПЕНЬ. Здесь проверяется не «зовёт ли
//       экран композитор» (А–Л), а «не стоит ли перед ним чужая лестница»: `labelOfStep` ставил
//       заметку ПЕРЕД вызовом и кормил этим все три вида полотна и фулскрин, так что шаг с
