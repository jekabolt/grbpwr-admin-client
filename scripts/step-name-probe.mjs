// ДВОЕКОДЬЕ ИМЕНИ ШАГА: РАБОТА НАЗЫВАЕТ ЕГО ВЕЗДЕ, ИЛИ ЖЕ ЕГО НАЗЫВАЕТ СЕГОДНЯШНЯЯ ДЕРИВАЦИЯ (R8).
//
// ДЕФЕКТ, РАДИ КОТОРОГО ПРОБА. R6 научил пикер писать РАБОТУ в строку шага — и на этом остановился:
// имя шага собиралось по-прежнему из глагола с машинкой и класса шва. Поэтому шаг с классом шва
// отстрочки, которому назначили московский шов, назывался «Hem — rolled (Moscow)» в триггере
// пикера и «topstitch · front» в заголовке над ним, в рельсе слева, в карте примерки, на схеме
// сборки и — что хуже всего — НА ПЕЧАТНОМ ЛИСТЕ, то есть на той единственной копии карточки,
// которая стоит у машины. Швея и технолог называли одну строку разными словами.
//
// ПОЧЕМУ ПРОБА ЖИВАЯ, А НЕ ТАБЛИЧНАЯ. Проверяется не то, что композитор возвращает правильную
// строку, — он и до R8 возвращал правильную из того, что ему дали, — а то, что ЭКРАН зовёт его С
// РАБОТОЙ. Проба, зовущая композитор напрямую, зеленела бы при ровно том дефекте, ради которого
// заведена. У печатного листа причина ещё жёстче: он держал свою развилку по типу шага, и ветка
// ВТО шла мимо композитора вовсе — увидеть это можно только напечатав лист.
//
// ЦИТАТЫ:
//   А — работа названа: шаг зовётся ПОДПИСЬЮ КАТАЛОГА в рельсе и в шапке открытого шага, и тем же
//       словом стоит в триггере пикера (три органа, одно имя);
//   Б — то же имя НА ПЕЧАТНОМ ЛИСТЕ, включая шаг ВТО, чья ветка листа композитора не звала;
//   В — то же имя в КАРТЕ ПРИМЕРКИ на вкладке семплов;
//   Н — та же КАРТА ПРИМЕРКИ, но строка спецификации под именем: плотность строчки названа ОБЕИМИ
//       единицами — «4 st/cm (2.5 mm)». Длина стежка в мм не хранится нигде и считается как
//       `10 / плотность`; карта собирала строку руками и печатала только «4 st/cm», то есть
//       теряла половину чтения ровно у того, кому она нужна, — у оператора с диалом ДЛИНЫ СТЕЖКА;
//   Г — шаг БЕЗ работы зовётся по-старому: буквой в букву тем же, что даёт сегодняшняя деривация;
//   Д — незнакомый токен виден ТЕКСТОМ на всех трёх экранах и НЕ подменён догадкой;
//   Е — остаток R6 закрыт: работа бьёт класс шва, а не наоборот;
//   Ж — экраны не расходятся: рельс, карта и лист называют каждый шаг одним и тем же словом;
//   З — каталог НЕ приехал: работа, знакомая снимку бандла, зовётся ТЕМ ЖЕ именем, что с сервера;
//       шаг без работы не шелохнулся; работа, снимку неизвестная, видна токеном; работа 0331,
//       выписанная в снимок дельтой, названа его ярлыком. Пустых имён нет;
//   И — R8 НИЧЕГО НЕ ПИШЕТ: после монтирования всех экранов значения `work` в форме те же, что
//       положили. Половина фазы «перестать терять» стоит именно на этом;
//   К — ФРАЗА ДЛИНЫ на печатном листе называет ТО, ЧТО РЕЖУТ: прорезь — разрезом, шаг без работы —
//       по-прежнему петлёй, незнакомый токен — токеном. Заголовок и факты — ДВА РАЗНЫХ ПУТИ в одну
//       бумагу, и R8 починила только первый: строка звалась «Slit — overcast», а клетка «machine /
//       mode» в той же строке печатала «buttonhole, cut 18 mm»;
//   Л — печать РЕЛИЗНОГО СНАПШОТА (источник БЕЗ поля `work`) даёт сегодняшнюю деривацию, и клетка
//       отличается от живой ровно одним словом. Признака «это релиз» продуктовый код не читает и
//       читать не должен: отсутствие поля в подписанном блобе И ЕСТЬ утверждение «работа здесь
//       названа не была»;
//   О — ПРИПУСК ШВА: одно чтение на карте примерки и в редакторе, и наследование не теряется.
//       Две половины, и вторая дороже. СЛОВО: карта печатала «SA 10 mm», редактор — «allowance
//       10 mm», причём «SA» вставало в тот же список ·, где стоят коды ISO 4916 (SS, LS, EF, BS,
//       FS, OS), двухбуквенным токеном в верхнем регистре. ФАКТ: припуск хранится ТОЛЬКО там, где
//       шаг его переопределяет, и пустая колонка значит «действует стандарт карточки, а нет его —
//       цеховой»; редактор ходил по этой лестнице, карта читала лишь собственное значение шага, —
//       и шаг, ИСПРАВНО наследующий припуск, показывал число в редакторе и НИЧЕГО на карте.
//       Цитата стоит НА СВЕРКЕ двух поверхностей, а не на тексте каждой: порознь обе половины
//       зеленели бы и в мире, где слова совпали случайно. Отдельными шагами проверены ГЕЙТ
//       лестницы (на упаковке карточный стандарт не печатается — он верен и бессмыслен разом) и
//       его граница (НАПИСАННОЕ человеком число видно на любом глаголе);
//   П — КЛАСС ШВА назван ОДНИМ ярлыком на обеих ЖИВЫХ поверхностях. Текстом они не расходились и
//       до правки — карта подписей у обоих одна, — но искали его двумя копиями
//       `seamClassOptions.find(...)` с двумя проверками UNKNOWN, то есть держали две редакции
//       одного правила. Цитата запрещает расхождение, а не проверяет сегодняшний текст;
//   П (продолжение) — РАЗВИЛКА ФОЛБЭКА, И ОНА НАМЕРЕННАЯ. Незнакомый токен (класс, ушедший из
//       контракта) живые экраны ОБА обходят молчанием, а АРХИВ РЕЛИЗОВ печатает ТОКЕНОМ: на
//       живом экране сырой `TECH_CARD_…` хуже пустоты (пустота видимо неполна, токен выглядит
//       ответом), а из подписанного документа строку нельзя терять вовсе. Читается настоящий
//       `ReleasesField`, снимок приезжает по сети. Главная цитата — та, что требует ОТВЕТЫ
//       РАЗНЫМИ: без неё две почти одинаковые функции свели бы в одну, и любая из двух сторон
//       такого сведения — дефект. Отдельно проверена ГРАНИЦА развилки: НЕ НАЗВАННЫЙ класс архив
//       не печатает так же, как живой экран, — расходится ровно фолбэк незнакомого токена;
//   Р — ПЕЧАТНЫЙ ЛИСТ читает припуск ТОЙ ЖЕ лестницей, что экраны, — включая ЦЕХОВУЮ ступень,
//       которой у него не было вовсе. Карточка без своего стандарта печаталась «card standard not
//       set» ровно тогда, когда редактор и карта примерки уже показывали цеховое число, а источник
//       на бумаге звался «(card standard)» против «(card)» на экране. Главная половина цитаты —
//       СВЕРКА листа с картой примерки в одном стенде. Вторая половина — про ГЕЙТ: ступень
//       приезжает сетью, и без своей строки в `onDataStatus` она делает дефект ПЛАВАЮЩИМ (бумага
//       верна, когда ответ успел). Проверяется это НЕ ПО ТЕКСТУ — пока ответ в пути, клетка
//       выглядит так же, как если бы цех промолчал, — а по тому, что документ САМ говорит о своей
//       готовности;
//   С — ЗОНА И КЛАСС ШВА НА ЛИСТЕ — те же ярлыки, что в заголовке шага и на карте примерки. Лист
//       держал две local'ные копии через `optionLabel`, и копиями они были БУКВАЛЬНО: то же правило
//       слово в слово, без фолбэка на токен, то есть без развилки, которую стоило бы сохранить.
//       Платилось это тем, что первая же ступень, дописанная в общий ярлык, попадала бы в заголовок
//       и НЕ попадала в колонку того же листа — расхождение от правки чего-то ДРУГОГО;
//   Т — ШАГ, У КОТОРОГО СВОЕГО СЛОВА НЕТ, зовётся на листе тем же, чем на экранах. Две дыры одной
//       ветки: у ДУБЛИРОВАНИЯ слово есть, но лист брал его из словаря процессов ПРЕССА («fusing»
//       против «fuse» на всех экранах); у РУЧНОЙ РАБОТЫ слова нет вовсе, композитор доходит до
//       заметки, а лист до композитора не доходил и печатал подпись КАТЕГОРИИ вместо единственного
//       осмысленного имени, какое у шага было. Проверяется и то, что заметка не встала в клетку
//       дважды — именем и своей строкой подряд;
//   У — РЯДЫ ОТСТРОЧКИ названы на ОБЕИХ поверхностях. `topstitch.rows` знал только лист: технолог
//       по карте примерки видел одну строчку там, где швея по бумаге прокладывала две, — а число
//       рядов человек заполняет РУКАМИ, контролом «rows of topstitching»;
//   Ф — КАРТОЧНАЯ ПЛОТНОСТЬ наследуется только там, где есть строчка. Здесь права была БУМАГА, и
//       тем цитата интереснее: сведение чинит ЭКРАН. Ультразвук и термолента соединяют теплом —
//       стежка нет вовсе (оттого нет и номера по ISO 4915), — но правило жило приватным предикатом
//       листа, и сводка редактора показывала на таком шаге унаследованные «4 st/cm (2.5 mm)»;
//   Х — ДОЛЕВАЯ печатается СТРЕЛКОЙ И СЛОВОМ, как на вкладке деталей и в видах кроя. Это РАСКРОЙНЫЙ
//       лист, а `lengthwise` и `crosswise`, стоящие в столбик, различаются одной буквой В СЕРЕДИНЕ
//       слова; глиф для того и заведён, что его читают не дочитывая;
//   Ц — ПРОЦЕНТ РАСКРОЯ печатается только там, где у слота ЕСТЬ норма. ЕДИНСТВЕННАЯ из семи копий,
//       расходившаяся не в СЛОВЕ, а в ЧИСЛЕ, ПО КОТОРОМУ ЗАКУПАЮТ: лист считал нормой строки
//       рецепта, привязанные к ДЕТАЛИ, панель редактора их отбрасывала, и «+15 %» появлялся на
//       спецификации там, где в редакторе надбавки не стояло. Права панель — сервер исключает такие
