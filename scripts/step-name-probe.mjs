async function sheetNames(count = STEPS.length) {
  await page.evaluate(() => window.__stepName.sheet());
  // ЖДЁМ ПОСЛЕДНЮЮ СТРОКУ ИМЕННО ЭТОГО СТЕНДА. Индекс был зашит числом, и на стенде с другим
  // числом шагов ожидание молча выбирало таймаут: двадцать секунд простоя на каждый вызов и
  // чтение недорисованного листа в награду.
  await page
    .waitForFunction((n) => !!document.querySelector(`#sheet [data-sheet-step="${n}"]`), {
      timeout: 20000,
    }, count - 1)
    .catch(() => {});
  return page.evaluate(() =>
    [...document.querySelectorAll('#sheet [data-sheet-step]')].map((n) =>
      (n.textContent ?? '').replace(/\s+/g, ' ').trim(),
    ),
  );
}

/**
 * Клетка «machine / mode» каждой строки листа — там печатается фраза длины прорези.
 *
 * ЧИТАЕТСЯ КЛЕТКА ЦЕЛИКОМ, А НЕ ПОДСТРОКА В НЕЙ, и это принципиально: цитата «не сдвинулось ни на
 * символ» сравнивает ВЕСЬ текст клетки, поэтому фраза не может тихо переехать в соседнюю колонку
 * или обрасти вторым словом, оставив пробу зелёной.
 */
const modeCells = () =>
  page.evaluate(() =>
    [...document.querySelectorAll('#sheet [data-sheet-mode]')].map((n) =>
      (n.textContent ?? '').replace(/\s+/g, ' ').trim(),
    ),
  );

/**
 * Напечатать лист ЛЮБОЙ карточки и дождаться его последней строки.
 *
 * `sheetNames` выше ждёт девятую строку — она написана про карточку из девяти шагов и другую ждать
 * не умеет. Стенд припуска короче, и «лист не нарисовался» на нём выглядело бы как «клетки нет».
 */
async function printSheet(lastIndex) {
  await page.evaluate(() => window.__stepName.sheet());
  await page
    .waitForFunction((i) => !!document.querySelector(`#sheet [data-sheet-step="${i}"]`), lastIndex, {
      timeout: 20000,
    })
    .catch(() => {});
  // Гейт готовности документ сообщает ЭФФЕКТОМ, а не рендером: он проходит после первого кадра.
  await page.waitForTimeout(200);
}

/**
 * КЛЕТКА «seam» строки листа — СПИСКОМ СВОИХ СТРОК: класс шва, припуск, факты шва.
 *
 * АДРЕС — ЗАГОЛОВОК КОЛОНКИ, а не порядковый номер: колонок девять, они плотные, и новая между
 * ними появлялась уже дважды. Номер, вписанный в пробу константой, пережил бы такую вставку молча и
 * начал бы читать соседнюю клетку — то есть цитата зеленела бы или краснела не о том органе.
 *
 * СПИСКОМ, А НЕ ТЕКСТОМ КЛЕТКИ, по той же причине, по какой список возвращает `mapSpec`: склейка
 * соседей — известный способ получить зелёную цитату там, где нужное слово принесла соседняя
 * строка. Здесь это особенно близко: класс шва и припуск стоят вплотную, и «SS — plain seam» +
 * «allowance 10 mm» склеились бы в строку, содержащую обе искомые подстроки при пустой второй.
 */
const sheetSeamLines = (i) =>
  page.evaluate((i) => {
    const name = document.querySelector(`#sheet [data-sheet-step="${i}"]`);
    const row = name?.closest('tr');
    const table = name?.closest('table');
    if (!row || !table) return null;
    const heads = [...table.querySelectorAll('thead th')].map((h) =>
      (h.textContent ?? '').replace(/\s+/g, ' ').trim(),
    );
    const col = heads.indexOf('seam');
    if (col < 0) return `(колонки «seam» нет: ${heads.join('|')})`;
    const cell = row.children[col];
    if (!cell) return `(клетки нет, колонок в строке ${row.children.length})`;
    return [...cell.children].map((n) => (n.textContent ?? '').replace(/\s+/g, ' ').trim());
  }, i);

