await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '12' });
ck(pageErrors.length === 0, 'стенд припуска смонтировался без исключений', pageErrors[0] ?? '');

// О.1 — СОБСТВЕННОЕ ЗНАЧЕНИЕ. Точным равенством: кроме класса шва и припуска у шага не заполнено
// ничего, так что узел обязан состоять ровно из этих двух чтений.
const saOwnMap = await mapSpec(0);
ck(
  saOwnMap?.[0] === 'SS — plain seam · allowance 10 mm',
  'карта примерки называет собственный припуск СЛОВОМ, а не кодом «SA»',
  String(saOwnMap?.[0]),
);
ck(
  !JSON.stringify(saOwnMap).includes('SA '),
  'и старого двухбуквенного токена на карте нет вовсе',
  JSON.stringify(saOwnMap),
);
await openStep(0);
const saOwnEditor = await editorSeam();
ck(
  saOwnEditor === 'SS — plain seam · allowance 10 mm',
  'редактор читает то же поле теми же словами',
  saOwnEditor,
);
ck(saOwnMap?.[0] === saOwnEditor, 'две поверхности — ОДНА строка', `${saOwnMap?.[0]} / ${saOwnEditor}`);

// О.2 — ПОТЕРЯННЫЙ ФАКТ. Шаг припуска не переопределяет, и обе поверхности обязаны назвать
// карточный стандарт — С ЕДИНИЦЕЙ и с источником.
const saCardMap = await mapSpec(1);
ck(
  saCardMap?.[0] === 'allowance 12 mm (card)',
  'УНАСЛЕДОВАННЫЙ припуск виден на карте примерки — он и был потерян',
  String(saCardMap?.[0]),
);
await openStep(1);
const saCardEditor = await editorSeam();
ck(
  saCardEditor === 'allowance 12 mm (card)',
  'и в редакторе — тем же чтением, С МИЛЛИМЕТРАМИ',
  saCardEditor,
);
// Единица названа ОТДЕЛЬНОЙ проверкой: ручная сборка редактора писала «allowance 12 (card)» —
// число верное, ступень верная, единицы нет. Склеенная цитата не отличила бы «потеряли миллиметры»
// от «потеряли ступень целиком».
ck(saCardEditor.includes('12 mm'), 'единица у унаследованной ступени на месте', saCardEditor);
ck(saCardMap?.[0] === saCardEditor, 'две поверхности — ОДНА строка', `${saCardMap?.[0]} / ${saCardEditor}`);

// О.3 — ГЕЙТ. Лестница неприменима там, где шва нет: «allowance 12 mm (card)» на упаковке верно и
// бессмысленно разом. Редактор этот отказ уже выносил; проверяется, что вторая поверхность получила
// ЕГО ЖЕ, а не своё прочтение.
const saPackMap = await mapSpec(2);
ck(
  (saPackMap ?? []).every((t) => !t.includes('allowance')),
  'на шаге без шва карточный стандарт НЕ печатается',
  JSON.stringify(saPackMap),
);
await openStep(2);
ck(
  (await editorSeam()) === '(сводки шва нет)',
  'и редактор на нём сводку шва не рисует вовсе',
  await editorSeam(),
);
// ...но НАПИСАННОЕ ЧЕЛОВЕКОМ число показывается на любом глаголе: гейт спрашивают у ступеней НАД
// шагом, а не у самого поля.
const saPackOwnMap = await mapSpec(3);
ck(
  saPackOwnMap?.[0] === 'allowance 5 mm',
  'а СВОЙ припуск виден и на шаге без шва',
  String(saPackOwnMap?.[0]),
);
await openStep(3);
ck((await editorSeam()) === 'allowance 5 mm', 'и в редакторе тоже', await editorSeam());

// О.4 — ПОСЛЕДНЯЯ СТУПЕНЬ. Карточка своего стандарта не назвала, цех — назвал. Ступень приезжает
// ПО СЕТИ, отдельным запросом, и до этой правки карта примерки его не делала вовсе.
head('О (продолжение). цеховая ступень — та же лестница, тот же текст на обеих поверхностях');
pageErrors.length = 0;
shopAllowance = '15';
await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '' });
ck(pageErrors.length === 0, 'стенд цеховой ступени смонтировался без исключений', pageErrors[0] ?? '');
const saShopMap = await mapSpec(1);
ck(
  saShopMap?.[0] === 'allowance 15 mm (workshop)',
  'карта примерки доходит до ЦЕХОВОЙ ступени и называет её источник',
  String(saShopMap?.[0]),
);
await openStep(1);
const saShopEditor = await editorSeam();
ck(saShopEditor === 'allowance 15 mm (workshop)', 'редактор — тем же чтением', saShopEditor);
ck(saShopMap?.[0] === saShopEditor, 'две поверхности — ОДНА строка', `${saShopMap?.[0]} / ${saShopEditor}`);
// И СОБСТВЕННОЕ ЗНАЧЕНИЕ ПО-ПРЕЖНЕМУ БЬЁТ ОБЕ СТУПЕНИ — иначе «лестница работает» означало бы
// всего лишь «нижняя ступень громче верхней».
const saOwnAgain = await mapSpec(0);
ck(
  saOwnAgain?.[0] === 'SS — plain seam · allowance 10 mm',
  'собственное значение шага бьёт обе ступени над ним',
  String(saOwnAgain?.[0]),
);

// ── КЛАСС ШВА: ОДИН ЯРЛЫК ───────────────────────────────────────────────────────────────────────
//
// Карта примерки и редактор искали подпись класса КАЖДЫЙ СВОИМ `seamClassOptions.find(...)` с
// собственной проверкой UNKNOWN. Текстом они пока не расходились — карта подписей у обоих одна, —
// но два поиска по одному массиву это две редакции одного правила, и первая же ступень, дописанная
// в одну из них, стала бы третьим прочтением одного поля. Цитата стоит НА СВЕРКЕ, а не на тексте:
// именно расхождение и надо запретить.
head('П. класс шва назван ОДНИМ ярлыком на обеих поверхностях');
await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '12' });
const clsMap = (await mapSpec(0))?.[0]?.split(' · ')[0];
await openStep(0);
const clsEditor = (await editorSeam()).split(' · ')[0];
ck(clsMap === 'SS — plain seam', 'карта примерки называет класс его подписью', String(clsMap));
ck(clsEditor === 'SS — plain seam', 'редактор — той же', String(clsEditor));
ck(clsMap === clsEditor, 'и это ОДНА подпись, а не две совпавшие', `${clsMap} / ${clsEditor}`);

// ── РАЗВИЛКА ФОЛБЭКА: ОДИН ТОКЕН, ДВА РАЗНЫХ ОТВЕТА — И ЭТО НАМЕРЕННО ───────────────────────────
//
// ПОДПИСИ У ЖИВЫХ ЭКРАНОВ И У АРХИВА ОДНИ (`SEAM_CLASS_LABELS`), А ФОЛБЭКИ РАЗНЫЕ, и разойтись им
// приказано. Живому экрану сырой `TECH_CARD_SEAM_CLASS_…` хуже пустоты: пустота ВИДИМО неполна, а
// токен ВЫГЛЯДИТ ответом, и технолог читает его как назначение. Архиву правило обратное и сильнее:
// строка подписана, и потерять её нельзя даже ценой некрасивого токена.
//
// БЕЗ ЭТОЙ ЦИТАТЫ РАЗНИЦА ЧИТАЕТСЯ КАК НЕДОСМОТР. Две почти одинаковые функции с одним именем в
// двух файлах — первое, что следующий ревьюер захочет свести, и свести их можно в ЛЮБУЮ сторону:
// в одну — на живой экран выезжает токен, в другую — из подписанного документа пропадает строка.
// Обе стороны закрыты мутациями (`--mutate-liveclass`, `--mutate-releaseclass`) — по одной на
// каждое направление «починки», иначе половина развилки осталась бы без сторожа.
//
// ЧИТАЕТСЯ СТЕНД БЕЗ СТУПЕНЕЙ ПРИПУСКА: ни карточного стандарта, ни цехового. Тогда строка
// спецификации состоит ровно из класса шва и якоря-лапки, и «класс промолчал» нельзя спутать с
// «его заслонил припуск».
head('П (продолжение). незнакомый класс: живые экраны молчат, ПОДПИСАННЫЙ документ печатает токен');
pageErrors.length = 0;
shopAllowance = '';
await mount(SEAM_STEPS, { requiredSeamAllowanceMm: '' });
ck(pageErrors.length === 0, 'стенд развилки смонтировался без исключений', pageErrors[0] ?? '');

// ТОЧНЫМ РАВЕНСТВОМ С ЯКОРЕМ: узел обязан состоять РОВНО из лапки. Так одно чтение отвечает сразу
// на два вопроса — класс шва не сказал ничего И строка при этом не исчезла.
const clsUnknownMap = await mapSpec(4);
ck(
  clsUnknownMap?.[0] === FOOT,
  'КЛАСС НЕ НАЗВАН — карта примерки молчит, а строка спецификации цела',
  String(clsUnknownMap?.[0]),
);
const clsGoneMap = await mapSpec(5);
ck(
  clsGoneMap?.[0] === FOOT,
  'токен, УШЕДШИЙ ИЗ КОНТРАКТА, на живом экране тоже молчит — сырого токена там нет',
  String(clsGoneMap?.[0]),
);
await openStep(5);
const clsGoneEditor = await editorSeam();
ck(
  !clsGoneEditor.includes('TECH_CARD_'),
  'и редактор его не печатает: у живых поверхностей ОДИН ярлык, значит и одно молчание',
  clsGoneEditor,
);

// ...А ПОДПИСАННЫЙ ДОКУМЕНТ ПЕЧАТАЕТ ЕГО ТОКЕНОМ. Экран настоящий, снимок приезжает по сети.
await mountReleases(11);
const goneRow = await releaseRow('default seam class');
ck(
  goneRow === GONE_CLASS,
  'АРХИВ РЕЛИЗОВ печатает тот же токен ТОКЕНОМ: подписанная строка не имеет права пропасть',
  goneRow,
);
// СВЕРКА — ГЛАВНАЯ ЦИТАТА СЕКЦИИ, а не сумма двух предыдущих: она утверждает, что ответы РАЗНЫЕ, и
// тем запрещает свести их в любую из двух сторон. Порознь обе половины зеленели бы и в мире, где
// развилки нет вовсе.
ck(
  goneRow !== String(clsGoneMap?.[0]) && goneRow === GONE_CLASS && clsGoneMap?.[0] === FOOT,
  'ОДИН токен — ДВА разных ответа, и разными они сделаны НАМЕРЕННО',
  `архив: ${goneRow} / живой экран: ${clsGoneMap?.[0]}`,
);
// И ГРАНИЦА РАЗВИЛКИ: расходятся они РОВНО на незнакомом токене. «Не назван» архив печатает так же,
// как живой экран, — пустотой; иначе «архив всё показывает сырьём» было бы столь же согласно с
// цитатой выше, а это уже другое правило.
await mountReleases(12);
const unknownRow = await releaseRow('default seam class');
ck(
  unknownRow === '(строки нет)',
  'а НЕ НАЗВАННЫЙ класс архив тоже не печатает: расходится ровно фолбэк незнакомого токена',
  unknownRow,
);

// ── СХЕМА СБОРКИ ────────────────────────────────────────────────────────────────────────────────
//
// ЧЕМ ЭТА СЕКЦИЯ ОТЛИЧАЕТСЯ ОТ ВСЕХ ПРЕДЫДУЩИХ. Выше проверялось, что экран зовёт композитор С
// РАБОТОЙ; здесь — что экран не приделывает к композитору СВОЮ СТУПЕНЬ. `labelOfStep` кормит все
// три вида схемы и фулскрин, и заметка в нём стояла ПЕРЕД вызовом: до этой правки шаг 0 звался на
// полотне «check the pin at the sleeve head», хотя работа у него названа и рельс звал его
// московским швом.
//
// СВЕРКА С КАРТОЙ ПРИМЕРКИ — ГЛАВНАЯ ЦИТАТА, а не украшение. Карта смонтирована в том же стенде и
// читает ТЕ ЖЕ строки формы, но зовёт композитор напрямую и с заметкой ВНУТРИ. Требование
// «полотно = карта» и есть буквальная формулировка дефекта: две поверхности одной карточки не
// имеют права называть одну строку разными словами. Голая проверка «полотно говорит „Hem —
// rolled (Moscow)“» такого утверждения не делает — она зеленела бы и в мире, где имя совпало
// случайно.
head('М. схема сборки называет шаг ТЕМ ЖЕ, ЧЕМ карта примерки');
pageErrors.length = 0;
await mount(SCHEMATIC_STEPS);
// Вид переключается ЖЕСТОМ по настоящему органу, а не подстановкой предпочтения: карточка без
// узлов открывается списком, и «схема» здесь — то, куда попадает рука.
await page
  .locator('[role="radiogroup"][aria-label="sequence view"] [role="radio"]')
  .filter({ hasText: 'schematic' })
  .click();
// Строки шагов на полотне — по `title` органа: он один и тот же у бокса узла и у хвоста, а
// собственного `data-*` у них нет. Текст берётся целиком («10 · ИМЯ»), чтобы имя не могло тихо
// уехать в соседний узел, оставив цитату зелёной.
await page.waitForSelector('[title="open the step in the list"]', { timeout: 20000 });
const canvasRows = await page.evaluate(() =>
  [...document.querySelectorAll('[title="open the step in the list"]')].map((n) =>
    (n.textContent ?? '').replace(/\s+/g, ' ').trim(),
  ),
);
const mapRows = [await mapName(0), await mapName(1)];
ck(pageErrors.length === 0, 'схема смонтировалась без исключений', pageErrors[0] ?? '');
ck(canvasRows.length === 2, 'обе строки шагов нарисованы на полотне', canvasRows.join(' | '));
ck(
  canvasRows[0] === `10 · ${MOSCOW} · front`,
  'шаг с работой И непустой заметкой зовётся на схеме ПОДПИСЬЮ КАТАЛОГА',
  String(canvasRows[0]),
);
ck(
  !String(canvasRows[0]).includes(NOTE_WORK),
  'и текста заметки в его строке нет вовсе',
  String(canvasRows[0]),
);
ck(
  canvasRows[1] === `20 · ${NOTE_BARE}`,
  'шаг без работы и без выводимого имени по-прежнему зовётся ЗАМЕТКОЙ — фолбэк цел',
  String(canvasRows[1]),
);
for (let i = 0; i < SCHEMATIC_STEPS.length; i++) {
  ck(
    canvasRows[i] === `${(i + 1) * 10} · ${mapRows[i]}`,
    `шаг ${i}: схема и карта примерки называют его ОДНИМ словом`,
    `${canvasRows[i]} / ${mapRows[i]}`,
  );
}

await browser.close();
console.log(`\n${bad === 0 ? 'ЗЕЛЁНАЯ' : `КРАСНАЯ: ${bad}`}`);
process.exit(bad === 0 ? 0 : 1);
