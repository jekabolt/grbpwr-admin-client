// СВЕРКА С КАРТОЙ ПРИМЕРКИ — ГЛАВНАЯ ЦИТАТА, а не украшение. Карта смонтирована в том же стенде и
// читает ТЕ ЖЕ строки формы, но зовёт композитор напрямую и с заметкой ВНУТРИ. Требование
// «полотно = карта» и есть буквальная формулировка дефекта: две поверхности одной карточки не
