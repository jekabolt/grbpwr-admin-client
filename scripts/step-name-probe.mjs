//
// ИМЯ ФЛАГА ПРОВЕРЯЕТСЯ, А НЕ УГАДЫВАЕТСЯ: любое `--mutate…` вне этого списка роняет прогон с
// кодом 2 и словами «проба НЕ ЗАПУСКАЛАСЬ». Так и был найден дефект, ради которого сторож заведён:
