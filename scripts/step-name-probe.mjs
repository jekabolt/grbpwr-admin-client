//       заметки. Цитата — сверка полотна С КАРТОЙ ПРИМЕРКИ в том же стенде: карта читает те же
//       строки формы, но зовёт композитор напрямую, и «две поверхности, одно слово» и есть
//       буквальная формулировка дефекта. Фолбэк проверяется отдельным шагом — тем, у которого
