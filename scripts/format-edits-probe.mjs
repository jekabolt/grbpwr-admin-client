//
// СЧИТАЮТСЯ ИСХОДЫ, А НЕ КОД ВОЗВРАТА: каждая строка ловится по отдельности, отсутствующая
// функция считается ПРОВАЛОМ строки, а не обрывом прогона.
import { build as esbuild } from 'esbuild';
