// но код хайлайтится тройными». Первый заход трактовал жалобу как ошибку в развилке «одна строка —
// бэктики, несколько — ограда» и развилку сохранил; владелец выбрал другое — ВСЕГДА ОГРАДА. Строки
// R1…R8 поэтому ждут ровно противоположного тому, чего ждали вчера, и это не расшатывание таблицы,
