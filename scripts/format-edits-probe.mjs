const m = await import(pathToFileURL(outfile).href);

let pass = 0;
let fail = 0;
const failed = [];

const show = (s) => JSON.stringify(s);
const same = (a, b) =>
  a && b && a.start === b.start && a.end === b.end && a.text === b.text &&
  a.sel?.[0] === b.sel?.[0] && a.sel?.[1] === b.sel?.[1];

/** Как выглядит поле ПОСЛЕ правки — то, что человек увидит; сравнение идёт по Edit. */
const applied = (text, edit) =>
  edit ? text.slice(0, edit.start) + edit.text + text.slice(edit.end) : '—';

function row(id, note, run, want, input) {
  let got = null;
  let err = '';
  try {
    got = run();
    // `null` — ЗАКОННЫЙ ОТВЕТ, а не промах: операция режима таблицы, которой здесь не место,
    // обязана отказаться (шапку не удалить, последний столбец не удалить, вне таблицы — ничего).
    // Без этой ветки таблица не смогла бы выразить ожидание «правки нет» вовсе.
    if (want !== null && (!got || typeof got !== 'object')) err = `вернулось ${show(got)}`;
  } catch (e) {
    err = e instanceof Error ? e.message : String(e);
  }
  const ok = !err && (want === null ? got === null : same(got, want));
  if (ok) pass += 1;
  else { fail += 1; failed.push(id); }
  console.log(`${ok ? '  ok  ' : '  FAIL'} ${id} ${note}`);
  if (!ok) {
    console.log(`        ждали  ${show(want)}`);
    console.log(`        имеем  ${err ? `ОШИБКА: ${err}` : show(got)}`);
    if (!err && input != null) {
      console.log(`        текст после правки: ${show(applied(input, got))}`);
    }
  }
}

