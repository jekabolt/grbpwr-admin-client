import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'prettier';

export const SIZE_CHART_ICON_FILES = [
  'tops.json',
  'outerwear.json',
  'bottoms.json',
  'footwear.json',
  'accessories.json',
];

const scriptDir = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_OUTPUT = resolve(scriptDir, '../src/lib/pom/size-chart-icons.ts');

function number(value, field, key) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`${key}.${field} must be a number`);
  }
  return value;
}

function lineOf(line, iconKey, index) {
  const key = `${iconKey}.lines[${index}]`;
  if (!line || typeof line !== 'object') throw new Error(`${key} must be an object`);
  const name = line.name === 'front-rise' ? 'rise' : line.name;
  if (typeof name !== 'string' || !name.trim()) throw new Error(`${key}.name must be a string`);

  if (line.type === 'horizontal') {
    return {
      type: 'horizontal',
      name,
      y: number(line.y, 'y', key),
      xStart: number(line.xStart, 'xStart', key),
      xEnd: number(line.xEnd, 'xEnd', key),
    };
  }
  if (line.type === 'vertical') {
    const out = {
      type: 'vertical',
      name,
      x: number(line.x, 'x', key),
      yStart: number(line.yStart, 'yStart', key),
      yEnd: number(line.yEnd, 'yEnd', key),
    };
    if (line.view === 'diagonal') {
      out.view = 'diagonal';
      out.xEnd = number(line.xEnd, 'xEnd', key);
    }
    return out;
  }
  throw new Error(`${key}.type must be horizontal or vertical`);
}

function iconOf(icon, key) {
  if (!icon || typeof icon !== 'object') throw new Error(`${key} must be an object`);
  if (typeof icon.label !== 'string' || !icon.label.trim()) {
    throw new Error(`${key}.label must be a string`);
  }
  if (typeof icon.vb !== 'string' || icon.vb.trim().split(/\s+/).length !== 4) {
    throw new Error(`${key}.vb must be a viewBox`);
  }
  if (typeof icon.inner !== 'string' || !icon.inner.includes('<g')) {
    throw new Error(`${key}.inner must be SVG markup`);
  }
  if (!Array.isArray(icon.lines)) throw new Error(`${key}.lines must be an array`);
  return {
    label: icon.label,
    viewBox: icon.vb,
    inner: icon.inner.replaceAll('#000', 'currentColor'),
    lines: icon.lines.map((line, index) => lineOf(line, key, index)),
  };
}

export async function loadIconCatalog(inputDir) {
  const catalog = {};
  for (const file of SIZE_CHART_ICON_FILES) {
    const source = JSON.parse(await readFile(resolve(inputDir, file), 'utf8'));
    if (!source || Array.isArray(source) || typeof source !== 'object') {
      throw new Error(`${file} must contain an object`);
    }
    for (const [key, icon] of Object.entries(source)) {
      if (catalog[key]) throw new Error(`duplicate icon key: ${key}`);
      catalog[key] = iconOf(icon, key);
    }
  }
  return catalog;
}

export function renderIconModule(catalog) {
  return `// Generated by scripts/gen-size-chart-icons.mjs. Do not edit by hand.\n\nexport type SizeChartIconLine =\n  | { type: 'horizontal'; name: string; y: number; xStart: number; xEnd: number }\n  | {\n      type: 'vertical';\n      name: string;\n      x: number;\n      yStart: number;\n      yEnd: number;\n      view?: 'diagonal';\n      xEnd?: number;\n    };\n\nexport type SizeChartIcon = {\n  label: string;\n  viewBox: string;\n  inner: string;\n  lines: SizeChartIconLine[];\n};\n\nexport const SIZE_CHART_ICONS: Record<string, SizeChartIcon> = ${JSON.stringify(catalog, null, 2)};\n`;
}

export async function generateSizeChartIcons(inputDir, outputPath = DEFAULT_OUTPUT) {
  const catalog = await loadIconCatalog(resolve(inputDir));
  const source = await format(renderIconModule(catalog), {
    parser: 'typescript',
    semi: true,
    tabWidth: 2,
    printWidth: 100,
    singleQuote: true,
    trailingComma: 'all',
  });
  await writeFile(outputPath, source);
  return catalog;
}

const isMain = process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  const inputDir = process.argv[2];
  if (!inputDir) {
    console.error('Usage: node scripts/gen-size-chart-icons.mjs <dir-with-json>');
    process.exitCode = 1;
  } else {
    const catalog = await generateSizeChartIcons(inputDir);
    console.log(`Generated ${Object.keys(catalog).length} icons in ${DEFAULT_OUTPUT}`);
  }
}
