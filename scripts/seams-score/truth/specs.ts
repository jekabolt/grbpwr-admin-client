// TRUTH seam specs for the seam-inference MEASUREMENT (yarn seams:score) — TEST DATA, never product
// data. For every prod card the corpus stand reads (prod ids) and beta card 49: every seam that is
// physically sewn, in the graph's edge ids of today's segmentation at the size the live app reads
// (DXF block NAMES — the runner maps them to the card's line keys), with how each row was derived
// (the technologist's order in the archive + the geometry + the notches), a confidence and a class.
// `yarn seams:score build` turns them into StoredSeam rows (truth/<id>.seams.json); `… sheet` draws
// them on the flat pieces (<metrics>/truth/<id>-flat-edges.png) — every row is checked there by eye.
//
// Rows: confirmed (default) = sewn; status 'rejected' = a pair the engine tends to sew that is NOT
// sewn (two hems, two cuffs, a vent, a dart's two sides); kind 'closure' = an opening closed by
// buttons / a fly, not a seam (neutral when drawn shut). A side is an edge id ('FP_L#2'), a chain
// ('BP#3+4') or an array (a composite: one edge ↔ several pieces, in walk order); a part may carry
// its sewn stretch in mm ('BP_L#1@0-99').
//   bucket  main (default) = the garment's seams, scored for precision / recall; ply = the bagging of
//           two-ply parts (collar, stand, cuff, flap) and the plies' share of a sandwich — the doll
//           draws plies as layers, so these are counted apart; lining = the lining (the doll reads
//           the shell only).
//   anyOf   rows of one group are readings of ONE physical seam (a sandwich: the back is sewn to
//           the yoke AND its ply in one seam — the yoke row, the ply row or the two plies' edges
//           paired all say it); one found is enough, none found is one miss.
//   pattern interchangeable identical panels (a bag's 16 triangles): regexes over `name#k` with a
//           count of seams; any pairing that fits counts, up to the count.
//
// Conventions read off the files (not assumed): pieces are drawn FACE UP — a back's drawing-left is
// the wearer's left; a front whose centre-front edge is on its left is the wearer's left front
// (checked on SS26-005, the one asymmetric body, by its notches). The engine pairs every symmetric
// shoulder CROSSED (BP#3 ↔ FRONT_L#1); the truth uncrosses them.
//
// The six garment cards 4 / 5 / 6 / 7 / 11 / 16 carry the gold rows of scripts/doll/gold/specs.ts
// (checked on p4-gold/*.png), re-keyed by prod id, classed, and extended with the plies, pockets,
// flies and vents the gold left out; the others were derived here from the archives' orders.

export type Confidence = 'sure' | 'likely' | 'unsure';
export type Bucket = 'main' | 'ply' | 'lining';

export type TruthSeam = {
  a?: string | string[];
  b?: string | string[];
  /** Default edge (composite when a side has 2+ parts). */
  kind?: 'edge' | 'partial' | 'closure';
  /** Default confirmed. rejected = NOT sewn (hems, two cuffs …) — a wrong pairing when predicted. */
  status?: 'confirmed' | 'rejected';
  /** Partial (or a closure over part of an edge): sewn sub-range of each run, mm from its start. */
  rangeMm?: { a: [number, number]; b: [number, number] };
  /** The seam class the error tables group by: shoulder, armhole, side, inseam, waistband, cuff … */
  cls: string;
  /** Default sure. */
  confidence?: Confidence;
  /** Default main. */
  bucket?: Bucket;
  /** Readings of one physical seam share a tag. */
  anyOf?: string;
  /** Interchangeable identical panels: regexes over `name#k`, and how many such seams there are. */
  pattern?: { a: string; b: string; count: number; self?: boolean };
  /** How the row was derived, in words. */
  why: string;
};

